%% TP_manual_setup.m — 수동 조종 실습의 설정값 (오프라인 · VRX 공용)
%
%   모델의 InitFcn(TP_manual_init)이 Run 을 누를 때마다 이 파일을 돌린다.
%   그래서 **값은 이 파일에서 고친다.** 명령창에서 고친 값은 다음 Run 에 덮인다.
%
%   좌표 규약 (과목 공통)
%     NED — 북이 x, 동이 y.  코드 이름은 x_n(북) · y_n(동).  psi 는 북에서 시계방향 +
%     N 은 요 모멘트에만 쓴다

%% 1. 시간
Ts_tp    = 0.05;        % 제어·통신 주기 [s] (20 Hz — GPS 가 약 20 Hz 로 온다)
T_end_tp = 900;         % 최대 실행 시간 [s]. 그 전에 Stop 을 누르면 된다

%% 2. 월드 원점 — 3·15 해양누리공원 앞 수역 (TP_haeyang/haeyang_points.m 과 같은 값)
lat0_tp = 35.1862095;   % [deg]  가제보 ENU 원점 (동 0 · 북 0) 의 위도
lon0_tp = 128.5665903;  % [deg]  경도

%% 3. 버튼 하나가 요구하는 힘 — 여기를 바꾸면 배의 빠르기가 바뀐다
%     버튼은 0 또는 1 이다. 눌린 버튼에 아래 값을 곱해 요구 힘 X · Y · N 을 만든다
X_btn = 400;            % 전진·후진 버튼의 전후력 [N]    (좌·우 추진기에 200 N 씩)
Y_btn = 200;            % 횡이동 버튼의 횡력 [N]         (선수추진기 200 N)
N_btn = 400;            % 선회 버튼의 요 모멘트 [N m]    (좌·우 추진기 ±195 N)

%% 4. 추진기 배치와 한계 — 6주차 W06_setup.m 5절과 같은 값
half_beam = 1.027135;   % 선미 좌·우 추진기의 좌우 반폭 b [m]
l_bow     = 0.75;       % 선수추진기의 x 위치 l3 [m] (선체 중심에서 앞으로)
F_max     = 500;        % 선미 추진기 추력 한계 [N]
F_bow_max = 250;        % 선수추진기 추력 한계 [N]
alloc_prm = [half_beam; l_bow; F_max; F_bow_max];

%% 5. 선체 계수 — 오프라인 운동모델만 쓴다 (6주차 W06_setup.m 7절과 같은 값)
m_usv = 226.5;   Izz = 653;
Xu = 100;  Xuu = 150;
Yv = 100;  Yvv = 100;
Nr = 800;  Nrr = 800;
usv_p = [m_usv; Izz; Xu; Xuu; Yv; Yvv; Nr; Nrr; half_beam; l_bow];

%   오프라인 출발 상태 s = [u v r x_n y_n psi] — 출발선 (북 -32, 동 0), 선수 북
x0_tp = [0; 0; 0; -32; 0; 0];

%% 6. GPS 안테나 자리 — 선체 중심에서 뒤로 0.85 m (요구조건 7-1 절 실측)
%     GPS 가 내는 것은 안테나의 위치다. 선수각만큼 돌린 이 거리를 더해야 선체 중심이 된다
d_gps = 0.85;           % [m]

%% 7. GCS 화면
animate       = 1;      % 1 = GCS 를 띄운다, 0 = 띄우지 않는다
animate_every = 0.25;   % 다시 그리는 간격 [s]. 느린 PC 는 0.5 로 올린다
gcs_window    = 120;    % 오른쪽 그래프에 보이는 시간 폭 [s]
boat_scale    = 3.0;    % 지도 위 선체 확대 배율 (1 = 실제 크기, 전장 4.9 m)
gcs_view      = [-105 50 -130 45];   % 지도에 보이는 범위 [북최소 북최대 동최소 동최대] [m] — 남서쪽에 공원 호안이 들어온다
basemap_name  = 'satellite';   % 인터넷이 없으면 자동으로 다음 지도로 넘어간다

%   위치유지 판정 (요구조건 3-2 절) — 5 m 이내 · 0.1 m/s 이하 · 5 초
hold_radius = 5.0;      % [m]
hold_speed  = 0.1;      % [m/s]
hold_time   = 5.0;      % [s]

%% 8. ROS
ros_domain_id = '7';    % WSL 에서 가제보를 띄울 때 준 ROS_DOMAIN_ID 와 같아야 한다
