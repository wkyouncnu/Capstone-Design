% W10_SETUP  10주차 실습 설정 — 이 파일만 고치면 된다.
%
%   틸팅(방위) 추진기 · 추력 배분 · 동적위치유지(DP)
%
%   >> W10_setup
%   >> open_system('W10_0_offline')      % 실습 A — 오프라인 DP
%   >> open_system('W10_1_vrx')          % 실습 B — Gazebo 연동
%
%   9주차까지와 달라지는 것
%     - 후방 추진기 2기가 좌우로 ±45° 돌아간다 (방위추진기, azimuth thruster)
%     - 입력이 2개에서 4개로 늘어난다 -> 배분(allocation) 문제가 생긴다
%     - 3자유도가 모두 제어 가능해진다 -> 제자리 유지(DP)가 가능해진다

clear; clc;

%% ====================================================================
%  1. 추진기 배치 — VRX WAM-V 후방 2기
%     출처: wamv_aft_thrusters.xacro
%       left  : (-2.373776, +1.027135)
%       right : (-2.373776, -1.027135)
%     회전 관절: wamv/{left,right}_chassis_engine_joint (revolute, 축 z)
%     VRX 자체 한계는 ±pi 이지만, 실제 WAM-V 하드웨어와 참고 문헌을 따라
%     ±45° 로 제한해서 쓴다. 이 제한이 배분 문제를 의미 있게 만든다.
% =====================================================================
thr_x   = -2.373776;        % 추진기 전후 위치 [m] (선미쪽이 음수)
thr_y   =  1.027135;        % 좌우 반폭 [m]
del_max = deg2rad(45);      % 방위각 한계 [rad]
del_rate= deg2rad(30);      % 방위각 최대 각속도 [rad/s] — 서보 한계
tau_del = 0.20;             % 방위 서보 1차 지연 [s]

%% ====================================================================
%  2. 확장 추력 배분 행렬  tau = T_e * f
%     f = [FxL FyL FxR FyR]'  (선체 좌표계 성분)
%     각 추진기의 힘을 극좌표(T, delta) 대신 직교 성분으로 두는 것이
%     핵심이다. 그러면 T_e 가 상수가 되어 유사역행렬을 미리 구해 둘 수 있다.
%       X = FxL + FxR
%       Y = FyL + FyR
%       N = (x*FyL - y_L*FxL) + (x*FyR - y_R*FxR)
%
%     부호 주의 — NED 선체계에서 y 는 **우현**이 양수다.
%     Gazebo 의 left 엔진은 ENU 선체계에서 y = +1.027 (좌현) 이므로
%     NED 로는 y_L = -1.027, y_R = +1.027 이다.
%     이 부호를 뒤집으면 요 되먹임이 반대가 되어 DP 가 선수를 못 잡는다.
% =====================================================================
y_L = -thr_y;   y_R = +thr_y;

T_e = [     1,      0,      1,      0 ;
            0,      1,      0,      1 ;
         -y_L,  thr_x,   -y_R,  thr_x ];

% 확인: 방위각 0 이면 N = (F_L - F_R)*b 가 되어야 한다 (7~9주차와 같은 식)
assert(abs(T_e(3,1) - thr_y) < 1e-9 && abs(T_e(3,3) + thr_y) < 1e-9, ...
       'T_e 의 요 행 부호가 7~9주차 차동추진 식과 어긋납니다.');

T_pinv = pinv(T_e);         % 4x3. ||f||^2 를 최소로 하는 해

% 섹터 한계를 벗어난 요구를 어떻게 처리할 것인가
%   1 = 불감대 (연구실 자산 WAMV_USV_Control_Allocation.m 방식)
%   2 = 섹터 경계로 클램프 후 유효 성분만 사용
alloc_mode = 2;
fprintf('T_e 계급 = %d  (3 이면 3자유도 모두 제어 가능)\n', rank(T_e));

%% ====================================================================
%  3. 추진기 성능 — 7~9주차와 같은 값
% =====================================================================
F_max  = 500;               % 추진기 1기당 추력 한계 [N]
k_prop = 1000 * 0.004422 * 0.2^4;   % 0.0070752 [N/(rad/s)^2]
n_max  = sqrt(F_max / k_prop);
tau_n  = 0.30;              % 모터 시상수 [s]

%% ====================================================================
%  4. DP 제어 게인 — 3자유도 PID
%     tau = -J'(psi) * [ Kp*eta_e + Ki*∫eta_e ] - Kd*nu
%     eta_e 는 NED 기준 오차, nu 는 선체 기준 속도다.
%     회전행렬 J' 로 NED 오차를 선체 힘으로 바꾼다.
% =====================================================================
%     게인은 "DP 대역폭" 으로 정한다.
%       위치 : w_n = sqrt(Kp/m)        -> 50/211  -> 0.49 rad/s
%       선수 : w_n = sqrt(Kp/Izz)      -> 160/653 -> 0.49 rad/s
%     이 대역폭은 파랑 주파수(2.09 rad/s)보다 충분히 낮아야 한다.
%     그래야 파랑 필터(1.2 rad/s)를 끼워 넣어도 위상 여유가 남는다.
Kp_dp = diag([   50,    50,   160 ]);   % [N/m, N/m, N·m/rad]
Kd_dp = diag([  110,   110,   200 ]);   % [N/(m/s), N/(m/s), N·m/(rad/s)]
Ki_dp = diag([    5,     5,    16 ]);   % 정상 외란(바람)을 지우는 항
i_max = [ 200; 200; 400 ];              % 적분항 포화 (안티와인드업)

%% ====================================================================
%  5. DP 목표값 시나리오
%     mode 0 : 고정 목표 (제자리 유지)
%     mode 1 : 4단계 시나리오 — 전진 / 횡이동 / 선수 회전 / 복귀
% =====================================================================
dp_mode = 1;

dp_N0   = 0;      dp_E0   = 0;     dp_PSI0 = deg2rad(0);   % 시작 목표

% 기준모델 — 계단 목표를 배가 실제로 낼 수 있는 궤적으로 바꾼다
dp_ref_on = 1;
dp_vmax   = [0.5; 0.5; deg2rad(8)];    % 목표점 최대 이동 속도 [m/s, m/s, rad/s]
tau_ref   = 6;                          % 목표 근처에서의 접근 시상수 [s]
% 한 번에 한 가지씩만 시킨다. 두 가지를 동시에 시키면 어떻게 되는지는 과제 ⑤.
dp_step = [  0    0     0    0 ;   % t [s]  N [m]  E [m]  psi [deg]   제자리 유지
            60   10     0    0 ;   %                                 전진 10 m
           140   10    15    0 ;   %                                 횡이동 15 m
           220   10    15   45 ;   %                                 제자리 선수 45도
           300   10    15    0 ];  %                                 선수 복귀

%% ====================================================================
%  6. 외란 — 바람과 파랑
%     바람: Jin 외(2025) 식 (11)~(19), Fossen(2011) 8.1절
%     파랑: Bretschneider 스펙트럼에서 뽑은 조화합 근사
%
%     주의 — 아래 면적·계수는 문헌의 통상값을 쓴 **가정값**이다.
%     VRX 에서 측정한 값이 아니다. 절대값보다 경향을 보는 데 쓴다.
% =====================================================================
wind_on    = 1;
wind_speed = 6.0;              % 참풍속 [m/s]
wind_dir   = deg2rad(45);      % 참풍향 [rad, NED. 바람이 불어오는 쪽]

rho_air = 1.225;               % 공기 밀도 [kg/m^3]
A_Fw    = 1.5;                 % 정면 투영 면적 [m^2]   (가정값)
A_Lw    = 3.0;                 % 측면 투영 면적 [m^2]   (가정값)
L_oa    = 4.9;                 % 전장 [m]
c_x = 0.70;  c_y = 0.85;  c_n = 0.12;    % 풍력 계수 (문헌 범위 중앙값)

filt_on   = 1;            % 파랑 필터 켜기/끄기
w_filt    = 1.20;         % 저역통과 차단 주파수 [rad/s]
                          %   DP 대역폭 0.49 < w_filt 1.20 < 파랑 2.09
                          %   너무 낮추면 위상 지연으로 요 루프가 진동한다

wave_on   = 1;
Hs        = 0.30;              % 유의파고 [m]
Tp        = 3.0;               % 첨두주기 [s]
wave_dir  = deg2rad(45);       % 파향 [rad, NED]
k_wave    = 900;               % 파고 -> 파랑력 환산 이득 [N/m]  (가정값)
n_wave    = 5;                 % 조화 성분 개수
lw_arm    = 1.2;               % 파랑 요모멘트 팔길이 [m]        (가정값)

% --- Bretschneider 스펙트럼에서 성분 진폭을 뽑는다 -------------------
w0    = 2*pi/Tp;
wmin  = 0.5*w0;  wmax = 2.5*w0;
w_i   = linspace(wmin, wmax, n_wave)';
dw    = (wmax - wmin)/(n_wave - 1);
S_i   = (1.25/4) * (w0.^4) .* (Hs^2) ./ (w_i.^5) .* exp(-1.25*(w0./w_i).^4);
A_i   = sqrt(2*S_i*dw);                 % 성분 파고 [m]
rng(7);  phi_i = 2*pi*rand(n_wave,1);   % 위상 (고정 시드 -> 재현 가능)
wave_par = [w_i, A_i, phi_i];

fprintf('파랑: Hs %.2f m, Tp %.1f s -> 성분 %d개, 합성 진폭 %.3f m\n', ...
        Hs, Tp, n_wave, sum(A_i));

%% ====================================================================
%  7. 오프라인 플랜트 계수 — 7~9주차와 같은 값 (Gazebo VRX 와 동일)
% =====================================================================
m_usv  = 211;    Izz = 653;
Xu = 100;  Xuu = 150;
Yv = 100;  Yvv = 100;
Nr = 800;  Nrr = 800;

plant_par = [m_usv; Izz; Xu; Xuu; Yv; Yvv; Nr; Nrr];

%% ====================================================================
%  8. 실시간 그림
% =====================================================================
animate       = 1;
animate_every = 0.25;
boat_scale    = 2;

%% ====================================================================
%  9. VRX 스폰 위치
% =====================================================================
origin_north =  200;
origin_east  = -532;

%% ====================================================================
%  10. 자동 계산
% =====================================================================
Ts_ctrl = 0.05;
x0 = [0; 0; 0; 0; 0; 0];      % [u v r N E psi]'
T_end = 360;

fprintf('W10 설정 완료\n');
fprintf('  방위각 한계 ±%.0f deg, 각속도 한계 %.0f deg/s\n', ...
        rad2deg(del_max), rad2deg(del_rate));
fprintf('  추력 한계 %g N/기,  DP 시나리오 mode %d\n', F_max, dp_mode);
if wind_on
    fprintf('  바람 %.1f m/s @ %.0f deg\n', wind_speed, rad2deg(wind_dir));
else
    fprintf('  바람 없음\n');
end
if wave_on
    fprintf('  파랑 Hs %.2f m, Tp %.1f s @ %.0f deg\n', Hs, Tp, rad2deg(wave_dir));
else
    fprintf('  파랑 없음\n');
end

%% ====================================================================
%  11. 바로 실행
% =====================================================================
auto_run = 1;
skip_run = getappdata(0, 'W10_skip_run');
if isempty(skip_run), skip_run = false; end
setappdata(0, 'W10_skip_run', false);

if auto_run && ~skip_run
    fprintf('\n오프라인 DP 모델 실행 중 (auto_run = 0 으로 두면 실행하지 않는다)\n');
    load_system('W10_0_offline');
    out = sim('W10_0_offline');
    W10_plot(out, '오프라인 DP');
end
