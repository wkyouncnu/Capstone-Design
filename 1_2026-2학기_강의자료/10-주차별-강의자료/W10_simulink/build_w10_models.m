'eta  = [pn; pe; psi];'                                                     newline ...
'nu   = [u; v; r];'                                                         newline ...
'U    = sqrt(u*u + v*v);'                                                   newline ...
'beta = atan2(v, u);']);
    set_param([m '/Nav'],'Position',[2180 670 2350 890]);

