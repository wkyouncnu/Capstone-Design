% 1.5단 · 파랑 필터
% =====================================================================
function addWaveFilter(m, x, y)
    ss = [m '/WaveFilter'];
    add_block('built-in/Subsystem', ss, 'Position', [x y x+170 y+140]);

    in = {'eta','nu','pre','par'};
    for k = 1:numel(in)
        add_block('simulink/Sources/In1', [ss '/' in{k}], ...
                  'Position',[40 60+(k-1)*70 75 90+(k-1)*70], 'Port', num2str(k));
    end

    setFcn(ss, 'Filt', [ ...
'function [eta_f, nu_f, snew] = Filt(eta, nu, pre, par)'                 newline ...
'%#codegen'                                                              newline ...
'% Wave filtering for dynamic positioning.'                              newline ...
'%'                                                                      newline ...
'% First order wave loads make the vessel oscillate at the wave'         newline ...
'% frequency. That motion cannot be counteracted — trying to do so'      newline ...
'% only wears out the thrusters. A DP system therefore feeds the'        newline ...
'% controller with the LOW FREQUENCY part of the motion only.'           newline ...
'% Fossen (2011) 11.4.1 uses a passive observer; here a first order'     newline ...
'% low pass with a cut-off well below the wave frequency is enough to'   newline ...
'% show the effect.'                                                     newline ...
'%'                                                                      newline ...
'% par = [on; wf; Ts]'                                                   newline ...
''                                                                       newline ...
'on = par(1); wf = par(2); Ts = par(3);'                                 newline ...
'z  = [eta; nu];'                                                        newline ...
'if on < 0.5'                                                            newline ...
'    eta_f = eta;  nu_f = nu;  snew = z;'                                newline ...
'    return'                                                             newline ...
'end'                                                                    newline ...
'a = Ts*wf/(1 + Ts*wf);'                                                 newline ...
'snew = pre + a*(z - pre);'                                              newline ...
'% heading must be filtered on the difference, not the raw angle'        newline ...
'd3 = atan2(sin(eta(3) - pre(3)), cos(eta(3) - pre(3)));'                newline ...
'snew(3) = pre(3) + a*d3;'                                               newline ...
'snew(3) = atan2(sin(snew(3)), cos(snew(3)));'                           newline ...
'eta_f = snew(1:3);'                                                     newline ...
'nu_f  = snew(4:6);']);
    set_param([ss '/Filt'],'Position',[220 70 400 330]);

    out = {'eta_f','nu_f','snew'};
    for k = 1:numel(out)
        add_block('simulink/Sinks/Out1', [ss '/' out{k}], ...
                  'Position',[500 80+(k-1)*90 535 110+(k-1)*90], 'Port', num2str(k));
        add_line(ss, sprintf('Filt/%d',k), [out{k} '/1'], 'autorouting','on');
    end
    for k = 1:numel(in)
        add_line(ss, [in{k} '/1'], sprintf('Filt/%d',k), 'autorouting','on');
    end
    Simulink.BlockDiagram.arrangeSystem(ss);
end

% =====================================================================
% 2단 · DP 제어기 (3자유도 PID)
% =====================================================================
function addDPCtrl(m, x, y)
    ss = [m '/DPCtrl'];
    add_block('built-in/Subsystem', ss, 'Position', [x y x+190 y+220]);

    in = {'eta_d','eta','nu','Ipre','par'};
    for k = 1:numel(in)
        add_block('simulink/Sources/In1', [ss '/' in{k}], ...
                  'Position',[40 60+(k-1)*70 75 90+(k-1)*70], 'Port', num2str(k));
    end

    setFcn(ss, 'PID3', [ ...
'function [tau, Inew, eta_e] = PID3(eta_d, eta, nu, Ipre, par)'          newline ...
'%#codegen'                                                              newline ...
'% 3-DOF dynamic positioning controller (Fossen 2011, 12.2.10).'         newline ...
'%'                                                                      newline ...
'%   eta   = [N; E; psi]      position and heading in NED'               newline ...
'%   nu    = [u; v; r]        velocity in BODY'                          newline ...
'%   tau   = -J(psi)'' * (Kp*eta_e + Ki*I) - Kd*nu'                      newline ...
'%'                                                                      newline ...
'% The transpose of the rotation matrix turns a NED position error into' newline ...
'% a BODY force. Damping is taken on BODY velocity directly, so no'      newline ...
'% derivative of the error is needed (same idea as the P-D heading'      newline ...
'% controller of week 7).'                                               newline ...
'%'                                                                      newline ...
'% par = [Kp(1:3); Kd(1:3); Ki(1:3); imax(1:3); Ts]'                     newline ...
''                                                                       newline ...
'Kp = par(1:3);  Kd = par(4:6);  Ki = par(7:9);'                         newline ...
'im = par(10:12); Ts = par(13);'                                         newline ...
''                                                                       newline ...
'e = eta - eta_d;'                                                       newline ...
'e(3) = atan2(sin(e(3)), cos(e(3)));      % smallest signed angle'       newline ...
''                                                                       newline ...
'psi = eta(3);'                                                          newline ...
'J = [ cos(psi), -sin(psi), 0;'                                          newline ...
'      sin(psi),  cos(psi), 0;'                                          newline ...
'             0,         0, 1];'                                         newline ...
''                                                                       newline ...
'% integral state with clamping (anti-windup)'                           newline ...
'Inew = Ipre + Ts*e;'                                                    newline ...
'for i = 1:3'                                                            newline ...
'    lim = im(i)/max(Ki(i), 1e-9);'                                      newline ...
'    if Inew(i) >  lim, Inew(i) =  lim; end'                             newline ...
'    if Inew(i) < -lim, Inew(i) = -lim; end'                             newline ...
'end'                                                                    newline ...
''                                                                       newline ...
'tau = -J'' * ( Kp.*e + Ki.*Inew ) - Kd.*nu;'                            newline ...
'eta_e = e;']);
    set_param([ss '/PID3'],'Position',[220 70 420 400]);

    out = {'tau','Inew','eta_e'};
    for k = 1:numel(out)
        add_block('simulink/Sinks/Out1', [ss '/' out{k}], ...
                  'Position',[520 80+(k-1)*90 555 110+(k-1)*90], 'Port', num2str(k));
        add_line(ss, sprintf('PID3/%d',k), [out{k} '/1'], 'autorouting','on');
    end
    for k = 1:numel(in)
        add_line(ss, [in{k} '/1'], sprintf('PID3/%d',k), 'autorouting','on');
    end
    Simulink.BlockDiagram.arrangeSystem(ss);
end

% =====================================================================
% 3단 · 추력 배분
% =====================================================================
function addAlloc(m, x, y)
    ss = [m '/Alloc'];
    add_block('built-in/Subsystem', ss, 'Position', [x y x+190 y+180]);

    in = {'tau','Tp','lim'};
    for k = 1:numel(in)
        add_block('simulink/Sources/In1', [ss '/' in{k}], ...
                  'Position',[40 60+(k-1)*80 75 90+(k-1)*80], 'Port', num2str(k));
    end

    setFcn(ss, 'Allocate', [ ...
'function [Tcmd, Dcmd, sat] = Allocate(tau, Tp, lim)'                     newline ...
'%#codegen'                                                               newline ...
'% Thrust allocation for two azimuth (rotatable) thrusters.'              newline ...
'% Fossen (2011) 12.3.4 — constrained control allocation for azimuth'     newline ...
'% thrusters, solved with the EXTENDED THRUST VECTOR.'                    newline ...
'%'                                                                       newline ...
'% Step 1  f = pinv(T_e) * tau       f = [FxL FyL FxR FyR]'''             newline ...
'%         Because the thruster force is written in Cartesian components,' newline ...
'%         T_e is CONSTANT and its pseudo-inverse can be precomputed.'    newline ...
'%         There is no singular configuration to worry about.'            newline ...
'%'                                                                       newline ...
'% Step 2  Cartesian -> polar   T = |f_i|,  delta = atan2(Fy, Fx)'        newline ...
'%'                                                                       newline ...
'% Step 3  map the demand into the mechanical sector |delta| <= 45 deg'   newline ...
'%           |d| <=  45  : use as is'                                     newline ...
'%           |d| >  135  : REVERSE thrust, d -> d -+ 180'                 newline ...
'%           otherwise   : dead zone, no thrust can be produced'          newline ...
'%'                                                                       newline ...
'% Step 4  saturate the magnitude at F_max'                               newline ...
'%'                                                                       newline ...
'% lim = [F_max; delta_max; mode]'                                        newline ...
'%   mode 1 : dead zone   — demands inside the forbidden sector are'      newline ...
'%            dropped. Simple, but the realised tau is then wrong.'       newline ...
'%   mode 2 : clamp       — the angle is pushed to the nearest sector'     newline ...
'%            edge and the magnitude is scaled by cos of the angle'       newline ...
'%            error, so the useful component is kept.'                    newline ...
''                                                                        newline ...
'f = Tp * tau;'                                                           newline ...
'Fmax = lim(1);  dmax = lim(2);  mode = lim(3);'                          newline ...
''                                                                        newline ...
'Tcmd = zeros(2,1);  Dcmd = zeros(2,1);  sat = 0;'                        newline ...
'for i = 1:2'                                                             newline ...
'    fx = f(2*i-1);  fy = f(2*i);'                                        newline ...
'    Ti = sqrt(fx*fx + fy*fy);'                                           newline ...
'    di = atan2(fy, fx);'                                                 newline ...
'    ad = abs(di);'                                                       newline ...
'    if ad <= dmax'                                                       newline ...
'        To = Ti;   Do = di;'                                             newline ...
'    elseif ad >= pi - dmax'                                              newline ...
'        To = -Ti;  Do = di - sign(di)*pi;    % reverse thrust'           newline ...
'    elseif mode < 1.5'                                                   newline ...
'        To = 0;    Do = 0;                   % dead zone'                newline ...
'        sat = sat + 1;'                                                  newline ...
'    else'                                                                newline ...
'        % clamp to the nearest edge of the reachable sector'             newline ...
'        if ad <= pi/2'                                                   newline ...
'            Do = sign(di)*dmax;      To =  Ti*cos(ad - dmax);'           newline ...
'        else'                                                            newline ...
'            Do = sign(di)*(dmax - pi);  To = -Ti*cos(pi - dmax - ad);'   newline ...
'            Do = atan2(sin(Do), cos(Do));'                               newline ...
'        end'                                                             newline ...
'        sat = sat + 1;'                                                  newline ...
'    end'                                                                 newline ...
'    if To >  Fmax, To =  Fmax; sat = sat + 1; end'                       newline ...
'    if To < -Fmax, To = -Fmax; sat = sat + 1; end'                       newline ...
'    Tcmd(i) = To;  Dcmd(i) = Do;'                                        newline ...
'end']);
    set_param([ss '/Allocate'],'Position',[220 70 420 320]);

    out = {'Tcmd','Dcmd','sat'};
    for k = 1:numel(out)
        add_block('simulink/Sinks/Out1', [ss '/' out{k}], ...
                  'Position',[520 80+(k-1)*90 555 110+(k-1)*90], 'Port', num2str(k));
        add_line(ss, sprintf('Allocate/%d',k), [out{k} '/1'], 'autorouting','on');
    end
    for k = 1:numel(in)
        add_line(ss, [in{k} '/1'], sprintf('Allocate/%d',k), 'autorouting','on');
    end
    Simulink.BlockDiagram.arrangeSystem(ss);
end

% =====================================================================
% 4단 · 추진기 (모터 + 방위 서보)
% =====================================================================
function addThrusters(m, x, y)
    ss = [m '/Thrusters'];
    add_block('built-in/Subsystem', ss, 'Position', [x y x+190 y+180]);

    in = {'Tcmd','Dcmd','Tpre','Dpre','par'};
    for k = 1:numel(in)
        add_block('simulink/Sources/In1', [ss '/' in{k}], ...
                  'Position',[40 60+(k-1)*70 75 90+(k-1)*70], 'Port', num2str(k));
    end

    setFcn(ss, 'Act', [ ...
'function [Tact, Dact, f] = Act(Tcmd, Dcmd, Tpre, Dpre, par)'            newline ...
'%#codegen'                                                              newline ...
'% Actuator dynamics of an azimuth thruster.'                            newline ...
'%   thrust  : first order lag, time constant tau_n'                     newline ...
'%   azimuth : RATE LIMIT first (servo can only turn so fast), then a'   newline ...
'%             first order lag. A real pod cannot snap to a new angle.'  newline ...
'% par = [Ts; tau_n; tau_del; rate_max]'                                 newline ...
''                                                                       newline ...
'Ts = par(1); tn = par(2); td = par(3); rmax = par(4);'                  newline ...
''                                                                       newline ...
'Tact = Tpre + (Ts/tn)*(Tcmd - Tpre);'                                   newline ...
''                                                                       newline ...
'Dact = Dpre;'                                                           newline ...
'for i = 1:2'                                                            newline ...
'    dd = Dcmd(i) - Dpre(i);'                                            newline ...
'    dd = atan2(sin(dd), cos(dd));           % shortest way round'       newline ...
'    lim = rmax*Ts;'                                                     newline ...
'    if dd >  lim, dd =  lim; end'                                       newline ...
'    if dd < -lim, dd = -lim; end'                                       newline ...
'    Dact(i) = Dpre(i) + (Ts/td)*dd;'                                    newline ...
'end'                                                                    newline ...
''                                                                       newline ...
'% back to Cartesian components in BODY'                                 newline ...
'f = [ Tact(1)*cos(Dact(1));'                                            newline ...
'      Tact(1)*sin(Dact(1));'                                            newline ...
'      Tact(2)*cos(Dact(2));'                                            newline ...
'      Tact(2)*sin(Dact(2)) ];']);
    set_param([ss '/Act'],'Position',[220 70 420 380]);

    out = {'Tact','Dact','f'};
    for k = 1:numel(out)
        add_block('simulink/Sinks/Out1', [ss '/' out{k}], ...
                  'Position',[520 80+(k-1)*90 555 110+(k-1)*90], 'Port', num2str(k));
        add_line(ss, sprintf('Act/%d',k), [out{k} '/1'], 'autorouting','on');
    end
    for k = 1:numel(in)
        add_line(ss, [in{k} '/1'], sprintf('Act/%d',k), 'autorouting','on');
    end
    Simulink.BlockDiagram.arrangeSystem(ss);
end

% =====================================================================
% 5단 · 외란 (바람 + 파랑)
% =====================================================================
function addEnv(m, x, y)
    ss = [m '/Env'];
    add_block('built-in/Subsystem', ss, 'Position', [x y x+190 y+180]);

    in = {'t','nu','psi','wpar','wvpar'};
    for k = 1:numel(in)
        add_block('simulink/Sources/In1', [ss '/' in{k}], ...
                  'Position',[40 60+(k-1)*70 75 90+(k-1)*70], 'Port', num2str(k));
    end

    setFcn(ss, 'Dist', [ ...
'function [tau_env, tau_w, tau_v] = Dist(t, nu, psi, wpar, wvpar)'       newline ...
'%#codegen'                                                              newline ...
'% Environmental loads in BODY axes.'                                    newline ...
'%'                                                                      newline ...
'% WIND  — Jin et al. (2025) Eq. (11)-(19); Fossen (2011) 8.1'           newline ...
'%   relative wind in BODY :'                                            newline ...
'%     u_rw = u - Vw cos(beta_w - psi)'                                  newline ...
'%     v_rw = v - Vw sin(beta_w - psi)'                                  newline ...
'%   q     = 0.5 rho_a Vrw^2'                                            newline ...
'%   tau_w = q * [ CX*AFw ; CY*ALw ; CN*ALw*L ]'                         newline ...
'%   CX = -cx cos(g), CY = -cy sin(g), CN = cn sin(2g)'                  newline ...
'%'                                                                      newline ...
'% WAVE  — first order approximation. Component amplitudes come from a'  newline ...
'%   Bretschneider spectrum (Jin et al. Eq. (21)-(25)); the force is'    newline ...
'%   taken proportional to the surface elevation with a single gain.'    newline ...
'%   This is an approximation, not a diffraction calculation.'           newline ...
'%'                                                                      newline ...
'% wpar  = [on; Vw; beta_w; rho_a; AFw; ALw; L; cx; cy; cn]'             newline ...
'% wvpar = [on; k_wave; theta_m; arm; w1..wn; A1..An; p1..pn]'           newline ...
''                                                                       newline ...
'u = nu(1); v = nu(2);'                                                  newline ...
'tau_w = zeros(3,1);'                                                    newline ...
'if wpar(1) > 0.5'                                                       newline ...
'    Vw = wpar(2); bw = wpar(3); rho = wpar(4);'                         newline ...
'    AF = wpar(5); AL = wpar(6); L = wpar(7);'                           newline ...
'    cx = wpar(8); cy = wpar(9); cn = wpar(10);'                         newline ...
'    urw = u - Vw*cos(bw - psi);'                                        newline ...
'    vrw = v - Vw*sin(bw - psi);'                                        newline ...
'    Vrw = sqrt(urw*urw + vrw*vrw);'                                     newline ...
'    g   = -atan2(vrw, urw);'                                            newline ...
'    q   = 0.5*rho*Vrw*Vrw;'                                             newline ...
'    tau_w = q * [ -cx*cos(g)*AF;'                                       newline ...
'                  -cy*sin(g)*AL;'                                       newline ...
'                   cn*sin(2*g)*AL*L ];'                                 newline ...
'end'                                                                    newline ...
''                                                                       newline ...
'tau_v = zeros(3,1);'                                                    newline ...
'if wvpar(1) > 0.5'                                                      newline ...
'    kw = wvpar(2); th = wvpar(3); arm = wvpar(4);'                      newline ...
'    n  = (numel(wvpar) - 4)/3;'                                         newline ...
'    zeta = 0;'                                                          newline ...
'    for i = 1:n'                                                        newline ...
'        wi = wvpar(4+i);'                                               newline ...
'        Ai = wvpar(4+n+i);'                                             newline ...
'        pi_i = wvpar(4+2*n+i);'                                         newline ...
'        zeta = zeta + Ai*sin(wi*t + pi_i);'                             newline ...
'    end'                                                                newline ...
'    rel = th - psi;                          % wave direction in BODY'  newline ...
'    Fw  = kw*zeta;'                                                     newline ...
'    tau_v = [ Fw*cos(rel); Fw*sin(rel); arm*Fw*sin(rel) ];'             newline ...
'end'                                                                    newline ...
''                                                                       newline ...
'tau_env = tau_w + tau_v;']);
    set_param([ss '/Dist'],'Position',[220 70 420 420]);

    out = {'tau_env','tau_w','tau_v'};
    for k = 1:numel(out)
        add_block('simulink/Sinks/Out1', [ss '/' out{k}], ...
                  'Position',[520 80+(k-1)*90 555 110+(k-1)*90], 'Port', num2str(k));
        add_line(ss, sprintf('Dist/%d',k), [out{k} '/1'], 'autorouting','on');
    end
    for k = 1:numel(in)
        add_line(ss, [in{k} '/1'], sprintf('Dist/%d',k), 'autorouting','on');
    end
    Simulink.BlockDiagram.arrangeSystem(ss);
end

