function build_w10_models()
% BUILD_W10_MODELS  10주차 모델 두 개를 만든다.
%
%   W10_0_offline : Gazebo 없이 도는 틸팅 추진기 + 배분 + DP
%   W10_1_vrx     : 같은 제어기를 VRX 와 연결한 것
%
%   실행 전에 반드시 >> W10_setup 을 먼저 실행할 것.
%
%   신호 흐름 (좌 -> 우)
%     DPRef -> DPCtrl -> Alloc -> Thrusters -> MotionModel(+Env) -> 로깅

    here = fileparts(mfilename('fullpath'));
    cd(here);

    if evalin('base', '~exist(''T_pinv'',''var'')')
        error('먼저 W10_setup 을 실행하십시오.');
    end

    build_offline();
    build_vrx();

    % 배치와 색을 정리한다. 선은 직선 또는 직각으로만 다시 그린다.
    slxList = dir('*.slx');
    for k = 1:numel(slxList)
        [~, mName] = fileparts(slxList(k).name);
        try, tidy_layout(mName); tidy_layout(mName); catch, end
    end

    fprintf('\n완료. 생성된 모델:\n');
    d = dir('*.slx');
    for k = 1:numel(d), fprintf('  %s\n', d(k).name); end
end

