function addAnimateA3(m, x, y)
%  실시간 그림 상자 — A3_animate.m 을 매 스텝 부른다
%
%  태그 **순서가 곧 A3_animate 의 인자 순서**다. 바꾸면 그림이 엉뚱한 값을
%  그린다 (오류는 뜨지 않는다). A3_animate.m 의 머리 주석과 함께 고칠 것.
%
%  요구 렌치와 실제 렌치를 **둘 다** 넣는 까닭
%    X_c·Y_c·N_c   제어기가 요구한 힘·모멘트 (배분기 입구)
%    X_a·Y_a·N_a   운동모델이 실제로 받은 힘·모멘트 (운동모델 출력 10~12)
%    둘을 축마다 한 칸씩 겹쳐 그린다. 벌어지는 순간이 곧 각도·추력 한계가
%    물린 순간이다. 실제 값을 그림에서 다시 계산하지 않는 것이 요점이다 —
%    두 곳에서 계산하면 식이 어긋나도 알아채지 못한다.
    tags = {'x_n','y_n','psi','psi_ref','x_ref','y_ref', ...
            'u','v','r','gate','phase', ...
            'TL','dL','TR','dR', ...
            'X_c','Y_c','N_c','X_a','Y_a','N_a'};
    add_animate_box(m, tags, 'A3_animate', '', [x y], 'Ts_ctrl');
end
