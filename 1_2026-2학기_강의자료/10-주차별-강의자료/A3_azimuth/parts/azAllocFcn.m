      'kscl = 1;'
      'if Tpk > Fmax'
      '    kscl = Fmax/Tpk;'
      '    TL = kscl*TL;'
      '    TR = kscl*TR;'
      'end'
      ''
      'function [T, d] = az_polar(Fx, Fy, dmax, rev, asat)'
