function src = azAllocFcn()
%AZALLOCFCN  아지무스 추진기 둘에 요구 렌치를 나누어 주는 함수의 본문
%
%   AzAlloc 블록(MATLAB Function)에 들어가는 코드를 문자열로 낸다.
%   배분식 전체가 **행렬 두 줄**이다 — B 를 세우고, 그 pseudo-inverse 를 곱한다.
%
%   입력  X, Y, N   요구 렌치 (제어기가 낸 값)
%         alloc     배분 방식  1 = pseudo-inverse,  2 = + null space 보정
%         p         기하·한계 묶음 (5 개)
%   출력  TL, dL, TR, dR   좌·우 추력과 방향각
%
%   실제 렌치(tau_a) 계산은 **운동모델 안**에 있다 (parts/addMotionModelXYN.m).
%   배분기는 추진기 명령까지만 낸다.

src = strjoin({
  'function [TL, dL, TR, dR] = AzAlloc(X, Y, N, alloc, p)'
  '%#codegen'
  '%  아지무스 추진기 둘에 요구 렌치를 나누어 준다'
  '%'
  '%  == 입력 =============================================================='
  '%    X      요구 전후 힘   [N]      선수 방향(+앞)'
  '%    Y      요구 횡 힘     [N]      우현 방향(+오른쪽)'
  '%    N      요구 요 모멘트 [N m]    시계 방향(+우선회)'
  '%    alloc  배분 방식 [-]           1 = pseudo-inverse'
  '%                                   2 = pseudo-inverse + null space 보정'
  '%    p      기하·한계 묶음 (A3_setup.m 의 az_prm)'
  '%      p(1) = b     반폭        [m]    중심선에서 추진기까지'
  '%      p(2) = L     거리        [m]    무게중심에서 추진기까지 (뒤쪽)'
  '%      p(3) = Fmax  추력 한계   [N]    한 대 기준'
  '%      p(4) = dmax  각도 한계   [rad]'
  '%      p(5) = rev   추력 반전   [-]    1 = 허용, 0 = 금지'
  '%'
  '%  == 출력 =============================================================='
  '%    TL, TR   좌·우 추력   [N]    양수면 노즐이 보는 쪽으로 민다'
  '%    dL, dR   좌·우 각도   [rad]  선수 기준, 우현 쪽이 +'
  '%'
  '%  == 왜 추력과 각도를 바로 풀지 않는가 ================================'
  '%    추진기 한 대의 힘은 극좌표 (T, d) 로 쓰면 비선형이다'
  '%        Fx = T cos(d),   Fy = T sin(d)'
  '%    그래서 추력과 각도를 묶어 **직교 성분 넷**을 미지수로 둔다'
  '%        ue = [Fx_L; Fy_L; Fx_R; Fy_R]        (확장 추력 벡터)'
  '%    이렇게 두면 요구 렌치와의 관계가 **완전한 선형식**이 된다'
  '%        B ue = tau,   tau = [X; Y; N]'
  '%    B 의 각 열은 "그 성분 1 N 이 렌치에 얼마를 보태는가" 이다'
  '%    풀고 난 뒤에 극좌표로 되돌리면 추력과 각도가 나온다 (3 단계)'
  '%    이 방식은 Sarda 등 [1] 6 절이 실제 WAM-V 에 쓴 것과 같다'
  '%'
  '%  == 해가 하나가 아니다 ================================================'
  '%    미지수 4 개, 식 3 개 — 같은 렌치를 내는 해가 **직선 하나**를 이룬다'
  '%      alloc = 1   그 직선에서 원점에 가장 가까운 점 (pseudo-inverse)'
  '%      alloc = 2   각도 한계를 지키는 점으로 직선 위를 미끄러진다'
  '%    직선의 방향 n = [0; 1; 0; -1] 은 좌우 횡력만 주고받는 꼴이라'
  '%    얼마를 더해도 X, Y, N 이 한 톨도 변하지 않는다 (B n = 0)'
  '%'
  '%  == 참고 문헌 =========================================================='
  '%    [1] Sarda, Qu, Bertaska, von Ellenrieder (2016)'
  '%        "Station keeping control of an unmanned surface vehicle exposed'
  '%         to current and wind disturbances", Ocean Engineering 127, 305-324'
  '%        6 절 — 아지무스 WAM-V 의 확장 추력 벡터와 pseudo-inverse 배분'
  '%    [2] Sordalen (1997) "Optimal thrust allocation for marine vessels",'
  '%        Control Engineering Practice 5(9), 1223-1231 — null space 이용'
  '%    [3] Fossen (2021) "Handbook of Marine Craft Hydrodynamics and Motion'
  '%        Control", 2nd ed., 11 장 — 배분 행렬과 pseudo-inverse 일반론'
  ''
  'b = p(1);  L = p(2);  Fmax = p(3);  dmax = p(4);  rev = p(5);'
  ''
  'tau = [X; Y; N];'
  ''
  '%  배분 행렬 — 열 하나가 성분 하나의 몫이다'
  '%    1 행 전후 · 2 행 횡 · 3 행 요 모멘트'
  '%    좌현은 (x, y) = (-L, -b), 우현은 (-L, +b) 에 앉는다'
  'B = [ 1,  0,  1,  0; ...'
  '      0,  1,  0,  1; ...'
  '      b, -L, -b, -L];'
  ''
  '%  === 1 단계. pseudo-inverse — 크기가 가장 작은 해 ==================='
  '%    ue = B'' (B B'')^-1 tau.  해의 직선에서 원점에 가장 가까운 점이다'
  'ue = B'' * ((B*B'') \ tau);'
  ''
  '%  === 2 단계. null space 보정 (alloc = 2) ============================'
  '%    각도 한계는 |Fy| <= tan(dmax) |Fx| 와 같은 말이다.'
  '%    ue + lam*n 을 넣으면 lam 에 대해 1 차식이라 허용 구간이 바로 나온다'
  'if alloc > 1.5'
  '    nz = [0; 1; 0; -1];'
  '    td = tan(dmax);'
  '    lo = max(-td*abs(ue(1)) - ue(2),  ue(4) - td*abs(ue(3)));'
  '    hi = min( td*abs(ue(1)) - ue(2),  ue(4) + td*abs(ue(3)));'
  '    if lo <= hi'
  '        lam = min(max(0, lo), hi);     % 구간 안에서 0 에 가장 가까운 값'
  '    else'
  '        lam = (lo + hi)/2;             % 구간이 비면 가운데 — 덜 넘긴다'
  '    end'
  '    ue = ue + lam*nz;'
  'end'
  ''
  '%  === 3 단계. 극좌표로 되돌리고 한계 안으로 넣는다 ==================='
  '[TL, dL] = az_polar(ue(1), ue(2), Fmax, dmax, rev);'
  '[TR, dR] = az_polar(ue(3), ue(4), Fmax, dmax, rev);'
  ''
  ''
  'function [T, d] = az_polar(Fx, Fy, Fmax, dmax, rev)'
  '%  직교 성분 둘 -> 추력 하나와 각도 하나'
  'T = hypot(Fx, Fy);'
  'd = atan2(Fy, Fx);'
  ''
  '%  뒤쪽을 보라는 요구는 **앞을 보고 역추력** 으로 바꿔 쓴다 (같은 힘)'
  'if abs(d) > pi/2'
  '    d = d - sign(d)*pi;'
  '    T = -T;'
  'end'
  ''
  '%  역추력을 금지했으면 되돌린다 — 각도가 한계를 넘게 된다 (A3-4 실습)'
  'if rev < 0.5 && T < 0'
  '    T = -T;'
  '    d = d + sign(d + (d==0))*pi;'
  '    if d >  pi, d = d - 2*pi; end'
  '    if d < -pi, d = d + 2*pi; end'
  'end'
  ''
  '%  한계 — 각도와 추력을 각각 한 줄로 깎는다'
  '%    깎인 만큼이 "못 낸 힘" 으로 남아 운동모델 쪽 기록에 숫자로 보인다'
  'd = max(min(d,  dmax), -dmax);'
  'T = max(min(T,  Fmax), -Fmax);'
  }, newline);
end
