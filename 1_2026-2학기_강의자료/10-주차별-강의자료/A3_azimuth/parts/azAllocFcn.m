function src = azAllocFcn()
% azAllocFcn — 아지무스 추력 배분 MATLAB Function 의 본문 (글자만 내놓는다)
%
%   6주차의 allocFcn 과 역할은 같다. 다른 것은 추진기 수와 미지수다.
%     6주차   추진기 셋 · 방향 고정 -> 미지수 셋 (FL, FR, FB)
%     부록 A3 추진기 둘 · 방향 가변 -> 미지수 넷 (크기 둘 + 각도 둘)
%
%   각도가 미지수로 들어가면 식이 비선형이 된다. 그래서 **확장 추력 벡터**로
%   한 번 펴 놓고 (각도 대신 x·y 성분을 미지수로 삼는다) 선형으로 풀고,
%   마지막에 크기·각도로 되돌린다. 자세한 유도는 강의자료 1-3 절에 있다.
    src = strjoin({
      'function [TL, dL, TR, dR, kscl] = AzAlloc(X, Y, N, p)'
      '%#codegen'
      '%  아지무스 추력 배분 — 요구 힘·모멘트를 추진기 두 대의 (크기, 각도) 로 나눈다.'
      '%'
      '%  들어오는 것    X 전후력 [N] · Y 횡력 [N] · N 요 모멘트 [N m]  (모두 선체고정)'
      '%  나가는 것      TL·TR 추력 [N] · dL·dR 방향각 [rad] · kscl 축소 배율 [-]'
      '%'
      '%  p = [b; L; Fmax; dmax; rev; split; alloc]'
      '%    b     half_beam  중심선에서 추진기까지의 반폭 [m]'
      '%    L     l_thr      무게중심에서 추진기까지, 뒤쪽으로 [m]'
      '%    Fmax  추진기 한 대의 추력 한계 [N]'
      '%    dmax  방향각 한계 [rad]  (본 부록의 설계 전제는 45 deg)'
      '%    rev   1 이면 뒤로 미는 것(음수 추력)을 허용, 0 이면 금지'
      '%    split 1 이면 영공간 보정을 켠다 (아래 1-1 단계), 0 이면 수도인버스 그대로'
      '%    alloc 배분 방식 — 0 공통 각도 · 1 수도인버스 · 2 수도인버스+영공간'
      '%'
      '%  --- 배분 방식 세 가지는 "같은 선 위의 다른 점" 이다 ---'
      '%    식 셋에 미지수 넷이므로 해는 점이 아니라 **직선 하나**다 (영공간 1 차원).'
      '%    어느 방식을 쓰든 X·Y·N 은 똑같이 만족한다. 다른 것은 그 직선 위의'
      '%    **어느 점에 앉느냐** 이고, 그 자리에 따라 각도가 ±45 deg 안에 드는지가'
      '%    갈린다. 세 방식의 실측 비교는 A3_4_limit_run 에 있다.'
      '%'
      '%  --- 1 단계. 확장 추력 벡터로 선형화 ---'
      '%    미지수를 (크기, 각도) 가 아니라 **x·y 성분 넷**으로 잡으면 식이 선형이 된다.'
      '%      X =  FxL + FxR'
      '%      Y =  FyL + FyR'
      '%      N =  b*(FxL - FxR) - L*(FyL + FyR)'
      '%    미지수 넷 · 식 셋이므로 해가 무한히 많다. 그 가운데 **추력 제곱합이 가장 작은**'
      '%    해를 고르는 것이 수도인버스(pinv) 다. 그 해를 손으로 풀어 두면 아래 세 줄이다.'
      '%      FxL = X/2 + C,  FxR = X/2 - C,  FyL = FyR = Y/2    (C = (L*Y + N)/(2*b))'
      '%    모델 안에서 pinv 를 부르지 않는 이유 — 고정 기하이므로 결과가 늘 같고,'
      '%    코드 생성(codegen)에서 행렬 역을 피할 수 있다.'
      'b = p(1);  L = p(2);  Fmax = p(3);  dmax = p(4);  rev = p(5);  split = p(6);'
      'alloc = p(7);'
      ''
      'if alloc < 0.5'
      '    %  === 수준 0. 공통 각도 — 두 대를 **같은 각도**로 튼다 ==============='
      '    %    가장 단순한 방식이다. 미지수가 (각도 하나 + 추력 둘) 셋뿐이라'
      '    %    식 셋과 수가 맞고, 네 줄로 닫힌식이 나온다.'
      '    %      d = atan2(Y, X)          두 대가 함께 트는 각도'
      '    %      S = hypot(X, Y)          두 추력의 합'
      '    %      D = (N + L*Y)/(b*cos d)  두 추력의 차'
      '    %      TL = (S+D)/2,  TR = (S-D)/2'
      '    %'
      '    %    그런데 순수 횡이동에서 무너진다. X = 0 이면 d = 90 deg 로,'
      '    %    설계 전제 ±45 deg 밖이다. 잘라서 쓰면 Y 를 못 내고,'
      '    %    자르지 않아도 cos d = 0 이라 D 가 발산한다.'
      '    %    **두 각도가 같으면 순수 횡이동은 구조적으로 불가능하다.**'
      '    dc = atan2(Y, X);'
      '    Sc = hypot(X, Y);'
      '    if rev > 0.5 && abs(dc) > pi/2'
      '        dc = dc - sign(dc)*pi;   %  뒤로 미는 쪽으로 고쳐 적는다'
      '        Sc = -Sc;'
      '    end'
      '    if dc >  dmax, dc =  dmax; end   %  여기서 잘린 만큼이 곧 못 낸 힘이다'
      '    if dc < -dmax, dc = -dmax; end'
      '    Dc  = (N + L*Y)/(b*cos(dc));'
      '    TLc = (Sc + Dc)/2;'
      '    TRc = (Sc - Dc)/2;'
      '    FxL = TLc*cos(dc);   FyL = TLc*sin(dc);'
      '    FxR = TRc*cos(dc);   FyR = TRc*sin(dc);'
      'else'
      '    C   = (L*Y + N)/(2*b);'
      '    FxL = X/2 + C;   FyL = Y/2;'
      '    FxR = X/2 - C;   FyR = Y/2;'
      'end'
      ''
      '%  --- 1-1 단계. 영공간 보정 — 각도 한계를 넘을 때 **횡력을 한쪽으로 몰아준다** ---'
      '%    수도인버스는 횡력을 두 대에 똑같이 나눈다 (FyL = FyR = Y/2). 그런데 전후력이'
      '%    섞이면 한쪽의 Fx 가 0 근처로 작아지고, 그 추진기만 각도가 90 deg 까지 치솟는다.'
      '%    설계 전제가 ±45 deg 이므로 그 요구는 잘려 나간다 — 힘이 모자라서가 아니라'
      '%    **똑같이 나눈 탓**이다.'
      '%'
      '%    고칠 자유가 하나 남아 있다. B 의 영공간이 1 차원이고 그 벡터가'
      '%      [FxL FyL FxR FyR] = [0  1  0  -1]'
      '%    이다 — 두 대에 크기 같고 방향 반대인 횡력을 주면 X·Y·N 이 **셋 다 그대로다.**'
      '%    따라서 lam 을 더하고 빼는 것은 요구를 바꾸지 않는다. 각도만 바뀐다.'
      '%'
      '%    각도 한계는 lam 에 대한 1 차 부등식이다 (|d| <= dmax  <=>  |Fy| <= tan(dmax)*|Fx|).'
      '%    그래서 허용 구간 [lo, hi] 를 닫힌식으로 바로 적을 수 있다. 반복도, 최적화도 없다.'
      '%    고르는 값은 그 구간에서 **0 에 가장 가까운 것** — 쓸데없이 몰지 않는다.'
      '%'
      '%    수준 2 에서만 켠다. 수준 1 (수도인버스 그대로) 과의 차이가 곧'
      '%    이 한 항의 효과다 — 도달 가능 집합이 19.7 % 에서 25.3 % 로 넓어진다.'
      'if alloc > 1.5 && split > 0.5 && dmax < pi/2 - 1e-6'
      '    td = tan(dmax);'
      '    lo = max(-td*abs(FxL) - Y/2,  Y/2 - td*abs(FxR));'
      '    hi = min( td*abs(FxL) - Y/2,  Y/2 + td*abs(FxR));'
      '    if lo <= hi'
      '        lam = min(max(0, lo), hi);'
      '    else'
      '        lam = (lo + hi)/2;   %  어떻게 나눠도 안 되는 요구 — 두 각도를 고르게 넘긴다'
      '    end'
      '    FyL = Y/2 + lam;'
      '    FyR = Y/2 - lam;'
      'end'
      ''
      '%  --- 2 단계. 성분을 (크기, 각도) 로 되돌리고 한계를 건다 ---'
      '[TL, dL] = az_polar(FxL, FyL, dmax, rev);'
      '[TR, dR] = az_polar(FxR, FyR, dmax, rev);'
      ''
      '%  --- 3 단계. 추력 포화 — 요구를 **같은 비율로** 줄인다 ---'
      '%    배분식이 선형이므로 X·Y·N 을 k 배 하면 추력도 정확히 k 배가 된다.'
      '%    따라서 한 번만 곱해 주면 끝난다. 방향각은 비(ratio)로만 정해지므로'
      '%    배율에 영향받지 않는다 — **각도 포화는 이 방법으로 고칠 수 없다.**'
      'Tpk  = max(abs(TL), abs(TR));'
      'kscl = 1;'
      'if Tpk > Fmax'
      '    kscl = Fmax/Tpk;'
      '    TL = kscl*TL;'
      '    TR = kscl*TR;'
      'end'
      ''
      'function [T, d] = az_polar(Fx, Fy, dmax, rev)'
      '%  성분 -> (크기, 각도). 각도 한계와 추력 반전 규칙을 여기서 건다.'
      'T = hypot(Fx, Fy);'
      'd = atan2(Fy, Fx);'
      '%  (a) 뒤쪽 90 deg 를 넘는 요구는 **반대로 틀고 뒤로 민다** 로 바꿔 적는다.'
      '%      그래야 각도가 ±90 deg 안에 머물고, 지령이 0 을 지날 때 atan2 가'
      '%      ±180 deg 로 튀면서 추진기가 반 바퀴 돌지 않는다.'
      'if abs(d) > pi/2'
      '    d = d - sign(d)*pi;'
      '    T = -T;'
      'end'
      '%  (b) 뒤로 미는 것을 금지하면 (a) 를 쓸 수 없다. 원래 각도로 되돌린다'
      '%      — 그 각도는 보통 한계를 한참 넘으므로 아래 (c) 에서 잘려 나간다.'
      '%      잘린 만큼이 그대로 힘의 오차가 된다. A3-4 실습에서 이것을 본다.'
      'if rev < 0.5 && T < 0'
      '    T = -T;'
      '    d = d + sign(d + (d==0))*pi;'
      '    if d >  pi, d = d - 2*pi; end'
      '    if d < -pi, d = d + 2*pi; end'
      'end'
      '%  (c) 각도 한계 — 넘으면 자른다. 자른 뒤의 힘은 요구와 다르다.'
      'if d >  dmax, d =  dmax; end'
      'if d < -dmax, d = -dmax; end'
      }, newline);
end
