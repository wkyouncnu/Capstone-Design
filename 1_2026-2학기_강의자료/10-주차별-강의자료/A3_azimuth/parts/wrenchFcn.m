function src = wrenchFcn()
%WRENCHFCN  추진기 명령 -> 선체에 실제로 걸리는 렌치
%
%   **운동모델 서브시스템 안**에 들어가는 MATLAB Function 이다
%   (parts/addMotionModelXYN.m 이 심는다).
%
%   운동모델은 추진기가 어떻게 생겼는지를 알아야 한다 — 노즐이 비스듬히
%   서 있으면 같은 추력이 전후·횡·요로 나뉘어 걸린다. 그 변환이 이 함수다.
%   배분기가 "거꾸로" 푼 B 를 여기서는 **바로** 쓴다. 두 계산이 같은 행렬을
%   쓰므로, 한계에 물리지 않는 한 요구 렌치와 실제 렌치가 같아진다.
%
%   입력  TL, dL, TR, dR   배분기가 낸 추력 [N] 과 각도 [rad]
%                          (각도는 변화율 제한을 거친 **실제** 각도다)
%         p                기하 묶음 — p(1) = b, p(2) = L
%   출력  X_a, Y_a, N_a    선체에 실제로 걸리는 렌치 [N, N, N m]

src = strjoin({
  'function [X_a, Y_a, N_a] = Wrench(TL, dL, TR, dR, p)'
  '%#codegen'
  '%  추진기 명령 -> 선체에 걸리는 렌치 (운동모델의 입구)'
  '%'
  '%  == 입력 =============================================================='
  '%    TL, TR   좌·우 추력 [N]      배분기가 낸 값. 음수면 역추력'
  '%    dL, dR   좌·우 각도 [rad]    변화율 제한을 거친 실제 각도'
  '%    p        기하 묶음 — p(1) = b 반폭 [m], p(2) = L 거리 [m]'
  '%'
  '%  == 출력 =============================================================='
  '%    X_a  실제 전후 힘   [N]'
  '%    Y_a  실제 횡 힘     [N]'
  '%    N_a  실제 요 모멘트 [N m]'
  '%'
  '%  == 왜 운동모델 안에 있는가 ==========================================='
  '%    선체가 받는 것은 추력과 각도가 아니라 **힘과 모멘트**다. 추진기가'
  '%    어떻게 달려 있는지가 그 변환을 정하므로, 변환은 배(운동모델) 쪽에'
  '%    속한다. 배분기는 "무엇을 명령할까" 까지만 책임진다'
  '%'
  '%  == 배분기와 같은 행렬이다 ============================================'
  '%    배분기는 B ue = tau 를 **거꾸로** 풀었고, 여기서는 **바로** 쓴다'
  '%        ue = [TL cos(dL); TL sin(dL); TR cos(dR); TR sin(dR)]'
  '%        tau_a = B ue'
  '%    각도·추력 한계에 물리지 않으면 tau_a 가 요구 렌치와 같아진다.'
  '%    기하를 고칠 때는 azAllocFcn.m 의 B 와 **함께** 고쳐야 한다'
  ''
  'b = p(1);  L = p(2);'
  ''
  'B = [ 1,  0,  1,  0; ...'
  '      0,  1,  0,  1; ...'
  '      b, -L, -b, -L];'
  ''
  '%  극좌표(추력·각도) -> 직교 성분 넷'
  'ue = [TL*cos(dL); TL*sin(dL); TR*cos(dR); TR*sin(dR)];'
  ''
  'tau_a = B*ue;'
  ''
  'X_a = tau_a(1);  Y_a = tau_a(2);  N_a = tau_a(3);'
  }, newline);
end
