function src = wrenchFcn()
% wrenchFcn — 실제로 난 힘·모멘트를 되계산하는 MATLAB Function 의 본문
%
%   배분에서 각도를 잘랐거나 추력을 줄였으면, 실제로 난 힘은 요구와 다르다.
%   운동모델에는 **실제로 난 힘**을 넣어야 한다. 요구를 그대로 넣으면 한계가
%   없는 배를 돌리는 셈이 되어, 각도 한계의 효과가 그림에 나타나지 않는다.
%
%   2026-11-12 개정 — AzAlloc 과 **같은 배치행렬 B** 를 써서 행렬 한 줄로 쓴다.
%   배분은 B 를 거꾸로 (의사역행렬), 확인은 B 를 바로 곱한다 — 같은 행렬을
%   양방향으로 쓴다는 점이 이 절의 요지다.
    src = strjoin({
      'function [X_a, Y_a, N_a] = Wrench(TL, dL, TR, dR, p)'
      '%#codegen'
      '%  Wrench — 추진기 두 대가 **실제로** 낸 렌치를 되계산한다'
      '%'
      '%  ===== 입력 =========================================================='
      '%    TL     [N]      좌현 추진기 추력 (음수 = 뒤로 밂). Rate Limiter 뒤의 값'
      '%    dL     [rad]    좌현 추진기 방향각. Rate Limiter 뒤의 값'
      '%    TR     [N]      우현 추진기 추력'
      '%    dR     [rad]    우현 추진기 방향각'
      '%    p      [-]      az_prm. 이 함수는 앞의 둘만 쓴다'
      '%      p(1) = b [m]  half_beam  중심선 -> 추진기, 가로 거리'
      '%      p(2) = L [m]  l_thr      무게중심 -> 추진기, 뒤쪽 거리'
      '%'
      '%  ===== 출력 =========================================================='
      '%    X_a    [N]      실제로 난 서지력   (achieved)'
      '%    Y_a    [N]      실제로 난 스웨이력'
      '%    N_a    [N m]    실제로 난 요 모멘트'
      '%'
      '%  ===== 쓰는 식 — AzAlloc 의 B 를 **그대로 거꾸로** 쓴다 ============='
      '%    (1) 각도를 성분으로 펴기 (extended force representation)'
      '%          ue = R(dL,dR) * [TL; TR]'
      '%          R  = [cos dL,      0;'
      '%                sin dL,      0;'
      '%                     0, cos dR;'
      '%                     0, sin dR]'
      '%    (2) 성분을 렌치로 모으기'
      '%          tau_a = B * ue,    B = [1, 0, 1, 0;'
      '%                                  0, 1, 0, 1;'
      '%                                  b,-L,-b,-L]'
      '%'
      '%    AzAlloc 은 tau -> ue 로 B 를 **거꾸로** 가고 (의사역행렬),'
      '%    여기서는 ue -> tau_a 로 B 를 **바로** 간다. 한계가 물리지 않았으면'
      '%    두 길이 정확히 되돌아오므로 tau_a = tau 가 된다.'
      '%    요구와 이 값의 차이가 곧 **한계 때문에 못 낸 힘**이다 (로그로 본다).'
      '%'
      '%  참고 : E. I. Sarda et al., Ocean Engineering 127 (2016) 305-324,'
      '%         식 (45)-(49). 그 논문의 tau = T f 가 여기의 tau_a = B ue 다.'
      'b = p(1);  L = p(2);'
      'B  = [ 1,  0,  1,  0; ...'
      '       0,  1,  0,  1; ...'
      '       b, -L, -b, -L];'
      'ue = [TL*cos(dL); TL*sin(dL); TR*cos(dR); TR*sin(dR)];'
      'tau_a = B*ue;'
      'X_a = tau_a(1);'
      'Y_a = tau_a(2);'
      'N_a = tau_a(3);'
      }, newline);
end
