% W05_SETUP  5주차 실습 설정 — 이 파일만 고치면 된다.
%
%   모델을 열기 전에 반드시 이 스크립트를 먼저 실행한다.
%   Simulink 의 Constant 블록들이 여기서 만든 변수 이름을 그대로 참조한다.
%
%   >> W05_setup
%   >> open_system('W05_0_offline')      % 실습 A — 조류 실험
%   >> open_system('W05_1_vrx')          % 실습 B — Gazebo 연동

clear; clc;

%% ====================================================================
%  1. 웨이포인트 — 출발점 기준 상대좌표 [m], NED
%     x = 북쪽(+), y = 동쪽(+)   (코드 이름 wp_north, wp_east, x_n, y_n)
%     한 변 80 m 짜리 사각형이다. 숫자만 바꾸면 경로가 바뀐다.
%
%     배는 (0,0) 에서 출발하는데 경로의 첫 구간은 y = 20 m (동쪽 20 m) 선이다.
%     즉 배가 경로에서 20 m 벗어난 곳에서 시작한다. 일부러 그렇게 두었다.
%     경로 위에서 출발하면 atan2 와 LOS 의 차이가 거의 보이지 않는다.
%
% > [주의] 이 좌표 범위를 크게 벗어나면 배가 육지에 얹힌다.
%   sydney_regatta 에서 스폰 기준으로 안전이 확인된 수역은
%   대략 N in [-28, 60],  E in [-18, 100] 이다.
%   (VRX wayfinding_task 의 공식 웨이포인트 3점을 환산해 얻은 값)
% =====================================================================
wp_north = [ -20   60   60  -20  -20 ];   % 웨이포인트 x (북쪽) [m]
wp_east  = [  20   20  100  100   20 ];   % 웨이포인트 y (동쪽) [m]

%% ====================================================================
%  2. 유도 설정
% =====================================================================
guidance_mode = 2;      % 1 = atan2 유도,  2 = LOS 유도
Delta         = 10;     % lookahead distance [m]  (LOS 만 사용)
R_LOS         = 5;      % 웨이포인트 수락반경 [m]
sw_mode       = 1;      % 전환 판정.  1 = 경로 방향 (d - x_e < R),  2 = 수락 원
u_ref         = 1.5;    % 목표 속도 [m/s]

%% ====================================================================
%  3. 조류 — 오프라인 모델(W05_0_offline)에서만 동작한다
%     VRX 에는 해류 플러그인이 없다. 실습 A 에서만 실험할 수 있다.
% =====================================================================
current_speed     = 0.0;    % 조류 속도 [m/s]
current_direction = 0.0;    % 조류가 흘러가는 방향 [deg, NED. 0 = 북]

%% ====================================================================
%  4. 제어 게인 — 두 모델이 완전히 같은 값을 쓴다
%     오프라인 플랜트가 Gazebo 와 같은 계수로 만들어져 있기 때문이다.
%     여기서 맞춘 게인이 VRX 에서도 그대로 통해야 정상이다.
% =====================================================================
% 헤딩 제어 — P-D 요각속도 되먹임 (MSS 방식)
%   tau_N = Kp_psi * ssa(psi_ref - psi) - Kd_psi * r
%   오차를 미분하지 않으므로 웨이포인트 전환 때 미분 킥이 없다
Kp_psi = 400;   Kd_psi = 200;

% 속도 제어 — u (surge velocity) 되먹임 PI
%   U = sqrt(u^2+v^2) 가 아니다. MSS 의 surge velocity control 과 같다
Kp_u = 300;     Ki_u = 100;

% 적분기 anti-windup — 역계산(back-calculation) 되감기 이득 [1/s]
%   dI/dt = e + Kb*( sat(v) - v ).  1/Kb 가 되감기는 시간상수다.
%   Kb = Ki/Kp 로 두는 것이 Astrom 의 권고다 (적분시간 Ti = Kp/Ki = 3 s 와 같게).
Kb = Ki_u / Kp_u;

half_beam = 1.027135;   % 후방 2추진기 좌우 반폭 [m] (wamv_aft_thrusters.xacro)
F_max     = 500;        % 추력 포화 [N]
% 왜 500 인가
%   1.5 m/s 를 유지하려면  X = (100 + 150*1.5)*1.5 = 488 N,  편당 244 N 이 든다.
%   4주차처럼 F_max = 250 으로 두면 직진에 다 써 버려 선회할 여유가 없다.
%   실제로 포화 시간이 77 % 였고 경로 이탈이 두 배로 커졌다.
%   500 으로 올리면 포화 0 %, 이탈량이 절반이 된다.
%   VRX 플러그인의 물리 한계는 2353.6 N 이므로 500 은 충분히 현실적이다.

%% ====================================================================
%  5. 오프라인 플랜트 계수 — Gazebo 와 같은 값
%     출처: wamv_gazebo_dynamics_plugin.xacro (SimpleHydrodynamics)
%           wamv_base.urdf.xacro (질량·관성)
%     확인: 정상상태 400 N -> u = 1.333 m/s. Gazebo 실측 1.332 m/s (4주차 J절)
% =====================================================================
m_usv  = 211;    % 총 질량 [kg]      = base_link 180 + 엔진 2x15 + 프로펠러 2x0.5
Izz    = 653;    % 요 관성 [kg m^2]  = base_link 446 + 엔진 이동항

Xu = 100;  Xuu = 150;    % surge 항력  -(Xu + Xuu|u|)u
Yv = 100;  Yvv = 100;    % sway  항력
Nr = 800;  Nrr = 800;    % yaw   항력
% 부가질량은 VRX 설정에서 xDotU = yDotV = nDotR = 0 이다

%% ====================================================================
%  6. 추진기 — 프로펠러 법칙이 어디 있는가
%     VRX 추진기 토픽 /wamv/thrusters/*/thrust (std_msgs/Float64) 가 받는 것은
%     **뉴턴**이다. 역 프로펠러 법칙은 제어기가 아니라 플러그인 **안**에 있다.
%
%     플러그인 선언  — 아래 두 자리에 계수가 적혀 있다
%       vrx/vrx_urdf/wamv_gazebo/urdf/thruster_layouts/
%                                      wamv_gazebo_thruster_config.xacro:10-24
%       펼친 결과   bow_wamv/bow_wamv_target.urdf:462-473 (left) · :484-495
%                   (right) · :506-517 (middle = 선수추진기)
%     플러그인 소스 — gz-sim7  src/systems/thruster/Thruster.cc
%       :520-521  OnCmdThrust         clamp(cmd, cmdMin, cmdMax)   <- 포화는 추력에
%       :562-584  ThrustToAngularVec  omega = sign(F*Ct)*sqrt(|F|/(rho*Ct*D^4))
%       :593-599  AngularVelToThrust  F = rho*Ct*D^4*|omega|*omega
%       :740-756  velocity_control    구한 omega 를 JointVelocityCmd 로 바로 쓴다
%       :770-773  AddWorldWrench      링크에 주는 힘은 **포화만 거친 지령**이다
%
%     Thrusters 서브시스템은 이 네 토막을 그 순서대로 다시 적는다. 세 번째 식은
%     플러그인에서 회전수 지령 모드에만 쓰이므로 되돌려 맞는지 보는 **검산**으로
%     두고, 그 차이를 F_err 로 로깅한다 (0 이 나와야 한다).
%       k = rho * Ct * D^4 = 1000 * 0.004422 * 0.2^4   (URDF 값 그대로)
% =====================================================================
k_prop = 1000 * 0.004422 * 0.2^4;   % 0.0070752 [N/(rad/s)^2]
n_max  = sqrt(F_max / k_prop);      % 265.8 rad/s (약 2538 rpm) — F_max 를 회전수로
                                    % 읽은 눈금이다. 포화 블록이 아니라 참고선이다

%   플러그인이 추력에 거는 한계 — URDF 의 max_thrust_cmd 를 그대로 옮긴다.
%   그 값의 유래도 URDF 에 식으로 적혀 있다 (thruster_config.xacro:6-8, 20)
%     (x_u + x_uu * v_max) * v_max / 2,   x_u = 51.3, x_uu = 72.4, v_max = 7.71667
%   즉 **최대 속도에서의 항력을 추진기 둘이 나눠 낸 몫**이다.
F_plugin_max = 2353.53383667818;    % [N] 추진기 하나당 (URDF 값 그대로)
%   본 과목의 F_max = 500 N 은 그 21 % 이므로 Gazebo 가 먼저 자르는 일은 없다.

%% ====================================================================
%  7. 실시간 그림 (W05_0_offline 전용)
%     모델이 도는 동안 배와 웨이포인트를 그린다.
%     선체는 shipModel.m 과 같은 모양 — 선수는 세모, 선미는 네모다.
% =====================================================================
animate       = 1;      % 1 = 켬,  0 = 끔 (끄면 훨씬 빨리 돈다)
animate_every = 0.25;   % 몇 초마다 다시 그릴 것인가 [시뮬레이션 초]
boat_scale    = 3;      % 선체를 몇 배로 크게 그릴 것인가
                        % 1 이면 실제 크기(전장 4.9 m). 넓은 경로에서는 점처럼 보인다

%% ====================================================================
%  8. VRX 스폰 위치 — 상대좌표를 절대좌표로 옮기는 기준점
%     vrx_gz/launch/competition.launch.py 의 Model('wamv','wam-v',[-532,162,0,0,0,1])
%     ENU 의 (x,y) = (-532, 162) 이므로 NED 로는 (N,E) = (162, -532)
%     설치마다 다르다 — 같은 2.4.0-2 인데 162 인 컴퓨터와 200 인 컴퓨터가 있다 (2026-09-18).
%     그래서 아래 값은 기본값일 뿐이고, W05_vrx_run 이 ground truth 첫 샘플로 덮어쓴다.
%     이 값이 틀리면 VRX 주행이 그 차이만큼 경로에서 벗어난 채 시작한다
% =====================================================================
origin_north =  162;
origin_east  = -532;

%  경로를 월드의 어디에 놓을 것인가 — VRX 에서만 쓴다 (2026-10-16 노트북 실측)
%     위 웨이포인트는 "이 점을 (0,0) 으로 본 좌표" 다. 스폰을 (0,0) 으로 삼으면
%     스폰이 162 인 설치(VRX 원본 그대로)에서는 경로 전체가 38 m 남쪽으로 밀려
%     4번 웨이포인트 부근에서 남쪽 해안에 얹힌다 (속도 1.5 -> 0 m/s, 미완주).
%     그래서 W05_vrx_run 은 경로 원점을 아래 월드 좌표에 고정하고, 배는 스폰
%     자리에서 출발한다. 162 설치에서는 배가 경로 원점보다 38 m 남쪽에서 출발한다.
path_north0 =  200;   % 경로 원점의 월드 좌표 (ENU y = NED 북쪽) [m]
path_east0  = -532;   % 경로 원점의 월드 좌표 (ENU x = NED 동쪽) [m]

%% ====================================================================
%  9. 자동 계산 — 손대지 않아도 된다
% =====================================================================
psi_init = atan2(wp_east(2)-wp_east(1), wp_north(2)-wp_north(1));

% 오프라인 모델 초기 상태 [u v r N E psi]'
% VRX 와 맞추기 위해 원점 (0,0) 에서 출발한다
x0 = [0.1; 0; 0; 0; 0; psi_init];

Ts_ctrl = 0.05;                          % 제어 주기 [s]
beta_c  = deg2rad(current_direction);    % 조류 방향 [rad]

% 오프라인 운동모델이 받는 계수 묶음 — 순서가 곧 p(1..9)
usv_p = [m_usv; Izz; Xu; Xuu; Yv; Yvv; Nr; Nrr; half_beam];
%   벡터를 블록 안에 적지 않고 **이름**으로 두는 까닭
%     Constant 블록은 적힌 글이 블록보다 길면 Simulink 가 값을 감추고 '-C-' 만
%     그린다. 강의노트에 그 그림이 그대로 실리므로 어느 값인지 알 수 없게 된다.

if guidance_mode == 1
    mode_name = 'atan2';
else
    mode_name = 'LOS';
end

fprintf('W05 설정 완료\n');
fprintf('  웨이포인트 %d개, 유도 = %s\n', numel(wp_north), mode_name);
fprintf('  Delta = %g m, R = %g m, u_ref = %g m/s\n', Delta, R_LOS, u_ref);
if sw_mode == 1
    sw_name = '경로 방향 (d - x_e < R)';
else
    sw_name = '수락 원';
end
fprintf('  전환 판정 = %s\n', sw_name);
fprintf('  조류 = %g m/s @ %g deg  (오프라인 모델에서만 적용)\n', ...
        current_speed, current_direction);

%% ====================================================================
%  10. 바로 실행
%      이 파일을 실행하면 오프라인 모델이 곧바로 돌고 그림이 나온다.
%      설정만 바꾸고 직접 Run 하고 싶으면 auto_run = 0 으로 둘 것.
% =====================================================================
% 실행 길이와 자동 정지 (2026-10-02)
%
%   전에는 VRX 모델의 StopTime 이 inf 였다. Run 을 누르면 끝나지 않아 Stop 을
%   손으로 눌러야 했다. 이제 **마지막 웨이포인트를 지나면 모델이 스스로 멈춘다.**
%
%   끝났다는 신호는 유도부의 gate 다. 마지막 구간을 지나면 wp_idx 가 n 으로
%   빗장이 걸리고 gate 가 0 이 된다. 그 뒤 stop_hold 초만 더 돌고 끝낸다 —
%   도착해서 멈추는 모습이 그래프에 남아야 읽을 수 있기 때문이다.
% =====================================================================
T_run     = 600;    % 최대 실행 시간 [s] — AutoStop 이 안 걸릴 때를 받친다
stop_hold = 10;     % 임무가 끝난 뒤 더 도는 시간 [s]

% =====================================================================
auto_run = 1;

% W05_compare 처럼 여러 조건을 스스로 돌리는 스크립트는 이 자동 실행을 건너뛴다
skip_run = getappdata(0, 'W05_skip_run');
if isempty(skip_run), skip_run = false; end
setappdata(0, 'W05_skip_run', false);


%% ====================================================================
%  ROS 2 도메인 — WSL 의 ~/.bashrc 와 같아야 토픽이 보인다 (스킬 규칙 27)
%    WSL 터미널에서  echo $ROS_DOMAIN_ID
%    본 과목은 전 주차 7. 자기 팀 번호로 바꿀 때는 WSL 쪽도 같이 바꾼다
% =====================================================================
ros_domain_id = '7';
setenv('ROS_DOMAIN_ID', ros_domain_id);
fprintf('  ROS_DOMAIN_ID = %s  (WSL 의 echo $ROS_DOMAIN_ID 와 같아야 함)\n', ros_domain_id);

if auto_run && ~skip_run
    fprintf('\n오프라인 모델 실행 중  (auto_run = 0 으로 두면 실행하지 않는다)\n');
    if animate
        fprintf('  실시간 그림 켜짐 — 새 창이 열린다. 끄려면 animate = 0\n');
    end
    load_system('W05_0_offline');
    out = sim('W05_0_offline');
    W05_plot(out, sprintf('%s 유도 / 조류 %g m/s', mode_name, current_speed));
end
