% =====================================================================
% 1단 · DP 목표값
function mk_inputs(ss, in, nSig, cfg, dly, clk)
% 단계 입력 만들기 — 신호는 포트로, 설정은 상수로, 상태는 지연으로.
%
%   IN    함수 인자 순서 그대로의 이름 목록. **블록 이름도 이것을 쓴다**
%         뒤의 배선 코드가 이름으로 잇기 때문에 바꾸지 않는다
%   NSIG  바깥에서 들어오는 신호. 개수(앞에서부터) 또는 이름 목록 {'nu'}
%   CFG   {이름, 값}            설정값 -> 상자 안의 Constant
%   DLY   {이름, 출력포트, 초기값}  상태  -> 상자 안의 Unit Delay + 태그
%   CLK   비우지 않으면 그 이름의 블록을 Digital Clock 으로 만든다
%
%   설정값을 최상위에 두면 상수 열이 신호 사슬 앞을 가리고, 상태 되먹임을
%   최상위에 두면 화면을 가로지르는 선이 생긴다. 둘 다 상자 안의 일이다.
if nargin < 6, clk = ''; end

%  숫자면 '앞에서부터 그만큼', 이름 목록이면 그 이름들만 In1 으로 만든다.
%  [2] 같은 1원소 배열은 isscalar 가 참이라 개수와 구별되지 않는다 — 이름을 쓴다.
if iscell(nSig)
    [~, idx] = ismember(nSig, in);
else
    idx = 1:nSig;
end
for p = 1:numel(idx)
    k = idx(p);
    add_block('simulink/Sources/In1', [ss '/' in{k}], ...
              'Position',[40 60+(p-1)*70 75 90+(p-1)*70], 'Port', num2str(p));
end
if ~isempty(clk)
    add_block('simulink/Sources/Digital Clock', [ss '/' clk], ...
              'Position',[40 300 90 330], 'SampleTime','Ts_ctrl');
end
for k = 1:size(cfg,1)
    add_block('simulink/Sources/Constant', [ss '/' cfg{k,1}], ...
              'Position',[40 400+(k-1)*70 130 430+(k-1)*70], 'Value', cfg{k,2});
end
for k = 1:size(dly,1)
    nm = dly{k,1};
    %  블록 이름을 in{} 과 같게 둔다. 그래야 뒤의 배선이 그대로 통한다
    add_block('simulink/Discrete/Unit Delay', [ss '/' nm], ...
              'Position',[240 700+(k-1)*90 315 740+(k-1)*90], ...
              'SampleTime','Ts_ctrl', 'InitialCondition', dly{k,3});
    add_block('simulink/Signal Routing/From', [ss '/Fr_' nm], ...
              'Position',[110 709+(k-1)*90 180 731+(k-1)*90], 'GotoTag', ['s_' nm]);
    add_line(ss, ['Fr_' nm '/1'], [nm '/1'], 'autorouting','on');
end
end

% ---------------------------------------------------------------------
function mk_state_out(ss, fcn, dly)
%MK_STATE_OUT  상태 출력을 태그로 걸어 지연 블록이 받게 한다.
%   상자 밖으로 나가지 않는 값이므로 출력 포트를 만들지 않는다.
for k = 1:size(dly,1)
    nm = dly{k,1};
    add_block('simulink/Signal Routing/Goto', [ss '/Go_' nm], ...
              'Position',[560 709+(k-1)*90 640 731+(k-1)*90], ...
              'GotoTag', ['s_' nm], 'TagVisibility','local');
    add_line(ss, sprintf('%s/%d', fcn, dly{k,2}), ['Go_' nm '/1'], 'autorouting','on');
end
end

% =====================================================================
% 1단 · DP 목표값 (스케줄 + 레퍼런스 모델)
% =====================================================================
function addDPRef(m, x, y)
    ss = [m '/DPRef'];
    add_block('built-in/Subsystem', ss, 'Position', [x y x+160 y+120]);

    in  = {'t','mode','tbl','eta0','pre','rpar'};
    cfg = {'mode','dp_mode'; 'tbl','dp_step'; ...
           'eta0','[dp_N0; dp_E0; dp_PSI0]'; ...
           'rpar','[dp_ref_on; dp_vmax; tau_ref; Ts_ctrl]'};
    dly = {'pre',2,'[dp_N0; dp_E0; dp_PSI0]'};
    mk_inputs(ss, in, 0, cfg, dly, 't');

    setFcn(ss, 'Sched', [ ...
'function [eta_d, snew, eta_raw] = Sched(t, mode, tbl, eta0, pre, rpar)'  newline ...
'%#codegen'                                                              newline ...
'% DP setpoint scheduler and REFERENCE MODEL.'                           newline ...
'%'                                                                      newline ...
'%   mode 0 : hold the initial setpoint'                                 newline ...
'%   mode 1 : step through the table  [t  N  E  psi_deg]'                newline ...
'%'                                                                      newline ...
'% A raw step demand is never given to a DP controller. The vessel'      newline ...
'% cannot move at any speed, so a step makes the controller ask for a'   newline ...
'% force the thrusters cannot deliver, and the loop saturates.'          newline ...
'% A reference model turns the step into a feasible trajectory. Here a'  newline ...
'% saturated proportional law is used:'                                  newline ...
'%     v = (eta_raw - eta_d)/tau_ref,   |v| <= v_max'                    newline ...
'% Far from the target the setpoint moves at the constant speed v_max;'  newline ...
'% close to it the approach becomes exponential with time constant'      newline ...
'% tau_ref, so there is no corner at arrival.'                           newline ...
'% Fossen (2011) calls this the reference model; every DP system has'    newline ...
'% one.'                                                                 newline ...
'%'                                                                      newline ...
'% rpar = [on; vx; vy; vPsi; tau_ref; Ts]'                               newline ...
''                                                                       newline ...
'eta_raw = eta0;'                                                        newline ...
'if mode > 0.5'                                                          newline ...
'    n = size(tbl,1);'                                                   newline ...
'    for i = 1:n'                                                        newline ...
'        if t >= tbl(i,1)'                                               newline ...
'            eta_raw = [tbl(i,2); tbl(i,3); tbl(i,4)*pi/180];'           newline ...
'        end'                                                            newline ...
'    end'                                                                newline ...
'end'                                                                    newline ...
''                                                                       newline ...
'if rpar(1) < 0.5'                                                       newline ...
'    eta_d = eta_raw;  snew = eta_raw;'                                   newline ...
'    return'                                                             newline ...
'end'                                                                    newline ...
''                                                                       newline ...
'vmax = rpar(2:4);  tr = rpar(5);  Ts = rpar(6);'                        newline ...
'snew = pre;'                                                            newline ...
'for i = 1:3'                                                            newline ...
'    d = eta_raw(i) - pre(i);'                                           newline ...
'    if i == 3, d = atan2(sin(d), cos(d)); end'                          newline ...
'    v = d/tr;'                                                          newline ...
'    if v >  vmax(i), v =  vmax(i); end'                                 newline ...
'    if v < -vmax(i), v = -vmax(i); end'                                 newline ...
'    snew(i) = pre(i) + v*Ts;'                                           newline ...
'end'                                                                    newline ...
'snew(3) = atan2(sin(snew(3)), cos(snew(3)));'                           newline ...
'eta_d = snew;']);
    set_param([ss '/Sched'],'Position',[180 70 360 480]);

    out = {'eta_d','snew','eta_raw'};
    for k = [1 3]
        add_block('simulink/Sinks/Out1', [ss '/' out{k}], ...
                  'Position',[440 100+(k-1)*90 475 130+(k-1)*90], 'Port', num2str(1+(k>1)));
        add_line(ss, sprintf('Sched/%d',k), [out{k} '/1'], 'autorouting','on');
    end
    for k = 1:numel(in)
        add_line(ss, [in{k} '/1'], sprintf('Sched/%d',k), 'autorouting','on');
    end
    mk_state_out(ss, 'Sched', dly);
    Simulink.BlockDiagram.arrangeSystem(ss);
end

% =====================================================================
% 1.5단 · 파랑 필터
% =====================================================================
function addWaveFilter(m, x, y)
    ss = [m '/WaveFilter'];
    add_block('built-in/Subsystem', ss, 'Position', [x y x+170 y+140]);

    in  = {'eta','nu','pre','par'};
    cfg = {'par','[filt_on; w_filt; Ts_ctrl]'};
    dly = {'pre',3,'[0;0;0;0;0;0]'};
    mk_inputs(ss, in, 2, cfg, dly);

    setFcn(ss, 'Filt', [ ...
'function [eta_f, nu_f, snew] = Filt(eta, nu, pre, par)'                 newline ...
'%#codegen'                                                              newline ...
'% Wave filtering for dynamic positioning.'                              newline ...
'%'                                                                      newline ...
'% First order wave loads make the vessel oscillate at the wave'         newline ...
'% frequency. That motion cannot be counteracted — trying to do so'      newline ...
'% only wears out the thrusters. A DP system therefore feeds the'        newline ...
'% controller with the LOW FREQUENCY part of the motion only.'           newline ...
'% Fossen (2011) 11.4.1 uses a passive observer; here a first order'     newline ...
'% low pass with a cut-off well below the wave frequency is enough to'   newline ...
'% show the effect.'                                                     newline ...
'%'                                                                      newline ...
'% par = [on; wf; Ts]'                                                   newline ...
''                                                                       newline ...
'on = par(1); wf = par(2); Ts = par(3);'                                 newline ...
'z  = [eta; nu];'                                                        newline ...
'if on < 0.5'                                                            newline ...
'    eta_f = eta;  nu_f = nu;  snew = z;'                                newline ...
'    return'                                                             newline ...
'end'                                                                    newline ...
'a = Ts*wf/(1 + Ts*wf);'                                                 newline ...
'snew = pre + a*(z - pre);'                                              newline ...
'% heading must be filtered on the difference, not the raw angle'        newline ...
'd3 = atan2(sin(eta(3) - pre(3)), cos(eta(3) - pre(3)));'                newline ...
'snew(3) = pre(3) + a*d3;'                                               newline ...
'snew(3) = atan2(sin(snew(3)), cos(snew(3)));'                           newline ...
'eta_f = snew(1:3);'                                                     newline ...
'nu_f  = snew(4:6);']);
    set_param([ss '/Filt'],'Position',[220 70 400 330]);

    out = {'eta_f','nu_f','snew'};
    for k = 1:2
        add_block('simulink/Sinks/Out1', [ss '/' out{k}], ...
                  'Position',[440 100+(k-1)*90 475 130+(k-1)*90], 'Port', num2str(k));
        add_line(ss, sprintf('Filt/%d',k), [out{k} '/1'], 'autorouting','on');
    end
    for k = 1:numel(in)
        add_line(ss, [in{k} '/1'], sprintf('Filt/%d',k), 'autorouting','on');
    end
    mk_state_out(ss, 'Filt', dly);
    Simulink.BlockDiagram.arrangeSystem(ss);
end

% =====================================================================
% 2단 · DP 제어기 (3자유도 PID)
% =====================================================================
function addDPCtrl(m, x, y)
    ss = [m '/DPCtrl'];
    add_block('built-in/Subsystem', ss, 'Position', [x y x+190 y+220]);

    in  = {'eta_d','eta','nu','Ipre','par'};
    cfg = {'par','[diag(Kp_dp); diag(Kd_dp); diag(Ki_dp); i_max; Ts_ctrl]'};
    dly = {'Ipre',2,'[0;0;0]'};
    mk_inputs(ss, in, 3, cfg, dly);

    setFcn(ss, 'PID3', [ ...
'function [tau, Inew, eta_e] = PID3(eta_d, eta, nu, Ipre, par)'          newline ...
'%#codegen'                                                              newline ...
'% 3-DOF dynamic positioning controller (Fossen 2011, 12.2.10).'         newline ...
'%'                                                                      newline ...
'%   eta   = [N; E; psi]      position and heading in NED'               newline ...
'%   nu    = [u; v; r]        velocity in BODY'                          newline ...
'%   tau   = -J(psi)'' * (Kp*eta_e + Ki*I) - Kd*nu'                      newline ...
'%'                                                                      newline ...
'% The transpose of the rotation matrix turns a NED position error into' newline ...
'% a BODY force. Damping is taken on BODY velocity directly, so no'      newline ...
'% derivative of the error is needed (same idea as the P-D heading'      newline ...
'% controller of week 7).'                                               newline ...
'%'                                                                      newline ...
'% par = [Kp(1:3); Kd(1:3); Ki(1:3); imax(1:3); Ts]'                     newline ...
''                                                                       newline ...
'Kp = par(1:3);  Kd = par(4:6);  Ki = par(7:9);'                         newline ...
'im = par(10:12); Ts = par(13);'                                         newline ...
''                                                                       newline ...
'e = eta - eta_d;'                                                       newline ...
'e(3) = atan2(sin(e(3)), cos(e(3)));      % smallest signed angle'       newline ...
''                                                                       newline ...
'psi = eta(3);'                                                          newline ...
'J = [ cos(psi), -sin(psi), 0;'                                          newline ...
'      sin(psi),  cos(psi), 0;'                                          newline ...
'             0,         0, 1];'                                         newline ...
''                                                                       newline ...
'% integral state with clamping (anti-windup)'                           newline ...
'Inew = Ipre + Ts*e;'                                                    newline ...
'for i = 1:3'                                                            newline ...
'    lim = im(i)/max(Ki(i), 1e-9);'                                      newline ...
'    if Inew(i) >  lim, Inew(i) =  lim; end'                             newline ...
'    if Inew(i) < -lim, Inew(i) = -lim; end'                             newline ...
'end'                                                                    newline ...
''                                                                       newline ...
'tau = -J'' * ( Kp.*e + Ki.*Inew ) - Kd.*nu;'                            newline ...
'eta_e = e;']);
    set_param([ss '/PID3'],'Position',[220 70 420 400]);

    %  출력 포트 1 tau, 2 eta_e, 3 Inew (적분 상태 — 과제 ④ 에서 적분항 K_i*Inew 를 본다)
    out  = {'tau','Inew','eta_e'};
    port = [1 3 2];
    for k = 1:3
        add_block('simulink/Sinks/Out1', [ss '/' out{k} '_o'], ...
                  'Position',[440 100+(k-1)*90 475 130+(k-1)*90], 'Port', num2str(port(k)));
        add_line(ss, sprintf('PID3/%d',k), [out{k} '_o/1'], 'autorouting','on');
    end
    for k = 1:numel(in)
        add_line(ss, [in{k} '/1'], sprintf('PID3/%d',k), 'autorouting','on');
    end
    mk_state_out(ss, 'PID3', dly);
    Simulink.BlockDiagram.arrangeSystem(ss);
end

% =====================================================================
% 3단 · 추력 배분
% =====================================================================
function addAlloc(m, x, y)
    ss = [m '/Alloc'];
    add_block('built-in/Subsystem', ss, 'Position', [x y x+190 y+180]);

    in  = {'tau','Tp','lim'};
    cfg = {'Tp','T_pinv'; 'lim','[F_max; del_max; alloc_mode]'};
    mk_inputs(ss, in, 1, cfg, {});

    setFcn(ss, 'Allocate', [ ...
'function [Tcmd, Dcmd, sat] = Allocate(tau, Tp, lim)'                     newline ...
'%#codegen'                                                               newline ...
'% Thrust allocation for two azimuth (rotatable) thrusters.'              newline ...
'% Fossen (2011) 12.3.4 — constrained control allocation for azimuth'     newline ...
'% thrusters, solved with the EXTENDED THRUST VECTOR.'                    newline ...
'%'                                                                       newline ...
'% Step 1  f = pinv(T_e) * tau       f = [FxL FyL FxR FyR]'''             newline ...
'%         Because the thruster force is written in Cartesian components,' newline ...
'%         T_e is CONSTANT and its pseudo-inverse can be precomputed.'    newline ...
'%         There is no singular configuration to worry about.'            newline ...
'%'                                                                       newline ...
'% Step 2  Cartesian -> polar   T = |f_i|,  delta = atan2(Fy, Fx)'        newline ...
'%'                                                                       newline ...
'% Step 3  map the demand into the mechanical sector |delta| <= 45 deg'   newline ...
'%           |d| <=  45  : use as is'                                     newline ...
'%           |d| >  135  : REVERSE thrust, d -> d -+ 180'                 newline ...
'%           otherwise   : dead zone, no thrust can be produced'          newline ...
'%'                                                                       newline ...
'% Step 4  saturate the magnitude at F_max'                               newline ...
'%'                                                                       newline ...
'% lim = [F_max; delta_max; mode]'                                        newline ...
'%   mode 1 : dead zone   — demands inside the forbidden sector are'      newline ...
'%            dropped. Simple, but the realised tau is then wrong.'       newline ...
'%   mode 2 : clamp       — the angle is pushed to the nearest sector'     newline ...
'%            edge and the magnitude is scaled by cos of the angle'       newline ...
'%            error, so the useful component is kept.'                    newline ...
''                                                                        newline ...
'f = Tp * tau;'                                                           newline ...
'Fmax = lim(1);  dmax = lim(2);  mode = lim(3);'                          newline ...
''                                                                        newline ...
'Tcmd = zeros(2,1);  Dcmd = zeros(2,1);  sat = 0;'                        newline ...
'for i = 1:2'                                                             newline ...
'    fx = f(2*i-1);  fy = f(2*i);'                                        newline ...
'    Ti = sqrt(fx*fx + fy*fy);'                                           newline ...
'    di = atan2(fy, fx);'                                                 newline ...
'    ad = abs(di);'                                                       newline ...
'    if ad <= dmax'                                                       newline ...
'        To = Ti;   Do = di;'                                             newline ...
'    elseif ad >= pi - dmax'                                              newline ...
'        To = -Ti;  Do = di - sign(di)*pi;    % reverse thrust'           newline ...
'    elseif mode < 1.5'                                                   newline ...
'        To = 0;    Do = 0;                   % dead zone'                newline ...
'        sat = sat + 1;'                                                  newline ...
'    else'                                                                newline ...
'        % clamp to the nearest edge of the reachable sector'             newline ...
'        if ad <= pi/2'                                                   newline ...
'            Do = sign(di)*dmax;      To =  Ti*cos(ad - dmax);'           newline ...
'        else'                                                            newline ...
'            Do = -sign(di)*dmax;        To = -Ti*cos(pi - dmax - ad);'   newline ...
'            Do = atan2(sin(Do), cos(Do));'                               newline ...
'        end'                                                             newline ...
'        sat = sat + 1;'                                                  newline ...
'    end'                                                                 newline ...
'    if To >  Fmax, To =  Fmax; sat = sat + 1; end'                       newline ...
'    if To < -Fmax, To = -Fmax; sat = sat + 1; end'                       newline ...
'    Tcmd(i) = To;  Dcmd(i) = Do;'                                        newline ...
'end']);
    set_param([ss '/Allocate'],'Position',[220 70 420 320]);

    out = {'Tcmd','Dcmd','sat'};
    for k = 1:numel(out)
        add_block('simulink/Sinks/Out1', [ss '/' out{k}], ...
                  'Position',[520 80+(k-1)*90 555 110+(k-1)*90], 'Port', num2str(k));
        add_line(ss, sprintf('Allocate/%d',k), [out{k} '/1'], 'autorouting','on');
    end
    for k = 1:numel(in)
        add_line(ss, [in{k} '/1'], sprintf('Allocate/%d',k), 'autorouting','on');
    end
    Simulink.BlockDiagram.arrangeSystem(ss);
end

% =====================================================================
% 4단 · 추진기 (모터 + 방위 서보)
% =====================================================================
function addThrusters(m, x, y)
    ss = [m '/Thrusters'];
    add_block('built-in/Subsystem', ss, 'Position', [x y x+190 y+180]);

    in  = {'Tcmd','Dcmd','Tpre','Dpre','par'};
    cfg = {'par','[Ts_ctrl; tau_n; tau_del; del_rate]'};
    dly = {'Tpre',1,'[0;0]'; 'Dpre',2,'[0;0]'};
    mk_inputs(ss, in, 2, cfg, dly);

    setFcn(ss, 'Act', [ ...
'function [Tact, Dact, f] = Act(Tcmd, Dcmd, Tpre, Dpre, par)'            newline ...
'%#codegen'                                                              newline ...
'% Actuator dynamics of an azimuth thruster.'                            newline ...
'%   thrust  : first order lag, time constant tau_n'                     newline ...
'%   azimuth : first order lag (tau_del) whose angular RATE is capped'   newline ...
'%             at rate_max. A real pod cannot snap to a new angle.'      newline ...
'% par = [Ts; tau_n; tau_del; rate_max]'                                 newline ...
''                                                                       newline ...
'Ts = par(1); tn = par(2); td = par(3); rmax = par(4);'                  newline ...
''                                                                       newline ...
'Tact = Tpre + (Ts/tn)*(Tcmd - Tpre);'                                   newline ...
''                                                                       newline ...
'Dact = Dpre;'                                                           newline ...
'for i = 1:2'                                                            newline ...
'    dd = Dcmd(i) - Dpre(i);'                                            newline ...
'    dd = atan2(sin(dd), cos(dd));           % shortest way round'       newline ...
'    step = (Ts/td)*dd;                      % first order lag ...'      newline ...
'    lim  = rmax*Ts;                         % ... whose RATE is capped'  newline ...
'    if step >  lim, step =  lim; end'                                   newline ...
'    if step < -lim, step = -lim; end'                                   newline ...
'    Dact(i) = Dpre(i) + step;'                                          newline ...
'end'                                                                    newline ...
''                                                                       newline ...
'% back to Cartesian components in BODY'                                 newline ...
'f = [ Tact(1)*cos(Dact(1));'                                            newline ...
'      Tact(1)*sin(Dact(1));'                                            newline ...
'      Tact(2)*cos(Dact(2));'                                            newline ...
'      Tact(2)*sin(Dact(2)) ];']);
    set_param([ss '/Act'],'Position',[220 70 420 380]);

    out = {'Tact','Dact','f'};
    for k = 1:numel(out)
        add_block('simulink/Sinks/Out1', [ss '/' out{k}], ...
                  'Position',[440 100+(k-1)*90 475 130+(k-1)*90], 'Port', num2str(k));
        add_line(ss, sprintf('Act/%d',k), [out{k} '/1'], 'autorouting','on');
    end
    for k = 1:numel(in)
        add_line(ss, [in{k} '/1'], sprintf('Act/%d',k), 'autorouting','on');
    end
    mk_state_out(ss, 'Act', dly);
    Simulink.BlockDiagram.arrangeSystem(ss);
end

