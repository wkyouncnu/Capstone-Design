function build_w08_models()
% BUILD_W08_MODELS  8주차 Simulink 모델 2개를 생성한다.
%
%     W08_0_offline.slx   오프라인 WAM-V 로이터링 — Gazebo 없이 돈다
%     W08_1_vrx.slx       VRX 연동 — 운동모델만 Gazebo 로 바뀐다
%
%   7주차와 GNC 골격이 똑같다. 바뀐 것은 1단(유도)뿐이다.
%
%   LoiterVF → TurnCount → Inner Loop → Thrusters → 운동모델
%   (벡터필드)  (회전수)     (7주차와 동일)
%
%   유도법칙 출처
%     W. Jung, S. Lim, D. Lee, H. Bang,
%     "Unmanned Aircraft Vector Field Path Following with Arrival Angle Control"
%     식 (9)  극좌표 벡터필드,  식 (13) 침로 명령
%   구현 참고
%     UGV_WpFollowingAndLoitering/MILS/UGV_Control_StateFlow_260529.slx
%       의 KAIST_CircularVF, calculate_turns
%
%   모델이 깨졌을 때 이 스크립트를 다시 돌리면 복구된다.
%   실행 전에 반드시 >> W08_setup 을 먼저 실행할 것.

    here = fileparts(mfilename('fullpath'));
    addpath(fullfile(here, '..', '..', '_tools'));
    cd(here);

    if evalin('base', '~exist(''r_d'',''var'')')
        error('먼저 W08_setup 을 실행하십시오.');
    end

    build_offline();
    build_vrx();
    % 최상위 배치 — autorouting 에 맡기지 않고 규칙대로 직접 놓는다.
    % check_lines 의 일곱 항목이 전부 0 이 합격선 (references/line-routing.md)
    %  Wrap — 사슬을 접는 칸 수. 겹침 0 이 되는 것 중 가장 작은 쪽을 재서 골랐다
    lay_chain('W08_0_offline', {'Guidance','InnerLoop','Thrusters','MotionModel'}, ...
              'Boxes', {'Animate','Logging'}, 'Wrap', 2);
    lay_chain('W08_1_vrx', {'Guidance','InnerLoop','Thrusters','CmdPublisher','PoseSubscriber'}, ...
              'Boxes', {'Animate','Logging'}, 'Wrap', 3);

    %  색 — 역할표는 _tools/gnc_roles.m 하나뿐이다. 빌더는 부르기만 한다
    for mm = {'W08_0_offline','W08_1_vrx'}
        m = mm{1}; load_system(m);
        paint_roles(m);
        check_colour(m);
        mss_style(m); save_system(m); check_lines(m, false); export_diagram(m);
        close_system(m, 0);
    end
    fprintf('\n완료. 생성된 모델:\n');
    d = dir('W08_*.slx');
    for k = 1:numel(d), fprintf('  %s\n', d(k).name); end
end

% =====================================================================
% 공통 헬퍼
% =====================================================================
function fresh(m)
    try, close_system(m, 0); catch, end
    if exist([m '.slx'],'file'), delete([m '.slx']); end
    new_system(m);
end

function setFcn(sys, path, code)
    S  = sfroot;
    fpos = get_param([sys '/' path], 'Position');   % 포트가 생기며 블록이 멋대로 자란다
    ch = S.find('-isa','Stateflow.EMChart','Path',[sys '/' path]);
    ch.Script = code;
    set_param([sys '/' path], 'Position', fpos);    % 다시 놓아야 포트 위치가 저장 뒤와 같아진다 (사선 방지)
end

function C(m, name, value, x, y)
    add_block('simulink/Sources/Constant', [m '/' name], ...
              'Position', [x y x+95 y+30], 'Value', value);
end

