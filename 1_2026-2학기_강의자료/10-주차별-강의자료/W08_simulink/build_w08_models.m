function build_w08_models()
% BUILD_W08_MODELS  8주차 모델 두 개를 만든다.
%
%   W08_0_offline : Gazebo 없이 도는 틸팅 추진기 + 배분 + DP
%   W08_1_vrx     : 같은 제어기를 VRX 와 연결한 것
%
%   실행 전에 반드시 >> W08_setup 을 먼저 실행할 것.
%
%   신호 흐름 (좌 -> 우)
%     DPRef -> DPCtrl -> Alloc -> Thrusters -> MotionModel(+Env) -> 로깅

    here = fileparts(mfilename('fullpath'));
    addpath(fullfile(here, '..', '..', '_tools'));
    cd(here);

    if evalin('base', '~exist(''T_pinv'',''var'')')
        error('먼저 W08_setup 을 실행하십시오.');
    end

    build_offline();
    build_vrx();
    % 최상위 배치 — autorouting 에 맡기지 않고 규칙대로 직접 놓는다.
    % check_lines 의 일곱 항목이 전부 0 이 합격선 (references/line-routing.md)
    lay_chain('W08_0_offline', ...
              {'DPRef','WaveFilter','DPCtrl','Alloc','Thrusters','Env','MotionModel'}, ...
              'Boxes', {'Animate','Logging'}, 'Wrap', 2);
    lay_chain('W08_1_vrx', ...
              {'DPRef','WaveFilter','DPCtrl','Alloc','Thrusters','PoseSubscriber'}, ...
              'Boxes', {'CmdPublisher','Animate','Logging'}, 'Wrap', 2);

    %  색 — 역할표는 _tools/gnc_roles.m 하나뿐이다. 빌더는 부르기만 한다
    for mm = {'W08_0_offline','W08_1_vrx'}
        m = mm{1}; load_system(m);
        paint_roles(m);
        check_colour(m);
        mss_style(m); save_system(m); check_lines(m, false); export_diagram(m);
        close_system(m, 0);
    end

    fprintf('\n완료. 생성된 모델:\n');
    d = dir('*.slx');
    for k = 1:numel(d), fprintf('  %s\n', d(k).name); end
end

