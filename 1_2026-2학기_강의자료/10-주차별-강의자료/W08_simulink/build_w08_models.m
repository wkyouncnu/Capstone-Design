% =====================================================================
% 1단 · LOITER GUIDANCE — 벡터필드
% =====================================================================
function addGuidance(m, x, y)
% 1단 · GUIDANCE — 로이터 유도 전체를 상자 하나로 묶는다.
%
%   포트   x_n, y_n, beta  ->  psi_ref, gate, u_cmd
%
%   안에 들어가는 것
%     Schedule   시간에 따라 방향·속도·반경을 바꾼다 (시나리오)
%     LoiterVF   원 궤도 벡터필드 유도 — 목표 선수각을 낸다
%     TurnCount  몇 바퀴 돌았는지 세고, 다 돌면 배를 세운다
%     설정 상수와 한 스텝 지연 (ThDly · AccDly · ArmDly)
%
%   중심 좌표·반경·회전수 같은 값은 **신호가 아니라 설정**이다. 최상위에 늘어놓으면
%   상수 여덟 개와 선 여덟 개가 신호 사슬 앞을 가린다.
    ss = add_subsys(m, 'Guidance', [x y x+190 y+180], {'x_n','y_n','beta'}, ...
                    {'psi_ref','gate','u_cmd'}, gnc_colour('guidance'));
    % --- 시나리오: 시간에 따라 방향·속도·반경을 바꾼다 ---
    add_block('simulink/Sources/Digital Clock', [ss '/Clk'], ...
              'Position', [x-190 y+330 x-140 y+360], 'SampleTime','Ts_ctrl');
    add_block('simulink/User-Defined Functions/MATLAB Function', ...
              [ss '/Schedule'], 'Position', [x-100 y+240 x+40 y+400]);
    setFcn(ss, 'Schedule', [ ...
'function [pc, vd, rd] = Schedule(t, pc0, v0, rd0, use)'                newline ...
'%#codegen'                                                             newline ...
'% Change the loiter direction, speed and radius while the model runs.' newline ...
'% Direction is set by the SIGN of pc, speed by vd, radius by rd.'      newline ...
'if use < 0.5'                                                          newline ...
'    pc = pc0;   vd = v0;       rd = rd0;'                              newline ...
'elseif t < 150'                                                        newline ...
'    pc = pc0;   vd = v0;       rd = rd0;        % as configured'       newline ...
'elseif t < 300'                                                        newline ...
'    pc = -pc0;  vd = v0;       rd = rd0;        % reverse direction'   newline ...
'elseif t < 450'                                                        newline ...
'    pc = -pc0;  vd = v0*1.6;   rd = rd0;        % faster'              newline ...
'else'                                                                  newline ...
'    pc = -pc0;  vd = v0*1.6;   rd = rd0*0.6;    % tighter circle'      newline ...
'end']);

    % --- 벡터필드 유도 ---
    add_block('simulink/User-Defined Functions/MATLAB Function', ...
              [ss '/LoiterVF'], 'Position', [x+200 y x+380 y+220]);
    setFcn(ss, 'LoiterVF', [ ...
'function [psi_ref, r, theta, vf_x, vf_y] = LoiterVF(x_n, y_n, x_c, y_c, rd, vd, pc, beta, kcrab)' newline ...
'%#codegen'                                                                newline ...
'% Circular-orbit vector field guidance.'                                  newline ...
'%   Jung, Lim, Lee, Bang, "Unmanned Aircraft Vector Field Path Following' newline ...
'%   with Arrival Angle Control", eq. (9) and (13).'                       newline ...
'%'                                                                        newline ...
'%   rd  desired orbit radius [m]'                                         newline ...
'%   vd  desired speed [m/s]'                                              newline ...
'%   pc  shaping parameter.  SIGN sets the turn direction:'                newline ...
'%         pc > 0  clockwise,   pc < 0  counter-clockwise'                 newline ...
'%       A smaller |pc| pulls the vehicle harder onto the circle.'         newline ...
''                                                                         newline ...
'dx = x_n - x_c;'                                                            newline ...
'dy = y_n - y_c;'                                                            newline ...
''                                                                         newline ...
'r     = sqrt(dx*dx + dy*dy);      % distance from the centre'             newline ...
'theta = atan2(dy, dx);            % bearing of the vehicle from centre'   newline ...
'if r < 1e-6, r = 1e-6; end        % the centre itself is singular'        newline ...
''                                                                         newline ...
'% eq. (9): the field written in polar components'                         newline ...
'N = sqrt((r - rd)^2 + (pc*r)^2);'                                         newline ...
'if N < 1e-9, N = 1e-9; end'                                               newline ...
'r_dot   = -vd * (r - rd) / N;     % radial     : closes the gap'          newline ...
'rth_dot =  vd * pc * r   / N;     % tangential : goes round'              newline ...
''                                                                         newline ...
'% polar -> NED. The magnitude of this vector is always vd.'               newline ...
'vf_x = r_dot*cos(theta) - rth_dot*sin(theta);'                             newline ...
'vf_y = r_dot*sin(theta) + rth_dot*cos(theta);'                             newline ...
''                                                                         newline ...
'% eq. (13): the field gives a COURSE, i.e. a velocity direction.'         newline ...
'% The boat can only be told a HEADING. In a turn the two differ by'       newline ...
'% the crab angle beta, and that difference shows up as a radius error.'   newline ...
'%   kcrab = 0  command the field angle directly (the paper form)'         newline ...
'%   kcrab = 1  subtract beta so the VELOCITY lines up with the field'     newline ...
'chi_d   = atan2(vf_y, vf_x);'                                               newline ...
'p       = chi_d - kcrab*beta;'                                            newline ...
'psi_ref = atan2(sin(p), cos(p));']);

    % --- 회전수 세기 + 임무 종료 ---
    add_block('simulink/User-Defined Functions/MATLAB Function', ...
              [ss '/TurnCount'], 'Position', [x+470 y+260 x+660 y+470]);
    setFcn(ss, 'TurnCount', [ ...
'function [turns, gate, th_out, acc_out, armed] = TurnCount( ...'          newline ...
'         theta, r, rd, req, th_prev, acc_prev, armed_prev)'               newline ...
'%#codegen'                                                                newline ...
'% Count how many times the boat has gone round, then stop it.'            newline ...
'% Same idea as calculate_turns in the UGV Stateflow example: start'       newline ...
'% counting only after the boat has actually reached the circle,'          newline ...
'% otherwise the approach leg would be counted as part of a lap.'          newline ...
''                                                                         newline ...
'tol = 0.3*rd;                     % "on the circle": steady radius error is p_c*v*tau (up to ~7 m at p_c = 1), so the band must be wider than that'  newline ...
'th_out = theta;'                                                          newline ...
''                                                                         newline ...
'if armed_prev < 0.5'                                                      newline ...
'    acc_out = 0;'                                                         newline ...
'    if abs(r - rd) <= tol'                                                newline ...
'        armed = 1;                % reached the circle, start counting'   newline ...
'    else'                                                                 newline ...
'        armed = 0;'                                                       newline ...
'    end'                                                                  newline ...
'else'                                                                     newline ...
'    armed = 1;'                                                           newline ...
'    d = theta - th_prev;'                                                 newline ...
'    d = atan2(sin(d), cos(d));    % wrap: +pi to -pi must not count'      newline ...
'    acc_out = acc_prev + d;'                                              newline ...
'end'                                                                      newline ...
''                                                                         newline ...
'turns = abs(acc_out) / (2*pi);'                                           newline ...
''                                                                         newline ...
'% req = 0 means keep going forever'                                       newline ...
'if (req > 0) && (turns >= req)'                                           newline ...
'    gate = 0;                     % mission done, stop the boat'          newline ...
'else'                                                                     newline ...
'    gate = 1;'                                                            newline ...
'end']);

    % TurnCount 의 기억 세 개(각도·누적·무장)는 자기에게 되돌아온다.
    % 화면을 가로지르는 되먹임 선 대신 태그로 건넌다. 되먹임은 늘 이렇게 처리한다.
    d   = {'ThDly','AccDly','ArmDly'};
    tg  = {'th_prev','acc_prev','armed_prev'};
    src = [3 4 5];      % TurnCount 의 출력 포트
    dst = [5 6 7];      % TurnCount 의 입력 포트
    for k = 1:3
        drop_tag(ss, 'TurnCount', src(k), tg{k}, 150 + 60*k);

        q = port_xy(ss, 'TurnCount', 'Inport', dst(k));
        add_block('simulink/Discrete/Unit Delay', [ss '/' d{k}], ...
                  'Position', [x+300 q(2)-20 x+375 q(2)+20], ...
                  'InitialCondition','0', 'SampleTime','Ts_ctrl');
        add_block('simulink/Signal Routing/From', [ss '/Fr_' tg{k}], ...
                  'Position', [x+180 q(2)-11 x+250 q(2)+11], 'GotoTag', tg{k});
        add_line(ss, ['Fr_' tg{k} '/1'], [d{k} '/1']);              % 직선
        add_line(ss, [d{k} '/1'], sprintf('TurnCount/%d', dst(k))); % 직선
    end

    % --- 설정값 — 신호가 아니다. 상자 안에 둔다 ------------------------
    cfg = {'Pc0','p_c',  -170, 420;  'V0','u_ref',  -170, 470; ...
           'Rd0','r_d',  -170, 520;  'Sch','use_schedule', -170, 570; ...
           'Cn','center_north',  30, 620;  'Ce','center_east', 30, 670; ...
           'Kcr','crab_comp',    30, 720;  'Req','required_turns', 30, 770};
    for k = 1:size(cfg,1)
        add_block('simulink/Sources/Constant', [ss '/' cfg{k,1}], ...
                  'Position', [cfg{k,3} cfg{k,4} cfg{k,3}+90 cfg{k,4}+30], ...
                  'Value', cfg{k,2});
    end

    % --- 배선 : Schedule ------------------------------------------------
    add_line(ss,'Clk/1', 'Schedule/1','autorouting','on');
    add_line(ss,'Pc0/1', 'Schedule/2','autorouting','on');
    add_line(ss,'V0/1',  'Schedule/3','autorouting','on');
    add_line(ss,'Rd0/1', 'Schedule/4','autorouting','on');
    add_line(ss,'Sch/1', 'Schedule/5','autorouting','on');

    % --- 배선 : LoiterVF ------------------------------------------------
    add_line(ss,'x_n/1',  'LoiterVF/1','autorouting','on');
    add_line(ss,'y_n/1',  'LoiterVF/2','autorouting','on');
    add_line(ss,'Cn/1',  'LoiterVF/3','autorouting','on');
    add_line(ss,'Ce/1',  'LoiterVF/4','autorouting','on');
    add_line(ss,'Schedule/3','LoiterVF/5','autorouting','on');   % rd
    add_line(ss,'Schedule/2','LoiterVF/6','autorouting','on');   % vd
    add_line(ss,'Schedule/1','LoiterVF/7','autorouting','on');   % pc
    add_line(ss,'beta/1','LoiterVF/8','autorouting','on');
    add_line(ss,'Kcr/1', 'LoiterVF/9','autorouting','on');

    % --- 배선 : TurnCount -----------------------------------------------
    add_line(ss,'LoiterVF/3','TurnCount/1','autorouting','on');  % theta
    add_line(ss,'LoiterVF/2','TurnCount/2','autorouting','on');  % r
    add_line(ss,'Schedule/3','TurnCount/3','autorouting','on');  % rd
    add_line(ss,'Req/1',     'TurnCount/4','autorouting','on');

    % --- 출력 포트 ------------------------------------------------------
    add_line(ss,'LoiterVF/1', 'psi_ref/1','autorouting','on');
    add_line(ss,'TurnCount/2','gate/1','autorouting','on');
    add_line(ss,'Schedule/2', 'u_cmd/1','autorouting','on');

    % --- 로깅용 태그 — 상자 안에서 건다. 최상위에 태그를 늘어놓지 않는다 ---
    tg = {'LoiterVF',1,'psi_ref'; 'LoiterVF',2,'r_dist'; 'LoiterVF',3,'theta'; ...
          'LoiterVF',4,'vf_x';     'LoiterVF',5,'vf_y'; ...
          'TurnCount',1,'turns';  'TurnCount',2,'gate'; 'Schedule',2,'u_cmd'};
    for k = 1:size(tg,1)
        b = [ss '/Go_' tg{k,3}];
        add_block('simulink/Signal Routing/Goto', b, ...
                  'Position', [700 900+(k-1)*45 780 900+(k-1)*45+22], ...
                  'GotoTag', tg{k,3}, 'TagVisibility','global');
        add_line(ss, sprintf('%s/%d', tg{k,1}, tg{k,2}), ['Go_' tg{k,3} '/1'], ...
                 'autorouting','on');
    end

    Simulink.BlockDiagram.arrangeSystem(ss);
end

% =====================================================================
% 2단 · INNER LOOP — 7주차와 완전히 같다
% =====================================================================
function addInnerLoop(m, x, y)
    ss = [m '/InnerLoop'];
    add_block('built-in/Subsystem', ss, 'Position', [x y x+190 y+170]);

    in = {'psi_ref','gate','u_ref','psi','r','u'};
    for k = 1:numel(in)
        add_block('simulink/Sources/In1', [ss '/' in{k}], ...
                  'Position', [40 60+(k-1)*80 75 60+(k-1)*80+30], 'Port', num2str(k));
    end

    add_block('simulink/User-Defined Functions/MATLAB Function', ...
              [ss '/HeadingErr'], 'Position', [200 60 340 130]);
    setFcn(ss, 'HeadingErr', [ ...
'function e = HeadingErr(psi_ref, psi)'                          newline ...
'%#codegen'                                                      newline ...
'% Shortest signed angle, wrapped to [-pi, pi).'                 newline ...
'd = psi_ref - psi;'                                             newline ...
'e = atan2(sin(d), cos(d));']);

    add_block('simulink/Math Operations/Gain', [ss '/Kp_psi'], ...
              'Position', [410 60 460 100], 'Gain','Kp_psi');
    add_block('simulink/Math Operations/Gain', [ss '/Kd_rate'], ...
              'Position', [410 240 460 280], 'Gain','-Kd_psi');
    add_block('simulink/Math Operations/Sum', [ss '/SumN'], ...
              'Position', [560 110 590 150], 'Inputs','++');
    add_block('simulink/Discontinuities/Saturation', [ss '/SatN'], ...
              'Position', [650 110 690 150], ...
              'UpperLimit','2*F_max*half_beam', 'LowerLimit','-2*F_max*half_beam');

    add_line(ss,'psi_ref/1','HeadingErr/1','autorouting','on');
    add_line(ss,'psi/1',    'HeadingErr/2','autorouting','on');
    add_line(ss,'HeadingErr/1','Kp_psi/1','autorouting','on');
    add_line(ss,'r/1',        'Kd_rate/1','autorouting','on');
    add_line(ss,'Kp_psi/1', 'SumN/1','autorouting','on');
    add_line(ss,'Kd_rate/1','SumN/2','autorouting','on');
    add_line(ss,'SumN/1','SatN/1','autorouting','on');

    add_block('simulink/Math Operations/Product', [ss '/Gate'], ...
              'Position', [200 380 235 420]);
    add_block('simulink/Math Operations/Sum', [ss '/SurgeErr'], ...
              'Position', [300 385 330 415], 'Inputs','+-');
    add_block('simulink/Continuous/PID Controller', [ss '/PI_u'], ...
              'Position', [400 370 490 430]);
    set_param([ss '/PI_u'], 'Controller','PI', ...
        'TimeDomain','Discrete-time', 'SampleTime','Ts_ctrl', ...
        'P','Kp_u', 'I','Ki_u', 'LimitOutput','on', ...
        'UpperSaturationLimit','2*F_max', 'LowerSaturationLimit','-2*F_max', ...
        'AntiWindupMode','clamping');

    add_line(ss,'u_ref/1','Gate/1','autorouting','on');
    add_line(ss,'gate/1', 'Gate/2','autorouting','on');
    add_line(ss,'Gate/1','SurgeErr/1','autorouting','on');
    add_line(ss,'u/1',   'SurgeErr/2','autorouting','on');
    add_line(ss,'SurgeErr/1','PI_u/1','autorouting','on');

    add_block('simulink/User-Defined Functions/MATLAB Function', ...
              [ss '/Alloc'], 'Position', [760 230 910 340]);
    setFcn(ss, 'Alloc', [ ...
'function [FL, FR] = Alloc(X, N, half_beam, Fmax)'                newline ...
'%#codegen'                                                       newline ...
'% Differential thrust allocation for two aft thrusters.'         newline ...
'FL = X/2 + N/(2*half_beam);'                                     newline ...
'FR = X/2 - N/(2*half_beam);'                                     newline ...
'if FL >  Fmax, FL =  Fmax; end'                                  newline ...
'if FL < -Fmax, FL = -Fmax; end'                                  newline ...
'if FR >  Fmax, FR =  Fmax; end'                                  newline ...
'if FR < -Fmax, FR = -Fmax; end']);

    add_block('simulink/Sources/Constant', [ss '/HB'], ...
              'Position', [620 460 710 490], 'Value','half_beam');
    add_block('simulink/Sources/Constant', [ss '/FM'], ...
              'Position', [620 510 710 540], 'Value','F_max');
    add_block('simulink/Sinks/Out1', [ss '/FL'], 'Position',[980 250 1015 280], 'Port','1');
    add_block('simulink/Sinks/Out1', [ss '/FR'], 'Position',[980 310 1015 340], 'Port','2');

    add_line(ss,'PI_u/1','Alloc/1','autorouting','on');
    add_line(ss,'SatN/1','Alloc/2','autorouting','on');
    add_line(ss,'HB/1',  'Alloc/3','autorouting','on');
    add_line(ss,'FM/1',  'Alloc/4','autorouting','on');
    add_line(ss,'Alloc/1','FL/1','autorouting','on');
    add_line(ss,'Alloc/2','FR/1','autorouting','on');

    Simulink.BlockDiagram.arrangeSystem(ss);
end

% =====================================================================
% 3단 · THRUSTERS — 7주차와 완전히 같다
% =====================================================================
function addThrusters(m, x, y)
    ss = [m '/Thrusters'];
    add_block('built-in/Subsystem', ss, 'Position', [x y x+170 y+120]);

    add_block('simulink/Sources/In1', [ss '/FL_cmd'], 'Position',[40 60 75 90],  'Port','1');
    add_block('simulink/Sources/In1', [ss '/FR_cmd'], 'Position',[40 140 75 170],'Port','2');

    add_block('simulink/User-Defined Functions/MATLAB Function', ...
              [ss '/F2n'], 'Position', [170 70 320 160]);
    setFcn(ss, 'F2n', [ ...
'function n_cmd = F2n(FL, FR, k, n_max)'                              newline ...
'%#codegen'                                                           newline ...
'% Inverse propeller law:  F = k*n*|n|  ->  n = sign(F)*sqrt(|F|/k)'  newline ...
'F = [FL; FR];'                                                       newline ...
'n_cmd = zeros(2,1);'                                                 newline ...
'for i = 1:2'                                                         newline ...
'    ni = sign(F(i)) * sqrt(abs(F(i))/k);'                            newline ...
'    if ni >  n_max, ni =  n_max; end'                                newline ...
'    if ni < -n_max, ni = -n_max; end'                                newline ...
'    n_cmd(i) = ni;'                                                  newline ...
'end']);

    add_block('simulink/Sources/Constant', [ss '/Kp'], ...
              'Position',[40 250 130 280], 'Value','k_prop');
    add_block('simulink/Sources/Constant', [ss '/Nm'], ...
              'Position',[40 300 130 330], 'Value','n_max');

    add_block('simulink/Discrete/Discrete Transfer Fcn', [ss '/MotorLag'], ...
              'Position',[380 85 500 145]);
