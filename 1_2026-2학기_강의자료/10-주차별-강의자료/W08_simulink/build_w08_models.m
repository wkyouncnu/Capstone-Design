% 6단 · 운동모델
% =====================================================================
function addMotionModel(m, x, y)
    ss = [m '/MotionModel'];
    add_block('built-in/Subsystem', ss, 'Position', [x y x+200 y+180]);

    in  = {'f','tau_env','Te','par'};
    cfg = {'Te','T_e'; 'par','plant_par'};
    mk_inputs(ss, in, 2, cfg, {});

    setFcn(ss, 'EOM', [ ...
'function [xdot, tau_thr] = EOM(s, f, tau_env, Te, p)'                   newline ...
'%#codegen'                                                              newline ...
'% 3-DOF WAM-V equations of motion, NED — same coefficients as weeks'    newline ...
'% 7 to 9 (taken from the Gazebo VRX plugins).'                          newline ...
'% The only change is the input: the thruster force now has a sway'      newline ...
'% component, so all three degrees of freedom are actuated.'             newline ...
'%   s = [u v r N E psi]'''                                              newline ...
'%   p = [m Izz Xu Xuu Yv Yvv Nr Nrr]'''                                 newline ...
''                                                                       newline ...
'u = s(1); v = s(2); r = s(3); psi = s(6);'                              newline ...
'mm=p(1); Izz=p(2); Xu=p(3); Xuu=p(4); Yv=p(5); Yvv=p(6);'               newline ...
'Nr=p(7); Nrr=p(8);'                                                     newline ...
''                                                                       newline ...
'tau_thr = Te*f;                 % [X; Y; N] from the thrusters'         newline ...
'tau     = tau_thr + tau_env;'                                           newline ...
''                                                                       newline ...
'Dx = (Xu + Xuu*abs(u))*u;'                                              newline ...
'Dy = (Yv + Yvv*abs(v))*v;'                                              newline ...
'Dn = (Nr + Nrr*abs(r))*r;'                                              newline ...
''                                                                       newline ...
'du = (tau(1) - Dx)/mm + v*r;    % rigid-body Coriolis'                  newline ...
'dv = (tau(2) - Dy)/mm - u*r;'                                           newline ...
'dr = (tau(3) - Dn)/Izz;'                                                newline ...
''                                                                       newline ...
'xdot = [du; dv; dr;'                                                    newline ...
'        u*cos(psi) - v*sin(psi);'                                       newline ...
'        u*sin(psi) + v*cos(psi);'                                       newline ...
'        r];']);
    set_param([ss '/EOM'],'Position',[220 60 420 380]);

    add_block('simulink/Continuous/Integrator', [ss '/Integ'], ...
              'Position', [480 180 530 230], 'InitialCondition','x0');

    setFcn(ss, 'States', [ ...
'function [eta, nu, U, beta] = States(s)'                    newline ...
'%#codegen'                                                  newline ...
'nu   = s(1:3);'                                             newline ...
'eta  = s(4:6);'                                             newline ...
'U    = sqrt(s(1)*s(1) + s(2)*s(2));'                        newline ...
'beta = atan2(s(2), s(1));']);
    set_param([ss '/States'],'Position',[600 120 750 300]);

    out = {'eta','nu','U','beta','tau_thr'};
    for k = 1:numel(out)
        add_block('simulink/Sinks/Out1', [ss '/' out{k}], ...
                  'Position',[830 90+(k-1)*70 870 120+(k-1)*70], 'Port', num2str(k));
    end
    for k = 1:4
        add_line(ss, sprintf('States/%d',k), [out{k} '/1'], 'autorouting','on');
    end
    add_line(ss,'EOM/2','tau_thr/1','autorouting','on');

    for k = 1:numel(in)
        add_line(ss, [in{k} '/1'], sprintf('EOM/%d', k+1), 'autorouting','on');
    end
    add_line(ss,'EOM/1','Integ/1','autorouting','on');
    add_line(ss,'Integ/1','States/1','autorouting','on');
    % 상태 되먹임 — 화면을 가로지르는 대신 태그로 건너뛴다
    drop_tag(ss, 'Integ', 1, 'x_state', 280);
    b = port_xy(ss, 'EOM', 'Inport', 1);
    add_block('simulink/Signal Routing/From', [ss '/Fr_x_state'], ...
              'Position', [60 b(2)-11 130 b(2)+11], 'GotoTag','x_state');
    add_line(ss, 'Fr_x_state/1', 'EOM/1');
    Simulink.BlockDiagram.arrangeSystem(ss);
end

% =====================================================================
% 실시간 그림
% =====================================================================
function addAnimate(m, x, y)
% 실시간 그림 — 포트 없는 서브시스템 하나로 묶는다.
%
%   **인자 순서 = 아래 태그 순서 + t + en** 이다 (add_animate_box 규약).
%   W08_animate(eta, eta_d, eta_raw, Dact, Tact, t) 와 같아야 한다.
%   태그를 더하거나 순서를 바꾸면 그리는 함수의 인자도 함께 고칠 것.
%
%   eta_raw(계단 목표)를 함께 넘기는 이유 — 왼쪽 칸에 "시킨 곳"과 "지금 좇는
%   곳"을 둘 다 찍기 위해서다. 다섯 태그 모두 wireFront 가 이미 최상위에 건
%   Goto 이므로 **새 가지를 치지 않는다** (5주차에 가지를 쳤다가 본선이 사선이
%   되어 배선 검사가 걸린 적이 있다).
    add_animate_box(m, {'eta','eta_d','eta_raw','Dact','Tact'}, ...
                    'W08_animate', '', [x y], 'Ts_ctrl');
end

% =====================================================================
% 로깅
% =====================================================================
function addLogging(m, x, y)
% 로깅 — 포트 없는 서브시스템 하나로 묶는다. W08_plot.m 이 이 변수들을 읽는다.
    sig = {'eta','eta_d','eta_raw','eta_f','nu','eta_e','tau_cmd','tau_thr','tau_env', ...
           'Tact','Dact','sat','U','beta','I_dp'};
    add_logging_box(m, sig, sig, [x y], 'Ts_ctrl');
end

% =====================================================================
% 앞단 배선 — 두 모델이 공유한다
%   설정값과 상태 지연은 각 상자 안에 있다. 최상위에 남는 것은 신호뿐이다.
% =====================================================================
function wireFront(m)
    % --- 1단 · 목표값 : 입력이 없다. 시계와 표가 상자 안에 있다 ----------
    addDPRef(m, 400, 60);
    G(m,'eta_d',   620, 100);
    G(m,'eta_raw', 620, 160);
    add_line(m,'DPRef/1','Go_eta_d/1','autorouting','on');
    add_line(m,'DPRef/2','Go_eta_raw/1','autorouting','on');

    % --- 1.5단 · 파랑 필터 ---------------------------------------------
    addWaveFilter(m, 300, 400);
    F(m,'eta','f', 200, 420);
    F(m,'nu','f',  200, 470);
    add_line(m,'Fr_eta_f/1','WaveFilter/1','autorouting','on');
    add_line(m,'Fr_nu_f/1', 'WaveFilter/2','autorouting','on');
    G(m,'eta_f', 520, 420);
    G(m,'nu_f',  520, 470);
    add_line(m,'WaveFilter/1','Go_eta_f/1','autorouting','on');
    add_line(m,'WaveFilter/2','Go_nu_f/1','autorouting','on');

    % --- 2단 · 제어기 ---------------------------------------------------
    addDPCtrl(m, 620, 60);
    F(m,'eta_d','c', 540, 80);
    F(m,'eta_f','c', 540, 140);
    F(m,'nu_f','c',  540, 200);
    add_line(m,'Fr_eta_d_c/1','DPCtrl/1','autorouting','on');
    add_line(m,'Fr_eta_f_c/1','DPCtrl/2','autorouting','on');
    add_line(m,'Fr_nu_f_c/1', 'DPCtrl/3','autorouting','on');
    G(m,'tau_cmd', 860, 100);
    G(m,'eta_e',   860, 160);
    add_line(m,'DPCtrl/1','Go_tau_cmd/1','autorouting','on');
    add_line(m,'DPCtrl/2','Go_eta_e/1','autorouting','on');
    G(m,'I_dp',    860, 220);
    add_line(m,'DPCtrl/3','Go_I_dp/1','autorouting','on');

    % --- 3단 · 추력배분 -------------------------------------------------
    addAlloc(m, 1020, 60);
    F(m,'tau_cmd','a', 940, 80);
    add_line(m,'Fr_tau_cmd_a/1','Alloc/1','autorouting','on');
    G(m,'Tcmd', 1260, 100);
    G(m,'Dcmd', 1260, 160);
    G(m,'sat',  1260, 220);
    add_line(m,'Alloc/1','Go_Tcmd/1','autorouting','on');
    add_line(m,'Alloc/2','Go_Dcmd/1','autorouting','on');
    add_line(m,'Alloc/3','Go_sat/1','autorouting','on');

    % --- 4단 · 추진기 ---------------------------------------------------
    addThrusters(m, 1420, 60);
    F(m,'Tcmd','t', 1340, 80);
    F(m,'Dcmd','t', 1340, 140);
    add_line(m,'Fr_Tcmd_t/1','Thrusters/1','autorouting','on');
    add_line(m,'Fr_Dcmd_t/1','Thrusters/2','autorouting','on');
    G(m,'Tact', 1680, 100);
    G(m,'Dact', 1680, 160);
    G(m,'fthr', 1680, 220);
    add_line(m,'Thrusters/1','Go_Tact/1','autorouting','on');
    add_line(m,'Thrusters/2','Go_Dact/1','autorouting','on');
    add_line(m,'Thrusters/3','Go_fthr/1','autorouting','on');
end
% =====================================================================
function build_offline()
    m = 'W08_0_offline'; fresh(m);
    setSolver(m, 'T_end');

    wireFront(m);

    % --- 외란 : 바람·파랑. 설정값은 상자 안에 있다 -----------------------
    addEnv(m, 1820, 460);
    F(m,'nu','e',  1740, 540);
    F(m,'eta','e', 1740, 600);
    add_line(m,'Fr_nu_e/1', 'Env/1','autorouting','on');
    add_line(m,'Fr_eta_e/1','Env/2','autorouting','on');
    G(m,'tau_env', 2080, 500);
    add_line(m,'Env/1','Go_tau_env/1','autorouting','on');

    % --- 운동모델 -------------------------------------------------------
    addMotionModel(m, 2200, 60);
    F(m,'fthr','p',   2110, 80);
    F(m,'tau_env','p',2110, 140);
    add_line(m,'Fr_fthr_p/1','MotionModel/1','autorouting','on');
    add_line(m,'Fr_tau_env_p/1','MotionModel/2','autorouting','on');

    tags = {'eta','nu','U','beta','tau_thr'};
    for k = 1:numel(tags)
        G(m, tags{k}, 2470, 80+(k-1)*55);
        add_line(m, sprintf('MotionModel/%d',k), ['Go_' tags{k} '/1'], 'autorouting','on');
    end


    addAnimate(m, 2200, 560);
    addLogging(m, 2800, 60);

    note(m,'n1', ['W08 실습 C·D  —  오프라인 DP (Gazebo 불필요)' newline ...
        'DPRef -> WaveFilter -> DPCtrl -> Alloc -> Thrusters -> MotionModel(+Env)' newline ...
        '후방 2기가 ±45° 로 돌아가므로 3자유도가 모두 제어된다.' newline ...
        '바람·파랑 외란은 이 모델에서만 넣을 수 있다.' newline ...
        '실행 전 >> W08_setup'], 40, -140);

    save_system(m); close_system(m);
    fprintf('  W08_0_offline  생성\n');
end
% VRX 모델
% =====================================================================
function build_vrx()
    m = 'W08_1_vrx'; fresh(m);
    load_system('ros2lib');
    setSolver(m, 'T_end');

    wireFront(m);
    % --- 추력·각도 발행 : 네 토픽을 한 상자에 -----------------------------
    addCmdPub(m, [1820 60]);

    % --- 구독 + 항법 : 한 상자에 -----------------------------------------
    navCode = [ ...
'function [eta, nu, U, beta] = Nav(ex, ey, qx, qy, qz, qw, bx, by, wz, org_x, org_y)' newline ...
'%#codegen'                                                                 newline ...
'% Gazebo/ROS uses ENU with a body frame of x-forward, y-LEFT, z-UP.'       newline ...
'% Marine control uses NED with x-forward, y-STARBOARD, z-DOWN.'            newline ...
'% 첫 메시지가 도착하기 전에는 Subscribe 가 0 으로 채운 버스를 낸다.'       newline ...
'% 그대로 쓰면 위치가 스폰 원점만큼(약 568 m) 튀어 로그 첫 점이 망가진다.'  newline ...
'if ex == 0 && ey == 0'                                                     newline ...
'    eta = zeros(3,1); nu = zeros(3,1); U = 0; beta = 0;'                   newline ...
'    return'                                                                newline ...
'end'                                                                       newline ...
'x_n = ey - org_x;'                                                           newline ...
'y_n = ex - org_y;'                                                           newline ...
'yaw_enu = atan2(2*(qw*qz + qx*qy), 1 - 2*(qy*qy + qz*qz));'                newline ...
'p   = pi/2 - yaw_enu;'                                                     newline ...
'psi = atan2(sin(p), cos(p));'                                              newline ...
'u = bx;  v = -by;  r = -wz;'                                               newline ...
'eta  = [x_n; y_n; psi];'                                                     newline ...
'nu   = [u; v; r];'                                                         newline ...
'U    = sqrt(u*u + v*v);'                                                   newline ...
'beta = atan2(v, u);'];

    add_pose_subscriber(m, [2180 670], ...
        '/wamv/sensors/position/ground_truth_odometry', 'Ts_ctrl', navCode, ...
        {'eta','nu','U','beta'});

    tags = {'eta','nu','U','beta'};
    for k = 1:numel(tags)
        G(m, tags{k}, 2420, 680+(k-1)*45);
        add_line(m, sprintf('PoseSubscriber/%d',k), ['Go_' tags{k} '/1'], 'autorouting','on');
    end

    % VRX 에는 외란 모델을 넣지 않는다 — 바람은 world 가 만든다
    C(m,'ZeroEnv','[0;0;0]', 2420, 900);
    G(m,'tau_env', 2560, 900);
    add_line(m,'ZeroEnv/1','Go_tau_env/1','autorouting','on');
    C(m,'ZeroThr','[0;0;0]', 2420, 1060);
    G(m,'tau_thr', 2560, 1060);
    add_line(m,'ZeroThr/1','Go_tau_thr/1','autorouting','on');

    addAnimate(m, 2200, 1000);
    addLogging(m, 2800, 60);

