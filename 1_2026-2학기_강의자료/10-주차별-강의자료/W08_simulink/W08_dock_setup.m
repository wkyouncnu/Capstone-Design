% W08_DOCK_SETUP  8주차 실습 E 설정 — 미션 + 접안(위치제어) 단계
%
%   실행하면 접안 단계까지 붙은 오프라인 모델이 곧바로 돌고 그림이 나온다.
%
%   >> W08_dock_setup
%
%   임무: 웨이포인트 → 로이터링 → 웨이포인트 → **접안(위치제어)** → 종료
%   앞의 세 단계는 실습 A (W08_setup / W08_0_offline) 와 글자 하나까지 같다.
%   마지막 Dock 단계만 새로 붙었다.
%
%   왜 설정 파일이 따로인가
%     실습 A 의 W08_setup.m · W08_0_offline.slx 를 건드리지 않기 위해서다.
%     학생이 실습 A 를 돌린 뒤 실습 E 를 돌려도 A 의 결과가 바뀌지 않는다.
%     공통 값(웨이포인트·로이터·게인·운동모델)은 W08_setup.m 과 같은 수를 쓴다.
%
%   위치제어 부분은 6주차(동적위치제어)에서 가져온 것이다 — 새로 설계하지 않았다
%     외부루프(위치 P) · 내부루프(서지·스웨이 PI, 선수각 P–D) · 3추진기 추력배분
%     모두 6주차 구조와 게인 그대로다.

clear; clc;

%  그림 글꼴 — 한글 범례·축 이름이 깨지지 않게 못 박는다.
%  MATLAB 기본 글꼴(Helvetica 등)에는 한글 글립이 없어 네모(□) 로 나온다.
set(groot, 'defaultAxesFontName',   '맑은 고딕');
set(groot, 'defaultTextFontName',   '맑은 고딕');
set(groot, 'defaultLegendFontName', '맑은 고딕');

%% ====================================================================
%  1. 웨이포인트 경로 — 실습 A 와 같다 [m], NED
%
% > [주의] 안전 수역 N in [-28, 60],  E in [-18, 100]
%   도킹 스테이션과 접안 궤적도 이 범위 안에 든다 (아래 6절에서 확인).
%   마지막 WP5 는 (10, 90) — 실습 A 와 같은 값이다.
% =====================================================================
wp_north = [ -20   50   20   50   10 ];
wp_east  = [  20   20   55   90   90 ];

Delta = 10;     % LOS lookahead distance [m]
R_LOS = 5;      % 웨이포인트 수락반경 [m]

%% ====================================================================
%  2. 로이터링 — 실습 A 와 같다
% =====================================================================
loiter_wp     = 3;
loiter_radius = 18;
loiter_turns  = 2;
p_c           = 0.313;

u_ref = 1.5;             % 목표 속도 [m/s] — WpFollow · Loiter 공통

%% ====================================================================
%  3. 제어 게인
%     위: 선수각·서지 — 실습 A 와 같다
%     아래: 위치제어 — 6주차에서 그대로 가져왔다
% =====================================================================
Kp_psi = 400;   Kd_psi = 200;      % 선수각 P–D  (마이너스는 SumN 의 '+-' 에 있다)
Kp_u   = 300;   Ki_u   = 100;      % 서지 PI

Kp_x = 0.4;     Kp_y = 0.4;        % 위치 P (외부루프) [ (m/s) / m ]
u_max = 1.5;    v_max = 0.6;       % 외부루프 속도 지령 포화 [m/s]
Kp_v = 300;     Ki_v = 100;        % 스웨이 PI
Kb   = Ki_u / Kp_u;                % 역산 안티와인드업 계수 (6주차와 같다)

half_beam = 1.027135;              % 좌우 추진기 간 반폭 [m]
F_max     = 500;                   % 좌·우 추진기 한계 [N]
l_bow     = 0.75;                  % 선수추진기의 선체중심 앞쪽 거리 [m]
F_bow_max = 250;                   % 선수추진기 한계 [N]
bow_on    = 1;                     % 0 으로 두면 선수추진기를 끈다 (비교 실험용)

%% ====================================================================
%  4. 운동모델 계수 — 실습 A 와 같다 (한 주차에 배는 하나다)
% =====================================================================
m_usv = 211;    Izz = 653;
Xu = 100;  Xuu = 150;
Yv = 100;  Yvv = 100;
Nr = 800;  Nrr = 800;

%% ====================================================================
%  5. 추진기 모델 — 채널만 3개로 늘었다
% =====================================================================
k_prop    = 1000 * 0.004422 * 0.2^4;
n_max     = sqrt(F_max / k_prop);
n_bow_max = sqrt(F_bow_max / k_prop);
tau_n     = 0.30;

%% ====================================================================
%  6. 도킹 스테이션 — ㄷ 자 모양 접안 시설
%
%     dock_deg = 180 이면 베이가 북쪽을 등지고 **입구가 동쪽**을 본다.
%     접근점 (0, 90) 에서 서쪽으로 옆걸음해 들어간다 — 선수각을 바꾸지 않는다.
%
%     WP5 가 (-20, 90) 에서 (10, 90) 으로 바뀌었으므로 — (-20, 90) 은 육지였다 —
%     스테이션도 (-20, 75) -> (0, 80) 으로 **평행이동**했다. 방향은 그대로 180°,
%     그래서 베이 안쪽 여유는 글자 하나까지 같다 (아래 숫자 참고).
%
%     ㄷ 자 치수는 W08_dock_patch.m 에 있다 (입구 반폭 4.2 · 깊이 5.5 m)
%       벽 바깥  N in [-5.5, 5.5],  E in [73.2, 82.5]
%       베이 안  N in [-4.2, 4.2],  E in [74.5, 82.5]
%     접안 완료 자세(psi = 180°)의 선체는 N in [-2.45, 2.45], E in [78.98, 81.02]
%       → 좌우 1.75 m, 뒷벽까지 4.48 m, 입구면까지 1.48 m 여유
%
%     주변과의 거리
%       안전 수역 남쪽 끝(-28) 까지 22.5 m,  동쪽 끝(100) 까지 17.5 m
%       로이터 원(중심 (20, 55), 반경 18) 까지 최단 5.3 m
%       WP4->WP5 구간(E = 90) 에서 입구면(E = 82.5) 까지 7.5 m
% =====================================================================
dock_north =   0;      % 접안 완료 위치 (베이 안쪽) [m]
dock_east  =  80;
dock_deg   = 180;      % 접안 자세 — 선수각 [deg]
berth_side =  -1;      % +1 = 우현 접안,  -1 = 좌현 접안
L_app      =  10;      % 접근점을 입구 앞 몇 m 에 둘 것인가 [m] — 접근점 (0, 90)

R_dock = 4;            % 접근점 도달 판정 반경 [m]
R_stop = 1.5;          % 접안 완료 판정 반경 [m]

%% ====================================================================
%  7. 실시간 그림
% =====================================================================
animate       = 1;
animate_every = 0.25;
boat_scale    = 2;

%% ====================================================================
%  8. VRX 스폰 위치
% =====================================================================
origin_north =  162;   % 기본값일 뿐 — W08_dock_vrx_run 이 스폰 위치를 실측해 덮어쓴다
origin_east  = -532;

%% ====================================================================
%  9. 자동 계산 — 손대지 않아도 된다
% =====================================================================
Ts_ctrl = 0.05;

n_wp = numel(wp_north);
if loiter_wp < 2 || loiter_wp > n_wp - 1
    error('loiter_wp 는 2 이상 %d 이하여야 합니다 (마지막 웨이포인트 제외).', n_wp - 1);
end

loiter_xc = wp_north(loiter_wp);
loiter_yc = wp_east(loiter_wp);

%  추력배분 계수 묶음 — Alloc 블록이 이 벡터 하나를 받는다 (6주차와 같은 순서)
alloc_prm = [half_beam; l_bow; F_max; F_bow_max];

%  도킹 설정 묶음 — BerthRef 블록이 이 벡터 하나를 받는다
dock_q = [dock_north; dock_east; dock_deg*pi/180; L_app; berth_side; R_dock; R_stop];

%  접근점 — BerthRef 안에서 다시 계산하지만, 그림과 점검에 쓰려고 여기서도 낸다
app_north = dock_north - berth_side * L_app * sin(dock_deg*pi/180);
app_east  = dock_east  + berth_side * L_app * cos(dock_deg*pi/180);

psi_init = atan2(wp_east(1) - 0, wp_north(1) - 0);
x0 = [0.1; 0; 0; 0; 0; psi_init];

if p_c > 0, dir_name = '시계방향'; else, dir_name = '반시계방향'; end

fprintf('W08 실습 E 설정 완료\n');
fprintf('  웨이포인트 %d개\n', n_wp);
fprintf('  WP%d 도착 시 로이터링 — 반경 %g m, %g 바퀴, %s\n', ...
        loiter_wp, loiter_radius, loiter_turns, dir_name);
fprintf('  접안 위치 (x,y) = (%g, %g),  자세 %g°,  접근점 (%.1f, %.1f)\n', ...
        dock_north, dock_east, dock_deg, app_north, app_east);
fprintf('  목표 속도 %g m/s, 접안 옆걸음 한계 %g m/s\n', u_ref, v_max);

%% ====================================================================
%  10. 바로 실행
% =====================================================================
auto_run = 1;

skip_run = getappdata(0, 'W08_dock_skip_run');
if isempty(skip_run), skip_run = false; end
setappdata(0, 'W08_dock_skip_run', false);

%% ====================================================================
%  ROS 2 도메인 — WSL 의 ~/.bashrc 와 같아야 토픽이 보인다
% =====================================================================
ros_domain_id = '7';
setenv('ROS_DOMAIN_ID', ros_domain_id);
fprintf('  ROS_DOMAIN_ID = %s  (WSL 의 echo $ROS_DOMAIN_ID 와 같아야 함)\n', ros_domain_id);

if auto_run && ~skip_run
    fprintf('\n오프라인 모델 실행 중  (auto_run = 0 으로 두면 실행하지 않는다)\n');
    load_system('W08_2_dock');
    out = sim('W08_2_dock');
    W08_dock_plot(out, sprintf('WP -> 로이터(WP%d, %g바퀴) -> WP -> 접안', ...
                               loiter_wp, loiter_turns));
end
