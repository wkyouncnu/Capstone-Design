% W08_SETUP  8주차 실습 설정 — 이 파일만 고치면 된다.
%
%   실행하면 오프라인 모델이 곧바로 돌고 그림이 나온다.
%
%   >> W08_setup
%
%   한 점을 중심으로 도는 것을 로이터링(loitering)이라고 한다.
%   유도법칙은 KAIST 벡터필드 (Jung, Lim, Lee, Bang) 의 식 (9)·(13) 이다.
%   7주차 LOS 와 같은 내부루프·추진기·운동모델을 그대로 쓴다.

clear; clc;

%% ====================================================================
%  1. 로이터 중심과 반경 — 출발점 기준 상대좌표 [m], NED
%
%     배는 (0,0) 에서 출발한다. 중심까지 거리가 44.7 m 이므로
%     원 바깥에서 접근해 들어가는 모습을 볼 수 있다.
%
% > [주의] sydney_regatta 에서 안전이 확인된 수역은
%   대략 N in [-28, 60],  E in [-18, 100] 이다.
%   아래 설정이면 원이 N in [-5, 45], E in [15, 65] 를 차지한다.
% =====================================================================
center_north = 20;      % 로이터 중심 North [m]
center_east  = 40;      % 로이터 중심 East  [m]
r_d          = 25;      % 목표 반경 [m]

%% ====================================================================
%  2. 회전 방향과 속도
%
%     p_c 의 부호가 회전 방향을 정한다.  논문 III절:
%       "Positive and negative parameters generate clockwise and
%        counterclockwise vectors around the origin, respectively."
%
%     p_c 의 크기는 원에 얼마나 급하게 붙는지를 정한다.
%       |p_c| 가 작을수록 원 쪽으로 더 세게 당겨진다
% =====================================================================
p_c   = 0.313;    % > 0 시계방향,  < 0 반시계방향
u_ref = 1.5;      % 목표 속도 [m/s]

% 크랩각 보상
%   벡터필드는 "속도가 향할 방향"(침로 chi)을 준다.
%   그런데 배에는 "뱃머리 방향"(선수각 psi)밖에 지시할 수 없다.
%   선회 중에는 둘이 크랩각 beta 만큼 어긋나고, 그만큼 반경 오차가 생긴다.
%     0 = 논문 그대로 (필드 각도를 선수각으로 지시)
%     1 = psi_ref = chi_d - beta 로 보정
crab_comp = 0;

% p_c 를 왜 0.313 으로 두는가 — 논문 식 (28) 로 계산한 값이다
%   특성방정식  s^2 + (1/tau_r) s + v/(p_c r_d tau_r) = 0
%   -> omega_c = sqrt( v / (p_c r_d tau_r) )
%      zeta_c  = 0.5 * sqrt( p_c r_d / (v tau_r) )
%   원하는 감쇠비 zeta_c 로 뒤집으면
%      p_c = 4 * zeta_c^2 * v * tau_r / r_d
%   본 모델의 헤딩 루프는 omega_n = 0.783, zeta = 0.978 이므로 tau_r = 1.31 s
%   zeta_c = 1 을 원하면  p_c = 4*1*1.5*1.31/25 = 0.313
%   (논문의 UAV 값 0.33 은 v=25, r_d=150, tau_r=0.5 로 계산한 것이다)

%% ====================================================================
%  3. 임무 종료 — 몇 바퀴 돌고 멈출 것인가
%     MILS 예제(UGV_Control_StateFlow) 의 StartMission2 -> StopMission2
%     전이 조건 number_of_turn >= required_number_of_turn 과 같다.
% =====================================================================
required_turns = 2;     % 0 으로 두면 멈추지 않고 계속 돈다

%% ====================================================================
%  4. 시나리오 — 도는 도중에 방향·속도·반경을 바꿔 본다
%     1 로 두면 시간에 따라 아래 순서로 바뀐다.
% =====================================================================
use_schedule = 0;       % 0 = 위 설정 그대로,  1 = 아래 4단계

%   구간          방향        속도          반경
%   0 ~ 150 s     그대로      u_ref         r_d
%   150 ~ 300 s   반전        u_ref         r_d
%   300 ~ 450 s   반전        u_ref * 1.6   r_d
%   450 s ~       반전        u_ref * 1.6   r_d * 0.6

%% ====================================================================
%  5. 제어 게인 — 7주차와 완전히 같다
% =====================================================================
Kp_psi = 400;   Kd_psi = 200;      % 헤딩 P-D 요각속도 되먹임
Kp_u   = 300;   Ki_u   = 100;      % 속도 PI (u 되먹임)

half_beam = 1.027135;   % 후방 2추진기 좌우 반폭 [m]
F_max     = 500;        % 추력 포화 [N]

%% ====================================================================
%  6. 운동모델 계수 — Gazebo 와 같은 값 (7주차와 동일)
% =====================================================================
m_usv = 211;    Izz = 653;
Xu = 100;  Xuu = 150;
Yv = 100;  Yvv = 100;
Nr = 800;  Nrr = 800;

%% ====================================================================
%  7. 추진기(프로펠러 + 모터) 모델 — 7주차와 동일
% =====================================================================
k_prop = 1000 * 0.004422 * 0.2^4;   % 0.0070752 [N/(rad/s)^2]
n_max  = sqrt(F_max / k_prop);
tau_n  = 0.30;

%% ====================================================================
%  8. 실시간 그림
% =====================================================================
animate       = 1;      % 1 = 켬, 0 = 끔
animate_every = 0.25;   % 다시 그리는 간격 [시뮬 초]
boat_scale    = 1.5;    % 선체 확대 배율 (원이 작으므로 7주차보다 작게)

%% ====================================================================
%  9. VRX 스폰 위치 (실습 C 에서만 씀)
% =====================================================================
origin_north =  200;
origin_east  = -532;

%% ====================================================================
% 10. 자동 계산 — 손대지 않아도 된다
% =====================================================================
Ts_ctrl = 0.05;

% 처음에는 중심을 바라보게 둔다
psi_init = atan2(center_east - 0, center_north - 0);
x0 = [0.1; 0; 0; 0; 0; psi_init];     % [u v r N E psi]'

if p_c > 0, dir_name = '시계방향'; else, dir_name = '반시계방향'; end

fprintf('W08 설정 완료\n');
fprintf('  로이터 중심 (N,E) = (%g, %g),  반경 %g m\n', center_north, center_east, r_d);
fprintf('  p_c = %+.3f  ->  %s,  목표 속도 %g m/s\n', p_c, dir_name, u_ref);
if required_turns > 0
    fprintf('  %g 바퀴 돌면 정지\n', required_turns);
else
    fprintf('  계속 회전 (정지 조건 없음)\n');
end
if use_schedule
    fprintf('  시나리오 켜짐 — 도중에 방향·속도·반경이 바뀐다\n');
end

%% ====================================================================
% 11. 바로 실행
% =====================================================================
auto_run = 1;

skip_run = getappdata(0, 'W08_skip_run');
if isempty(skip_run), skip_run = false; end
setappdata(0, 'W08_skip_run', false);

if auto_run && ~skip_run
    fprintf('\n오프라인 모델 실행 중  (auto_run = 0 으로 두면 실행하지 않는다)\n');
    load_system('W08_0_offline');
    out = sim('W08_0_offline');
    W08_plot(out, sprintf('%s / r_d = %g m / u = %g m/s', dir_name, r_d, u_ref));
end
