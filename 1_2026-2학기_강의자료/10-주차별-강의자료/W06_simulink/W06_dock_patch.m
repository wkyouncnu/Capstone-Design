function [X, Y, inX, inY, mouthX, mouthY] = W06_dock_patch(dx, dy, dpsi, sd)
%W06_DOCK_PATCH  ㄷ 자 도킹 스테이션의 외곽선 — 애니메이션과 결과 그림이 같이 쓴다.
%
%   [X, Y] = W06_dock_patch(dx, dy, dpsi, sd)
%
%   입력 — 전부 W06_setup 의 선석 설정 그대로다
%     dx, dy    선석 위치 (북 x, 동 y) [m]   — 배가 **최종적으로 서는 자리**
%     dpsi      선석 방위 psi_t [rad]        — 부두가 뻗은 방향
%     sd        접안 방향 s (+1 / -1)        — 배가 부두의 어느 쪽에서 들어오는가
%
%   출력
%     X, Y        ㄷ 자 벽 다각형 (patch 로 바로 그린다). 북 x · 동 y [m]
%     inX, inY    베이 **안쪽** 네모 (물이 있는 칸). 궤적이 여기 안에 있어야 한다
%     mouthX, mouthY   베이 입구 중심선 두 점 — 계획 경로를 여기로 통과시킨다
%
%   왜 띠 하나가 아니라 ㄷ 자인가
%     텀프로젝트 과제의 도킹 스테이션(VRX dock_2022)은 세 면이 막힌 **베이**다.
%     직선 띠로 그리면 "배가 부두 옆에 와서 섰다" 까지만 보이고, 정작 채점 기준인
%     "베이 **안으로** 들어갔는가" 가 그림에 나오지 않는다. 세 면을 그려야
%     궤적이 날개 벽을 뚫고 지나가는지가 눈에 보인다.
%
%   좌표 — 선석을 원점으로 한 (a, b) 를 쓰고 마지막에 NED 로 되돌린다
%     a = 부두를 따라가는 쪽   (단위벡터 t = [cos dpsi, sin dpsi])
%     b = 부두에서 바다로 나가는 쪽 (단위벡터 n = sd*[-sin dpsi, cos dpsi])
%     이렇게 두면 psi_t 와 s 가 어떤 값이어도 아래 치수표를 손대지 않아도 된다.
%
%   치수 — 짐작이 아니라 **궤적을 재서** 정했다 (WAM-V 전장 4.9 m · 전폭 2.05 m)
%     옆걸음 접안(5단)은 배가 부두와 나란히 누운 채 들어오므로 **폭**이 문제이고,
%     전진 접안(7단)은 뱃머리부터 들어오므로 **깊이**가 문제다. 두 전략을 돌려
%     선체 네 귀퉁이가 실제로 어디까지 갔는지 재고, 거기에 여유를 더해 잡았다.
%
%       재어 보니                        | 벽 자리  | 남는 여유
%       5단 귀퉁이 좌우  |a| <= 2.45 m   | H  = 4.2 | 1.75 m
%       7단 뱃머리 깊이   b  >= -4.16 m   | K  = 5.5 | 1.34 m
%
%     7단의 끝 위치 오차가 1.713 m 라 중심이 선석보다 더 들어가고, 거기에
%     반길이 2.45 m 가 더해져 뱃머리가 -4.16 m 까지 간다. 깊이를 반길이로만
%     잡으면(K = 2.45) 뱃머리가 안쪽 벽을 뚫는다.

H = 4.2;      % 입구 반폭   [m]  — 선석에서 부두 따라 양옆
K = 5.5;      % 베이 깊이   [m]  — 선석에서 안쪽 벽까지
Lw = 2.5;     % 날개 길이   [m]  — 선석에서 바다 쪽으로 뻗은 두 벽. 아래 메모 참고
W = 1.3;      % 벽 두께     [m]

%   날개를 왜 짧게 두는가 — 이것도 재서 정했다
%     날개를 7 m 로 길게 뽑아 놓고 5단을 돌리면, 배가 접근점으로 사선으로
%     올라오는 42.1 ~ 46.9 s 구간에서 선체 귀퉁이가 **왼쪽 날개 끝단을 스친다**
%     (벽까지 남은 여유 0.022 m, 63 스텝 침범). 안쪽 벽은 건드리지 않는다 —
%     접근로를 막는 것은 깊이가 아니라 바다로 뻗은 날개 길이다.
%     Lw = 2.5 m 로 줄이면 같은 궤적이 날개 바깥을 여유 있게 비껴 간다.
%     실제 도크도 날개가 베이 깊이보다 길지 않다 — 입구 턱 정도다.

% ---- ㄷ 자 한붓그리기 : 바깥 둘레를 돌고 입구에서 안쪽 둘레로 되돌아온다 ----
%   (a, b) 순서. 입구는 b = +Lw 쪽이 열려 있다
a = [-H-W, -H-W, H+W, H+W,  H,  H, -H, -H];
b = [  Lw,  -K-W, -K-W,  Lw, Lw, -K, -K,  Lw];

% ---- 안쪽 칸 (물) ----
ai = [-H,  H,  H, -H];
bi = [-K, -K, Lw, Lw];

% ---- 입구 중심선 : 바깥 Lw 에서 선석까지 ----
am = [0, 0];
bm = [Lw, 0];

% ---- (a, b) -> NED ----
tx = cos(dpsi);        ty = sin(dpsi);
nx = -sd*sin(dpsi);    ny =  sd*cos(dpsi);

X = dx + a*tx + b*nx;        Y = dy + a*ty + b*ny;
inX = dx + ai*tx + bi*nx;    inY = dy + ai*ty + bi*ny;
mouthX = dx + am*tx + bm*nx; mouthY = dy + am*ty + bm*ny;
end
