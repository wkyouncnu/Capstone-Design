% W06_SETUP  6주차 실습 설정 — 이 파일만 고치면 된다.
%
%   모델을 열기 전에 반드시 이 스크립트를 먼저 실행한다.
%   Simulink 의 Constant 블록들이 여기서 만든 변수 이름을 그대로 참조한다.
%
%   >> W06_setup                 % stage 를 고르고 그 단계 모델을 돌린다
%
%   5주차와 달라진 것 하나 — 선수추진기(bow thruster)
%     5주차 : 추진기 2개. 낼 수 있는 힘은 X(전후) 와 N(요) 둘. 횡방향은 못 낸다
%     6주차 : 추진기 3개. X · Y(횡) · N 셋을 독립으로 낸다 -> 제자리 횡이동과
%             "정해진 위치 + 정해진 선수각" 유지가 된다

clear; clc;

%% ====================================================================
%  1. 단계 선택 — 쉬운 모델부터 하나씩 쌓는다
%
%     한 단계에 새로 생기는 것은 **하나**다. 1단을 이해하고 2단으로 간다.
%
%     stage  모델              이번에 새로 생기는 것
%     -----  ----------------  ---------------------------------------------
%       1    W06_1_point       위치 고리 + 속도 고리 + 선수각 고리 + 추력배분
%       2    W06_2_sway        선수추진기 on/off 스위치 (순수 횡이동)
%       3    W06_3_thrust      추진기 동역학 (추력<->회전수, 모터 지연, 포화)
%       4    W06_4_stop        도착 판정과 정지 게이트
%       5    W06_5_dock        단계 전이 (접근 -> 선수각 정렬 -> 횡이동 접안)
%       6    W06_6_vrx         Gazebo 연동 (운동모델만 실물로 바뀐다)
%       7    W06_7_front       전진 접안 (bow-first)
%       8    W06_8_ned         NED 좌표계 위치제어 접안
% =====================================================================
stage = 1;

%  아래 세 줄은 여러 단계를 잇달아 돌리는 검증 스크립트만 쓰는 뒷문이다.
%  평소에는 비어 있으므로 위의 한 줄이 그대로 단계를 정한다. 한 번 쓰면
%  지워지므로 그다음 W06_setup 은 다시 위의 값을 따른다.
%      setappdata(0, 'W06_stage', 5)    % 다음 W06_setup 한 번만 5단으로
if ~isempty(getappdata(0, 'W06_stage'))
    stage = getappdata(0, 'W06_stage');
    rmappdata(0, 'W06_stage');
end

%% ====================================================================
%  2. 목표
%
% > [주의] 이 좌표 범위를 크게 벗어나면 배가 육지에 얹힌다.
%   sydney_regatta 에서 스폰 기준으로 안전이 확인된 수역은
%   대략 N in [-28, 60],  E in [-18, 100] 이다 (5주차와 같은 값).
% =====================================================================
% (1단·3단·4단) 한 점·한 선수각 — 거기로 가서 그 자세로 선다
hold_north =  30;    % 목표 x (북쪽) [m]
hold_east  =  20;    % 목표 y (동쪽) [m]
hold_deg   =  45;    % 목표 선수각 [deg, NED. 0 = 북, 90 = 동]

% (2단) 순수 횡이동 — 선수각을 묶어 둔 채 옆으로만 간다
sway_north =   0;    % 목표 x [m] — 0 이면 북쪽으로는 움직이지 않는다
sway_east  =  12;    % 목표 y [m]
sway_deg   =   0;    % 묶어 둘 선수각 [deg]

% (5단·6단) 접안 — 옆걸음으로 붙인다 (lateral approach)
dock_north =  40;    % 선석(berth) 위치 x [m]
dock_east  =  45;    % 선석 위치 y [m]
dock_deg   =   0;    % 선석에 붙었을 때의 선수각 [deg] = 부두 방향
berth_side =  +1;    % +1 = 부두가 좌현쪽(열린 물은 우현),  -1 = 반대
L_app      =  15;    % 접근점을 선석에서 몇 m 옆에 둘 것인가 [m]
R_dock     =   4;    % 접근점에 이만큼 들어오면 다음 단계로 넘어간다 [m]
%
%   접근점 = 선석 + berth_side * L_app * (선석 방위의 오른쪽 수직방향)
%          = (40, 45) + 1 * 15 * (-sin 0, cos 0) = (40, 60)
%   배는 (0,0) -> 접근점 (40,60) 까지 뱃머리를 돌려 전진하고, 거기서 선수각을
%   0 deg 로 맞춘 뒤 **서쪽으로 15 m 횡이동**해 (40,45) 에 붙는다.
%   마지막 15 m 에서 선수각이 변하지 않는 것이 이 주차의 결과 그림이다.
%
% > 선석은 **그림에만 있는 가상의 부두**다. sydney_regatta 월드의 실제 도크
%   위치를 재서 쓴 값이 아니다. 좌표만 바꾸면 실제 도크로 옮길 수 있다.

R_stop = 1.5;        % 목표점에서 이만큼 안으로 들어오면 도착으로 본다 [m]

%% ====================================================================
%  3. 선수추진기 스위치 (2단에서 생긴다)
%
%     bow_on = 1  선수추진기를 쓴다
%     bow_on = 0  횡력 지령을 끊는다 — 추진기 둘뿐인 5주차의 배가 된다
%
%     2단 실습은 같은 목표를 두 값으로 각각 돌려 그림을 겹쳐 보는 것이다.
%     0 으로 두면 동쪽으로 12 m 가 끝까지 줄지 않는다. 옆으로 밀 힘이 없기
%     때문이다 (선수각은 그대로 잡힌다 — 요 모멘트는 좌·우 추진기로 낸다).
% =====================================================================
bow_on = 1;

%% ====================================================================
%  4. 제어 게인 — 바깥(위치)·안(속도)·선수각 세 고리
%     여덟 단계가 전부 같은 값을 쓴다. 오프라인 플랜트가 Gazebo 와 같은
%     계수로 만들어져 있기 때문이다.
%
%     바깥 고리 : 위치 오차 -> 속도 지령         (P 제어, 지령을 포화시킨다)
%     안쪽 고리 : 속도 오차 -> 추력              (PI 제어, anti-windup)
%     선수각    : 선수각 오차 -> 요 모멘트       (P-D, 요각속도 되먹임)
%
%     위치 오차를 바로 추력으로 바꾸지 않고 속도 지령을 거치는 까닭
%       (1) u_max · v_max 로 접근 속도를 직접 묶을 수 있다. 접안에서 꼭 필요하다
%       (2) 멀리 있을 때 추력이 포화된 채로 적분기가 쌓이는 일이 없다
%       (3) 5주차의 속도 PI 를 그대로 다시 쓴다 — 새로 배울 것이 한 고리뿐이다
% =====================================================================
Kp_x = 0.4;     % 전후 위치 오차 -> 서지 속도 지령 [1/s]
Kp_y = 0.4;     % 횡   위치 오차 -> 스웨이 속도 지령 [1/s]
u_max = 1.5;    % 서지 속도 지령 포화 [m/s]
v_max = 0.6;    % 스웨이 속도 지령 포화 [m/s]
%   왜 v_max 가 u_max 보다 작은가
%     횡방향은 선수추진기 하나로만 낸다. 0.6 m/s 를 유지하는 데 드는 힘은
%       Y = (Yv + Yvv*0.6)*0.6 = (100 + 60)*0.6 = 96 N
%     F_bow_max = 250 N 안에 들어간다. 1.2 m/s 로 올리면 (100+120)*1.2 = 264 N
%     으로 한계를 넘어 지령을 따라가지 못한다.

Kp_u = 300;     Ki_u = 100;      % 안쪽 고리 — 전후 속도 PI
Kp_v = 300;     Ki_v = 100;      % 안쪽 고리 — 횡 속도 PI
Kp_psi = 400;   Kd_psi = 200;    % 선수각 P-D:  tau_N = Kp*ssa(psi_d-psi) - Kd*r

%  (8단만) NED 좌표계 위치제어의 게인 — 실험실 논문 식 (13)·(15)
%    논문은 NED 전략의 위치 제어기에 임무 제어기와 **따로** 둔 게인을 쓴다.
%    NED 축에는 서지와 스웨이가 섞여 들어가므로 어느 한쪽의 게인을 그대로
%    쓸 근거가 없기 때문이다. 여기서는 숫자를 위의 선체고정 게인과 맞춰
%    두었다 — 두 전략의 차이가 게인이 아니라 **구조**에서 오게 하려는 것이다.
Kp_ned = 0.4;                    % NED 위치 오차 -> NED 속도 지령 [1/s]
Kp_vn  = 300;   Ki_vn = 100;     % NED 속도 PI (북·동 두 축에 같은 게인)
V_ned_max = v_max;               % NED 속도 지령의 **크기** 한계 [m/s]
%    왜 u_max 가 아니라 v_max 인가
%      NED 축은 그 속도를 어느 추진기가 내는지 모른다. 북쪽으로 1.5 m/s 를
%      지시해도 선수가 동쪽을 보고 있으면 그것은 횡방향 1.5 m/s 이고, 선수
%      추진기 하나로는 낼 수 없다. 느린 축의 한계로 묶어야 안전하다.

%% ====================================================================
%  5. 추진기 배치와 추력배분
%
%     선체 고정 좌표 (x 앞, y 우현, N 시계방향 +) 에서
%
%       | X |   | 1    1    0  | | F_L |        b  = half_beam
%       | Y | = | 0    0    1  | | F_R |        l3 = 선수추진기의 x 위치
%       | N |   | b   -b    l3 | | F_B |
%
%     세 식 세 미지수이므로 손으로 풀린다 (역행렬을 외울 필요가 없다)
%
%       F_B = Y
%       F_L = X/2 + (N - l3*Y) / (2b)
%       F_R = X/2 - (N - l3*Y) / (2b)
%
%     -l3*Y 항이 이 주차의 핵심이다. 선수추진기는 선수(앞쪽)에 있으므로
%     횡력을 내면 반드시 요 모멘트도 같이 낸다. 그 몫을 좌·우 추진기가
%     반대 부호로 상쇄해 주어야 비로소 **선수각이 변하지 않는 횡이동**이 된다.
%
%     Gazebo 실측으로 확인한 부호 (6주차 2-5, measure_bow.sh · measure_sway.sh)
%       선수추진기 +지령 -> 우현(NED +y) 으로 밀고 요도 +시계 방향
%       tau = [0, +250, 0] 을 배분하면 요가 유지된 채 우현으로만 간다
% =====================================================================
half_beam = 1.027135;   % 선미 좌·우 추진기의 좌우 반폭 [m]
l_bow     = 0.75;       % 선수추진기의 x 위치 [m] (선체 중심에서 앞으로)
F_max     = 500;        % 선미 추진기 추력 포화 [N] (5주차와 같다)
F_bow_max = 250;        % 선수추진기 추력 포화 [N]
%   선수추진기를 250 N 으로 둔 까닭
%     실제 선박의 선수추진기는 주기관보다 작다. 또 횡방향 권한을 일부러
%     좁혀 두면 "배분이 한계에 걸리면 어떻게 되는가" 를 실습에서 볼 수 있다.
%     VRX 플러그인의 물리 한계는 추진기마다 2353.6 N 이므로 둘 다 현실적이다.

%% ====================================================================
%  6. 오프라인 플랜트 계수 — Gazebo 와 같은 값
%     출처: wamv_gazebo_dynamics_plugin.xacro (SimpleHydrodynamics)
%           wamv_base.urdf.xacro (질량·관성)
% =====================================================================
m_usv  = 226.5;  % 총 질량 [kg] = base_link 180 + 엔진 3x15 + 프로펠러 3x0.5
Izz    = 653;    % 요 관성 [kg m^2]
%   선수추진기(엔진 15 kg + 프로펠러 0.5 kg) 가 x = +0.75 m 에 붙었다.
%   5주차의 211 kg 에 15.5 kg 을 더해 226.5 kg 이다.
%   요 관성은 5주차 값을 그대로 쓴다 — 선수추진기가 중심선(y=0) 에 있어
%   더해지는 몫이 15.5 * 0.75^2 = 8.7 kg m^2 로 653 의 1.3 % 다.

Xu = 100;  Xuu = 150;    % surge 항력  -(Xu + Xuu|u|)u
Yv = 100;  Yvv = 100;    % sway  항력  -(Yv + Yvv|v|)v
Nr = 800;  Nrr = 800;    % yaw   항력  -(Nr + Nrr|r|)r
% 부가질량은 VRX 설정에서 xDotU = yDotV = nDotR = 0 이다

%% ====================================================================
%  7. 추진기(프로펠러 + 모터) 모델 — 3단에서 모델에 들어간다
%
%       F_cmd  ->  n_cmd = sign(F)*sqrt(|F|/k)   (역 프로펠러 법칙)
%              ->  회전수 포화  |n| <= n_max
%              ->  1차 지연 (모터 응답)  tau_n
%              ->  F = k * n * |n|              (정 프로펠러 법칙)
%
%     VRX 의 추력 토픽은 **뉴턴**을 받는다. 위 변환은 Gazebo 가 요구하는 것이
%     아니라 모터가 즉시 힘을 내지 못하는 사실을 제어기 쪽에서 모사하는 것이다.
%       k = rho * Ct * D^4 = 1000 * 0.004422 * 0.2^4
% =====================================================================
k_prop = 1000 * 0.004422 * 0.2^4;   % 0.0070752 [N/(rad/s)^2]
n_max  = sqrt(F_max / k_prop);      % 266 rad/s (약 2540 rpm), F_max=500 기준
tau_n  = 0.30;                      % 모터 시상수 [s] (tau_n >= Ts_ctrl)

%% ====================================================================
%  8. 조류 — 오프라인 모델에서만 동작한다
%     VRX 에는 해류 플러그인이 없다.
%
%     6주차에서 조류는 전시용이 아니다. 접안에서 옆조류를 받으면 선수추진기
%     없이는 선석에 붙일 수 없다 — 그것을 눈으로 보는 실험이다.
% =====================================================================
current_speed     = 0.0;    % 조류 속도 [m/s]      (0.3 쯤 주고 다시 돌려 볼 것)
current_direction = 0.0;    % 흘러가는 방향 [deg, NED. 0 = 북]

%% ====================================================================
%  9. 실시간 그림
% =====================================================================
animate       = 1;      % 1 = 켬,  0 = 끔 (끄면 훨씬 빨리 돈다)
animate_every = 0.25;   % 몇 초마다 다시 그릴 것인가 [시뮬레이션 초]
boat_scale    = 3;      % 선체를 몇 배로 크게 그릴 것인가 (1 = 실제 전장 4.9 m)

%% ====================================================================
%  10. VRX 스폰 위치 — 상대좌표를 절대좌표로 옮기는 기준점 (6단)
%     아래 값은 이 설치에서 실제로 잰 스폰 위치다 — ground truth 첫 샘플이
%     ENU (x, y) = (-532.02, 200.00), yaw = +57.30 deg 였다 (2026-10-14 측정).
%     설치마다 다를 수 있으므로 W06_vrx_run 이 첫 샘플로 덮어쓴다.
% =====================================================================
origin_north =  200;
origin_east  = -532;

%% ====================================================================
%  11. 실행 길이와 자동 정지 (4단부터 AutoStop 이 쓴다)
%      목표점 안(R_stop)에 들어오면 gate 가 0 이 되고 stop_hold 초 뒤 멈춘다.
%      바로 멈추지 않는 까닭 — 도착해서 서 있는 모습이 그래프에 남아야 읽을 수 있다.
% =====================================================================
T_run     = 300;    % 최대 실행 시간 [s] — AutoStop 이 안 걸릴 때를 받친다
stop_hold = 15;     % 임무가 끝난 뒤 더 도는 시간 [s]

%% ====================================================================
%  12. 자동 계산 — 손대지 않아도 된다
% =====================================================================
Ts_ctrl = 0.05;                          % 제어 주기 [s]
beta_c  = deg2rad(current_direction);    % 조류 방향 [rad]

model_name = {'W06_1_point','W06_2_sway','W06_3_thrust','W06_4_stop', ...
              'W06_5_dock', 'W06_6_vrx', 'W06_7_front','W06_8_ned'};
stage_name = {'목표 자세로 가서 선다','순수 횡이동','추진기 동역학','도착 판정과 정지', ...
              '접안 (옆걸음)','Gazebo 연동','전진 접안','NED 위치제어 접안'};
mdl = model_name{stage};

% 단계별 목표와 초기 선수각
switch stage
    case 2                                   % 순수 횡이동
        x_d = sway_north;  y_d = sway_east;  psi_d = deg2rad(sway_deg);
        psi_init = psi_d;                    % 이미 목표 선수각으로 서 있다
    otherwise                                % 1·3·4 단 — 한 점으로 간다
        x_d = hold_north;  y_d = hold_east;  psi_d = deg2rad(hold_deg);
        psi_init = atan2(y_d, x_d);          % 목표점을 향해 선다
end

% 과업 고르기 — 유도부(5단 이상)와 그림·애니메이션이 함께 읽는다
%   1  한 점에 그 자세로 서 있기 (1·3·4단의 목표는 hold_*)
%   2  순수 횡이동           (2단의 목표는 sway_*)
%   3  접안                  (5단 이상, 목표는 dock_* 과 접근점)
% 단계에 맞춰 두어야 W06_plot 과 W06_animate 가 **그 단계의 목표**를 그린다
if stage == 2
    task_mode = 2;
elseif stage <= 4
    task_mode = 1;
else
    task_mode = 3;
end

% 접안 단계의 유도부가 한 줄로 받는 설정 묶음 — 순서가 곧 q(1..13)
task_q = [ hold_north;  hold_east;  deg2rad(hold_deg);
           sway_north;  sway_east;  deg2rad(sway_deg);
           dock_north;  dock_east;  deg2rad(dock_deg);
           R_dock;      L_app;      berth_side;      R_stop ];

% 접근점 — 그림과 초기 선수각 계산에 쓴다 (유도부 안의 식과 같다)
app_north = dock_north - berth_side * L_app * sin(deg2rad(dock_deg));
app_east  = dock_east  + berth_side * L_app * cos(deg2rad(dock_deg));
if stage >= 5
    psi_init = atan2(app_east, app_north);   % 접근점을 향해 선다
end

% 오프라인 모델 초기 상태 [u v r x_n y_n psi]'
% VRX 와 맞추기 위해 원점 (0,0) 에서 출발한다
x0 = [0.1; 0; 0; 0; 0; psi_init];

fprintf('W06 설정 완료\n');
fprintf('  %d단  %s  —  %s\n', stage, mdl, stage_name{stage});
if stage <= 4
    fprintf('  목표 (N,E) = (%g, %g) m,  선수각 %g deg\n', x_d, y_d, rad2deg(psi_d));
else
    fprintf('  선석 (N,E) = (%g, %g) m,  선수각 %g deg\n', ...
            dock_north, dock_east, dock_deg);
    fprintf('  접근점     = (%g, %g) m,  전환반경 %g m\n', ...
            app_north, app_east, R_dock);
    if stage == 7
        fprintf('  접안 선수각 : %g deg  — 전진 접안이라 선석 방위에 수직\n', ...
                dock_deg - berth_side*90);
    end
    if stage == 8
        fprintf('  제어 좌표계 : NED  — 위치 PI 가 북·동 축에서 돔 (5단은 선체고정)\n');
        fprintf('  NED 게인   : Kp_ned = %g,  속도 PI %g / %g,  크기 한계 %g m/s\n', ...
                Kp_ned, Kp_vn, Ki_vn, V_ned_max);
    end
end
if stage >= 2
    fprintf('  선수추진기 : bow_on = %d\n', bow_on);
end
fprintf('  속도 한계  : u_max = %g m/s,  v_max = %g m/s\n', u_max, v_max);
fprintf('  추력 한계  : 선미 %g N,  선수 %g N\n', F_max, F_bow_max);
fprintf('  조류 = %g m/s @ %g deg  (오프라인 모델에서만 적용)\n', ...
        current_speed, current_direction);

%% ====================================================================
%  ROS 2 도메인 — WSL 의 ~/.bashrc 와 같아야 토픽이 보인다 (6단에서 쓴다)
%    WSL 터미널에서  echo $ROS_DOMAIN_ID
%    본 과목은 전 주차 7. 자기 팀 번호로 바꿀 때는 WSL 쪽도 같이 바꾼다
% =====================================================================
ros_domain_id = '7';
setenv('ROS_DOMAIN_ID', ros_domain_id);
fprintf('  ROS_DOMAIN_ID = %s  (WSL 의 echo $ROS_DOMAIN_ID 와 같아야 함)\n', ros_domain_id);

%% ====================================================================
%  13. 바로 실행
%      설정만 바꾸고 직접 Run 하고 싶으면 auto_run = 0 으로 둘 것.
% =====================================================================
auto_run = 1;

skip_run = getappdata(0, 'W06_skip_run');
if isempty(skip_run), skip_run = false; end
setappdata(0, 'W06_skip_run', false);

if auto_run && ~skip_run && exist([mdl '.slx'], 'file')
    fprintf('\n%s 실행 중  (auto_run = 0 으로 두면 실행하지 않는다)\n', mdl);
    if animate
        fprintf('  실시간 그림 켜짐 — 새 창이 열린다. 끄려면 animate = 0\n');
    end
    load_system(mdl);
    out = sim(mdl);
    W06_plot(out, sprintf('%d단 — %s', stage, stage_name{stage}));
end
