% A2_GUI_SETUP  5단 설정 — 버튼 GCS 화면의 기준값
%
%   4단(`A2_live_setup`) 과 무엇이 다른가
%     4단은 **미리 찍어 둔** 웨이포인트를 파일에서 읽어 임무를 짰다
%     5단은 **빈 임무로 출발**한다. 점은 창이 떠 있는 동안 지도를 눌러 넣는다
%
%   | 항목          | 4단                          | 5단                        |
%   |---------------|------------------------------|----------------------------|
%   | 웨이포인트    | `mission_points.mat` 에서    | 실행 중 클릭으로           |
%   | 배열 길이     | 점 개수에 맞춰 바뀜          | **고정 WP_MAX**            |
%   | 유효 개수     | 배열 길이가 곧 개수          | 스칼라 `n_wp` 가 따로 말함 |
%   | 정지          | AutoStop 이 자동으로         | 정지 버튼으로              |
%
%   >> A2_gui_setup
%
%   왜 고정 길이인가 — 실측으로 확인한 Simulink 의 제약
%     실행 중에 Constant 블록의 **값**은 바꿔 주지만 **배열 길이**는 바꿔 주지
%     않는다 (`Simulink:Parameters:InvParamSetting`). 그래서 자리를 WP_MAX 개
%     미리 잡아 두고, 그중 앞 `n_wp` 개만 유효하다고 모델에 알려 준다.
%     점을 하나 더 찍으면 배열 내용과 `n_wp` 가 바뀌고 길이는 그대로다

clear;  clc;

here = fileparts(mfilename('fullpath'));
w05  = fullfile(fileparts(here), 'W05_simulink');
if ~isfolder(w05)
    error('A2:now05', '5주차 폴더를 찾지 못했다 : %s', w05);
end
addpath(here);   addpath(w05);

%% ====================================================================
%  1. 제어·플랜트 설정 — 5주차 것을 그대로
% =====================================================================
fprintf('\n[1] 5주차 제어 설정을 가져온다 — %s\n', fullfile(w05, 'W05_setup.m'));
setappdata(0, 'W05_skip_run', true);
run(fullfile(w05, 'W05_setup.m'));

%% ====================================================================
%  2. 지리 설정 — 기준점·베이스맵
% =====================================================================
setappdata(0, 'A2_keep_vars', true);    % A2_setup 의 clear 를 막는다
setappdata(0, 'A2_skip_clc',  true);
A2_setup;
setappdata(0, 'A2_keep_vars', false);

%% ====================================================================
%  3. 임무 — 빈 자리만 잡아 둔다
% =====================================================================
WP_MAX = 10;                       % 한 임무에 찍을 수 있는 점의 최대 개수

wp_north = zeros(1, WP_MAX);       % 1번 칸 = 출발점 (0, 0)
wp_east  = zeros(1, WP_MAX);
n_wp     = 1;                      % 지금 유효한 점은 출발점 하나뿐

%  n_wp = 1 이면 갈 구간이 없다 -> 유도부가 gate = 0 을 내고 배는 제자리에 선다.
%  창의 '출발' 버튼은 점이 하나라도 찍히기 전에는 눌리지 않는다

%% ====================================================================
%  4. 실행 조건
% =====================================================================
%  초기 상태 — 기준점에서, 북쪽을 보고, 거의 정지
x0 = [0.1; 0; 0; 0; 0; 0];         % [u v r N E psi]'

%  실행 길이 — AutoStop 을 껐으므로 이 값이 유일한 상한이다.
%  무한대로 두지 않는다. 15 분이면 수업 한 번의 임무로 충분하다
T_run = 900;

%  지도 범위 — 클릭할 자리를 미리 넉넉히 본다 (A2_setup 의 기본값을 쓴다)
%  map_span_m 은 A2_setup 에서 300 m 로 들어왔다

%  실시간 화면
animate       = 1;
animate_every = 0.2;      % 몇 초마다 다시 그릴 것인가 [시뮬레이션 초]
boat_scale    = 6;        % 지도 위에서는 실제 크기(전장 4.9 m)가 점으로 보인다

%% ====================================================================
%  5. 확인 출력
% =====================================================================
fprintf('\n[3] 임무 — 빈 상태로 출발\n');
fprintf('  기준점 lla0 = [%.7f  %.7f  %.1f]\n', lla0);
fprintf('  웨이포인트 자리 = %d 개 (고정 길이),  지금 유효한 점 = %d 개 (출발점)\n', ...
        WP_MAX, n_wp);
fprintf('  T_run = %d s (상한),  R_LOS = %g m,  Delta = %g m,  유도 = %s\n', ...
        T_run, R_LOS, Delta, mode_name);
fprintf('  지도 범위 = 기준점 ±%d m,  베이스맵 = %s\n', map_span_m, basemap_name);
fprintf('\n5단 설정 완료 — 다음은 A2_5_gui_done\n');
