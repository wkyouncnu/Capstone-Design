function A2_ex1_wgs84()
%A2_EX1_WGS84  예제 1 — WGS84 타원체는 어떤 모양인가
%
%   입력 : 없음
%   출력 : 화면 출력만 (WGS84 정의 상수 4개와 거기서 유도되는 값)
%
%   >> A2_ex1_wgs84
%
%   무엇을 보는가
%     - 위도·경도·고도라는 말은 **어떤 모양의 지구**를 전제해야 뜻이 생긴다
%     - 그 모양을 정한 약속이 WGS84 다
%     - 이 함수는 그 약속의 숫자를 그대로 꺼내 지구가 얼마나 찌그러졌는지 잰다
%
%   왜 중요한가
%     lla2ned · ned2lla · GPS 수신기 · 구글 지도가 모두 이 한 벌의 상수를 쓴다.
%     다른 타원체(예: 한국 구 측지계 Bessel)를 섞으면 수백 m 가 어긋난다

    fprintf('\n=== 예제 1 · WGS84 타원체 ===\n');

    %% 정의 상수 — 이 두 개만 '정의'이고 나머지는 전부 유도값이다
    a = 6378137;                 % 긴반지름(적도 반지름) [m]  — 정의값
    f = 1/298.257223563;         % 편평률 flattening       — 정의값

    %% 유도값
    b   = a*(1 - f);             % 짧은반지름(극 반지름) [m]
    e2  = 2*f - f^2;             % 제1 이심률의 제곱 e^2
    e   = sqrt(e2);

    fprintf('\n[정의 상수]  이 두 개가 WGS84 가 정한 값이다\n');
    fprintf('  긴반지름  a = %.0f m        (적도 방향)\n', a);
    fprintf('  편평률    f = 1/%.9f\n', 1/f);

    fprintf('\n[유도값]  위 두 개에서 계산되는 값\n');
    fprintf('  짧은반지름 b = a(1-f)      = %.4f m\n', b);
    fprintf('  이심률제곱 e^2 = 2f - f^2  = %.12f\n', e2);
    fprintf('  이심률     e              = %.12f\n', e);
    fprintf('  적도-극 반지름 차 a - b    = %.1f m  (= %.1f km)\n', a-b, (a-b)/1000);
    fprintf('  찌그러진 비율 (a-b)/a      = %.5f  (= %.3f %%)\n', (a-b)/a, (a-b)/a*100);

    %% 얼마나 구에 가까운가 — 학생이 가장 많이 오해하는 지점
    fprintf('\n[읽는 법]\n');
    fprintf('  - 지구는 적도 쪽이 %.1f km 더 불룩한 타원체다\n', (a-b)/1000);
    fprintf('  - 그러나 반지름의 %.3f %% 에 불과하다. 그림으로 그리면 구와 구별되지 않는다\n', (a-b)/a*100);
    fprintf('    (지름 30 cm 지구본으로 깎으면 적도 지름과 극 지름의 차가 %.1f mm 다)\n', ...
            0.30*(a-b)/a*1000);
    fprintf('  - 그래도 무시하면 안 된다. 수평거리로 환산하면 수백 m 의 오차가 된다\n');

    %% 평균 반지름 — 1부의 곡률 식에 쓰는 R
    R_mean = (2*a + b)/3;
    fprintf('\n[참고] 산술평균 반지름 R = (2a+b)/3 = %.1f m\n', R_mean);
    fprintf('  곡률 때문에 떠오르는 양 L^2/(2R) 을 어림할 때 쓰는 값이다\n');

    fprintf('\n=== 예제 1 끝 ===\n');
end
