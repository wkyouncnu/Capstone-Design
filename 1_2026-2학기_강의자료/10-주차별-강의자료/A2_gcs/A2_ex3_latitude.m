function A2_ex3_latitude()
%A2_EX3_LATITUDE  예제 3 — 위도에는 두 가지가 있다 (측지위도 · 지심위도)
%
%   입력 : 없음
%   출력 : 화면 출력만 (위도 0~90 도에서 두 위도의 차이 표)
%
%   >> A2_ex3_latitude
%
%   무엇을 보는가
%     "위도" 라고 부르는 각이 **지구 중심에서 잰 각이 아니다**.
%     GPS 와 지도가 주는 위도는 타원체면에 세운 **법선**이 적도면과 이루는 각이다
%
%   | 이름 | 기호 | 어디서 잰 각인가 |
%   | 측지위도 geodetic  | lat   | 타원체면의 법선 - 적도면 |
%   | 지심위도 geocentric| lat_c | 중심에서 그 점을 본 선 - 적도면 |
%
%   관계식 (타원체면 위의 점, h = 0)
%     tan(lat_c) = (1 - e^2) tan(lat)
%
%   왜 중요한가
%     - 법선이 **지구 중심을 지나지 않는다**는 것이 NED 의 D 축을 정하는 근거다
%     - D 축은 "중심을 향하는 방향" 이 아니라 "타원체면의 법선 아래쪽" 이다

    f = 1/298.257223563;  e2 = 2*f - f^2;

    fprintf('\n=== 예제 3 · 측지위도와 지심위도 ===\n');
    fprintf('\n[입력]  위도 0 ~ 90 도를 훑는다 (타원체면 위, h = 0)\n');

    lat_list = [0 15 30 36.3719625 45 60 75 90];

    fprintf('\n[출력]\n');
    fprintf('  %12s  %14s  %12s  %12s\n', ...
            '측지위도[d]', '지심위도[d]', '차[deg]', '차[분]');
    for lat = lat_list
        lat_c = atand((1 - e2) * tand(lat));
        if lat == 90, lat_c = 90; end          % tand(90) = Inf 의 극한
        d = lat - lat_c;
        fprintf('  %12.7f  %14.7f  %12.6f  %12.3f\n', lat, lat_c, d, d*60);
    end

    %% 차이가 가장 큰 위도를 직접 찾는다
    g = 0:0.01:90;
    dd = g - atand((1 - e2)*tand(g));
    dd(end) = 0;
    [dmax, imax] = max(dd);

    fprintf('\n[읽는 법]\n');
    fprintf('  - 적도와 극에서는 두 위도가 같다 (차 = 0)\n');
    fprintf('  - 차이가 가장 큰 곳은 위도 %.1f 도이며 그때 %.4f 도 = %.2f 분이다\n', ...
            g(imax), dmax, dmax*60);
    fprintf('  - 각도로는 작아 보이나, 지심위도를 측지위도인 줄 알고 넣으면\n');
    fprintf('    남북으로 %.1f km 어긋난 자리를 가리킨다\n', deg2rad(dmax)*6371000/1000);
    fprintf('  - 그래서 "위도" 를 쓸 때 어느 쪽인지 섞으면 조용히 틀린다\n');
    fprintf('  - 본 과목이 쓰는 값(GPS · 구글 지도 · lla2ned)은 전부 **측지위도** 다\n');

    fprintf('\n[직접 해 볼 것]\n');
    fprintf('  1. e2 를 0 으로 바꾸면(완전한 구) 두 위도가 어떻게 되는가\n');
    fprintf('  2. 기준점 위도 36.37 도에서 차이는 몇 분인가 — 위 표에서 읽을 것\n');

    fprintf('\n=== 예제 3 끝 ===\n');
end
