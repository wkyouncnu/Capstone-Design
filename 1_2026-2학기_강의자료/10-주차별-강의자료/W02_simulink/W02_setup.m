% W02_SETUP  turtlesim 목표점 제어 실습 설정 — 이 파일만 고치면 된다.
%
%   모델을 열기 전에 반드시 이 스크립트를 먼저 실행한다.
%   Simulink 의 Constant 블록들이 여기서 만든 변수 이름을 그대로 참조한다.
%
%   >> W02_setup
%   >> open_system('W02_1_pose_sub')        % 1단계 — 자세 구독만
%   >> open_system('W02_2_goto_offline')    % 2단계 — 오프라인 거북이 (turtlesim 불필요)
%   >> open_system('W02_3_goto_turtlesim')  % 3단계 — 실제 turtlesim 제어
%
%   좌표계 — turtlesim 은 수학 좌표계를 쓴다 (선박 NED 가 아님)
%     x = 오른쪽(+),  y = 위쪽(+),  theta = +x 축 기준 반시계 방향(+) [rad]
%     화면 크기 약 11.09 x 11.09,  시작 위치 (5.544, 5.544),  theta = 0

clear; clc;

%% ====================================================================
%  1. ROS 2 연결 — WSL 쪽 값과 같아야 한다
%     WSL 터미널에서  echo $ROS_DOMAIN_ID  (비어 있으면 0)
% =====================================================================
ros_domain_id = '7';
setenv('ROS_DOMAIN_ID', ros_domain_id);

%% ====================================================================
%  2. 목표 자세 — 숫자만 바꾸면 된다
% =====================================================================
x_goal     = 9.0;          % 목표 x
y_goal     = 2.0;          % 목표 y
theta_goal = deg2rad(90);  % 목표 선수각 [rad]  (90 deg = 화면 위쪽)

%% ====================================================================
%  3. 도착 판정
% =====================================================================
tol_d  = 0.05;             % 위치 허용오차 — 이 안에 들어오면 선수각 맞추기로 전환
tol_th = deg2rad(1.0);     % 선수각 허용오차 — 이 안에 들어오면 정지

%% ====================================================================
%  4. 제어 게인
%     속도   v = min(Kv * 거리, v_max) * max(cos(선수각오차), 0)
%     선수각 w = sat(Kpsi * ssa(psi_ref - theta), w_max)
% =====================================================================
Kv    = 1.0;     % 속도 게인 [1/s]  — 거리 1 남으면 1 /s 로 접근
v_max = 2.0;     % 최대 전진 속도
Kpsi  = 4.0;     % 선수각 게인 [1/s]
w_max = 2.0;     % 최대 회전 속도 [rad/s]

%% ====================================================================
%  5. 샘플링 · 시뮬레이션
%     turtlesim 은 /turtle1/pose 를 약 62.5 Hz 로 낸다. 제어는 20 Hz 면 충분
% =====================================================================
Ts      = 0.05;            % 제어 주기 [s]
T_end   = 20;              % 시뮬레이션 시간 [s]
x0      = [5.544445; 5.544445; 0];   % 오프라인 초기 자세 = turtlesim 시작 자세

animate       = 1;         % 오프라인 실시간 그림  1 = 켜기, 0 = 끄기
animate_every = 0.2;       % 그림 갱신 간격 [s]

fprintf('W02_setup 완료 — 목표 (%.2f, %.2f, %.1f deg), ROS_DOMAIN_ID=%s\n', ...
        x_goal, y_goal, rad2deg(theta_goal), ros_domain_id);
