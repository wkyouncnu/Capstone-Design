% W03_SETUP  3주차 좌표계 실습 설정 — 이 파일만 고치면 된다.
%
%   모델을 열기 전에 반드시 이 스크립트를 먼저 실행한다.
%   Simulink 의 Constant 블록들이 여기서 만든 변수 이름을 그대로 참조한다.
%
%   >> W03_setup
%   >> open_system('W03_1_frame_check')   % 1단계 — 변환식 확인 (VRX 불필요)
%   >> open_system('W03_2_vrx_nav')       % 2단계 — GPS·IMU 를 NED 로 (VRX 필요)
%   >> open_system('W03_3_vrx_drive')     % 3단계 — 추력을 주고 부호를 확인 (VRX 필요)
%
%   좌표계 — 3주차 §1-5 와 같은 규약
%     ENU (ROS·Gazebo) : x=동, y=북, z=위,  각도는 동쪽 기준 반시계
%     NED (선박 제어)  : x=북, y=동, z=아래, 각도는 북쪽 기준 시계
%     psi_NED = pi/2 - yaw_ENU,   r_NED = -r_ENU

clear; clc;

%% ====================================================================
%  1. ROS 2 연결 — WSL 쪽 값과 같아야 한다
%     WSL 터미널에서  echo $ROS_DOMAIN_ID
% =====================================================================
ros_domain_id = '8';
setenv('ROS_DOMAIN_ID', ros_domain_id);

%% ====================================================================
%  2. 기준점 (LLA → NED 원점) — 3주차 §1-5 의 시드니 레가타 기준점
%     이 점을 원점으로 북쪽·동쪽 몇 m 인지 계산한다
% =====================================================================
lat0 = -33.72276870341191;    % 기준 위도 [deg]
lon0 = 150.67399057896623;    % 기준 경도 [deg]
alt0 =   1.183941401541233;   % 기준 고도 [m]

%% ====================================================================
%  3. 1단계(변환식 확인)에 넣을 값 — 4주차 §2-3 에서 실제로 받은 센서값
%     VRX 를 띄우지 않아도 변환식을 확인할 수 있다
% =====================================================================
lat_s = -33.72242651051122;   % GPS 실측 샘플
lon_s = 150.67398709806955;
alt_s =   1.2479525180533528;

qx_s = -0.002985170390113125; % IMU 실측 샘플 (ROS 순서: x, y, z, w)
qy_s =  0.0052473626483582015;
qz_s =  0.4794804920417796;
qw_s =  0.8775317724700065;

%% ====================================================================
%  4. 3단계 추력 시나리오 — 두 숫자가 배를 움직인다 (3주차 §2-6)
%     scenario 1 : 직진      좌 +200, 우 +200
%     scenario 2 : 좌선회    좌 -200, 우 +200
% =====================================================================
scenario = 1;

if scenario == 1
    thrust_left  =  200;   % [N]
    thrust_right =  200;
else
    thrust_left  = -200;
    thrust_right =  200;
end

%% ====================================================================
%  5. 샘플링 · 시뮬레이션
%     IMU 설계값 100 Hz, GPS 20 Hz. 제어·기록은 20 Hz 면 충분하다
% =====================================================================
Ts    = 0.05;      % [s]
T_end = 30;        % [s]

animate       = 1;
animate_every = 0.5;

%  4단계 버튼 조종 — 버튼 하나를 누를 때 나가는 추력 [N]
%  추진기 한 대의 한계가 250 N 이므로 그보다 낮게 잡는다. 전진과 선회를 함께
%  누르면 한쪽이 합쳐져 한계를 넘으므로, Mix 안에서 다시 한 번 자른다.
teleop_thrust = 200;

%  버튼으로 몰아 보려면 30 초는 짧다. 4단계를 돌릴 때만 길게 잡는다.
T_end_teleop = 300;   % [s]

fprintf(['W03_setup 완료 — 기준점 (%.6f, %.6f), 시나리오 %d ' ...
         '(좌 %+.0f N / 우 %+.0f N), ROS_DOMAIN_ID=%s\n'], ...
        lat0, lon0, scenario, thrust_left, thrust_right, ros_domain_id);
