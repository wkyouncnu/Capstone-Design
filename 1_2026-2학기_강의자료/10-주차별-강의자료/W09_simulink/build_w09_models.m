    for k = 1:numel(sig)
        yy = y + (k-1)*55;
        F(m, sig{k}, 'log', x, yy+3);
        b = [m '/log_' sig{k}];
        add_block('simulink/Sinks/To Workspace', b, ...
                  'Position', [x+130 yy x+230 yy+30]);
