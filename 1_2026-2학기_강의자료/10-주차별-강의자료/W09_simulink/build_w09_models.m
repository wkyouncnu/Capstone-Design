% =====================================================================
% 1단 · 유도 — 웨이포인트 관리 + LOS + 로이터 벡터필드
% =====================================================================
function addGuidance(m, x, y)

    % ---- 웨이포인트 관리 + LOS (7주차 유도를 확장한 것) ----
    add_block('simulink/User-Defined Functions/MATLAB Function', ...
              [m '/WpManager'], 'Position', [x y x+200 y+240]);
    setFcn(m, 'WpManager', [ ...
'function [psi_los, y_e, idx, at_loiter, at_end] = WpManager( ...'          newline ...
'         pn, pe, wp_n, wp_e, Delta, R, loiter_wp, mode, idx_prev)'         newline ...
'%#codegen'                                                                 newline ...
'% Waypoint bookkeeping plus LOS guidance (week 7).'                        newline ...
'%   idx = index of the leg START. The leg runs wp(idx) -> wp(idx+1).'      newline ...
'%   The index only advances while the mission is in waypoint mode,'        newline ...
'%   so a loiter never makes the boat skip a leg.'                          newline ...
''                                                                          newline ...
'n = numel(wp_n);'                                                          newline ...
'k = min(max(idx_prev, 1), n-1);'                                           newline ...
''                                                                          newline ...
'xk  = wp_n(k);    yk  = wp_e(k);'                                          newline ...
'xk1 = wp_n(k+1);  yk1 = wp_e(k+1);'                                        newline ...
''                                                                          newline ...
'pi_p = atan2(yk1 - yk, xk1 - xk);'                                         newline ...
'y_e  = -(pn - xk)*sin(pi_p) + (pe - yk)*cos(pi_p);'                        newline ...
'psi_los = pi_p - atan(y_e / Delta);'                                       newline ...
''                                                                          newline ...
'd_next  = sqrt((xk1 - pn)^2 + (yk1 - pe)^2);'                              newline ...
'reached = d_next <= R;'                                                    newline ...
''                                                                          newline ...
'% arriving at the loiter waypoint, and arriving at the last one'           newline ...
'if reached && ((k+1) == loiter_wp)'                                        newline ...
'    at_loiter = 1;'                                                        newline ...
'else'                                                                      newline ...
'    at_loiter = 0;'                                                        newline ...
'end'                                                                       newline ...
'if reached && (k == n-1)'                                                  newline ...
'    at_end = 1;'                                                           newline ...
'else'                                                                      newline ...
'    at_end = 0;'                                                           newline ...
'end'                                                                       newline ...
''                                                                          newline ...
'% advance only in waypoint mode'                                           newline ...
'if (mode < 1.5) && reached && (k < n-1)'                                   newline ...
'    idx = k + 1;'                                                          newline ...
'else'                                                                      newline ...
'    idx = k;'                                                              newline ...
'end']);

    add_block('simulink/Discrete/Unit Delay', [m '/IdxDly'], ...
              'Position', [x+60 y+290 x+135 y+325], ...
              'InitialCondition','1', 'SampleTime','Ts_ctrl');
    add_line(m,'WpManager/3','IdxDly/1','autorouting','on');
    add_line(m,'IdxDly/1','WpManager/9','autorouting','on');

    % ---- 로이터 벡터필드 (8주차 그대로) ----
    add_block('simulink/User-Defined Functions/MATLAB Function', ...
              [m '/LoiterVF'], 'Position', [x y+390 x+200 y+590]);
    setFcn(m, 'LoiterVF', [ ...
'function [psi_lo, r, theta] = LoiterVF(pn, pe, cn, ce, rd, vd, pc, beta, kcrab)' newline ...
'%#codegen'                                                                newline ...
'% Circular-orbit vector field guidance.'                                  newline ...
'%   Jung, Lim, Lee, Bang, "Unmanned Aircraft Vector Field Path Following' newline ...
'%   with Arrival Angle Control", eq. (9) and (13).'                       newline ...
'%   pc > 0 clockwise, pc < 0 counter-clockwise.'                          newline ...
''                                                                         newline ...
'dn = pn - cn;'                                                            newline ...
'de = pe - ce;'                                                            newline ...
'r     = sqrt(dn*dn + de*de);'                                             newline ...
'theta = atan2(de, dn);'                                                   newline ...
'if r < 1e-6, r = 1e-6; end'                                               newline ...
''                                                                         newline ...
'N = sqrt((r - rd)^2 + (pc*r)^2);'                                         newline ...
'if N < 1e-9, N = 1e-9; end'                                               newline ...
'r_dot   = -vd * (r - rd) / N;'                                            newline ...
'rth_dot =  vd * pc * r   / N;'                                            newline ...
''                                                                         newline ...
'vfN = r_dot*cos(theta) - rth_dot*sin(theta);'                             newline ...
'vfE = r_dot*sin(theta) + rth_dot*cos(theta);'                             newline ...
''                                                                         newline ...
'chi_d  = atan2(vfE, vfN);'                                                newline ...
'p      = chi_d - kcrab*beta;'                                             newline ...
'psi_lo = atan2(sin(p), cos(p));']);

    % ---- 회전수 (모드가 로이터일 때만 센다) ----
    add_block('simulink/User-Defined Functions/MATLAB Function', ...
              [m '/TurnCount'], 'Position', [x+300 y+640 x+500 y+850]);
    setFcn(m, 'TurnCount', [ ...
'function [turns, th_out, acc_out, armed] = TurnCount( ...'                newline ...
'         theta, r, rd, mode, th_prev, acc_prev, armed_prev)'              newline ...
'%#codegen'                                                                newline ...
'% Count laps, but only while the mission is loitering (mode 2).'          newline ...
'% Leaving loiter mode resets the counter, so a second loiter later'       newline ...
'% starts from zero again.'                                                newline ...
''                                                                         newline ...
'th_out = theta;'                                                          newline ...
''                                                                         newline ...
'if mode < 1.5 || mode > 2.5'                                              newline ...
'    turns = 0; acc_out = 0; armed = 0;'                                   newline ...
'    return'                                                               newline ...
'end'                                                                      newline ...
''                                                                         newline ...
'tol = 0.05*rd + 1;'                                                       newline ...
'if armed_prev < 0.5'                                                      newline ...
'    acc_out = 0;'                                                         newline ...
'    if abs(r - rd) <= tol'                                                newline ...
'        armed = 1;'                                                       newline ...
'    else'                                                                 newline ...
'        armed = 0;'                                                       newline ...
'    end'                                                                  newline ...
'else'                                                                     newline ...
'    armed = 1;'                                                           newline ...
'    d = theta - th_prev;'                                                 newline ...
'    d = atan2(sin(d), cos(d));'                                           newline ...
'    acc_out = acc_prev + d;'                                              newline ...
'end'                                                                      newline ...
'turns = abs(acc_out) / (2*pi);']);

    dn = {'ThDly','AccDly','ArmDly'};
    for k = 1:3
        add_block('simulink/Discrete/Unit Delay', [m '/' dn{k}], ...
                  'Position', [x+340 y+900+(k-1)*50 x+415 y+935+(k-1)*50], ...
                  'InitialCondition','0', 'SampleTime','Ts_ctrl');
    end
    add_line(m,'TurnCount/2','ThDly/1','autorouting','on');
    add_line(m,'TurnCount/3','AccDly/1','autorouting','on');
    add_line(m,'TurnCount/4','ArmDly/1','autorouting','on');
    add_line(m,'ThDly/1', 'TurnCount/5','autorouting','on');
    add_line(m,'AccDly/1','TurnCount/6','autorouting','on');
    add_line(m,'ArmDly/1','TurnCount/7','autorouting','on');
end

% =====================================================================
% 미션 상태기계 (Stateflow)
% =====================================================================
function addMissionFSM(m, x, y)
    add_block('sflib/Chart', [m '/MissionFSM'], 'Position', [x y x+220 y+180]);

    rt = sfroot;
    ch = rt.find('-isa','Stateflow.Chart','Path',[m '/MissionFSM']);
    ch.ActionLanguage = 'MATLAB';
    ch.ChartUpdate    = 'DISCRETE';
    ch.SampleTime     = 'Ts_ctrl';

    ins = {'at_loiter','turns','req_turns','at_end'};
    for k = 1:numel(ins)
        d = Stateflow.Data(ch);
        d.Name = ins{k}; d.Scope = 'Input'; d.Port = k;
    end
    o = Stateflow.Data(ch);
    o.Name = 'mode'; o.Scope = 'Output'; o.Port = 1;

    s1 = Stateflow.State(ch);
    s1.Name = 'WpFollow';
    s1.LabelString = ['WpFollow' newline 'en: mode = 1;'];
    s1.Position = [70 90 210 70];

    s2 = Stateflow.State(ch);
    s2.Name = 'Loiter';
    s2.LabelString = ['Loiter' newline 'en: mode = 2;'];
    s2.Position = [70 310 210 70];

    s3 = Stateflow.State(ch);
    s3.Name = 'Finish';
    s3.LabelString = ['Finish' newline 'en: mode = 3;'];
    s3.Position = [430 90 210 70];

    % 기본 전이
    td = Stateflow.Transition(ch);
    td.Destination = s1;
    td.DestinationOClock = 0;
    td.SourceEndPoint = [175 35];
    td.MidPoint       = [175 62];

    % WpFollow -> Loiter
    t1 = Stateflow.Transition(ch);
    t1.Source = s1;  t1.SourceOClock = 6;
    t1.Destination = s2;  t1.DestinationOClock = 0;
    t1.LabelString = '[at_loiter > 0.5]';
    t1.MidPoint = [120 240];

    % Loiter -> WpFollow
    t2 = Stateflow.Transition(ch);
    t2.Source = s2;  t2.SourceOClock = 3;
    t2.Destination = s1;  t2.DestinationOClock = 3;
    t2.LabelString = '[turns >= req_turns]';
    t2.MidPoint = [350 245];

    % WpFollow -> Finish
    t3 = Stateflow.Transition(ch);
    t3.Source = s1;  t3.SourceOClock = 3;
    t3.Destination = s3;  t3.DestinationOClock = 9;
    t3.LabelString = '[at_end > 0.5]';
    t3.MidPoint = [355 125];
end

