    note(m,'n1', ['W09 실습 C  —  VRX 연동' newline ...
        '유도·FSM·내부루프·추진기는 W09_0_offline 과 완전히 같다.' newline ...
        '운동모델만 Gazebo 로 바뀐다.' newline ...
