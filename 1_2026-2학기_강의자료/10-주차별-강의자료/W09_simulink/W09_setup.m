%  그래서 멀쩡히 지나간 주행에 "최소 여유 0.04 m" 라는 있지도 않은 충돌이
%  찍혔다 (같은 주행을 바로 재면 3.65 m 다). SDF 는 include 까지가 아니라
%  모델 안쪽까지 읽어야 참값이다 — 이것이 이 표를 만들 때의 두 번째 함정이다.
obs_x_n = obs_x_n + 3;      % 링크 오프셋 — 북쪽 3 m
obs_y_n = obs_y_n + 5;      % 링크 오프셋 — 동쪽 5 m

%  부딪히는 반경은 1.5 m 다 (collision 실린더). 눈에 보이는 기둥(visual)은
