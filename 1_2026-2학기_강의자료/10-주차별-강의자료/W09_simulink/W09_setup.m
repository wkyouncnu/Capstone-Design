half_beam = 1.027135;   % 선미 좌·우 추진기의 좌우 반폭 [m]
F_max     = 500;        % 선미 추진기 추력 포화 [N]

%  선수추진기 — 6주차 값을 그대로 가져왔다 (W06_setup.m 과 같은 숫자다).
%  이 주차의 가제보 모델이 6주차 선수추진기 배치를 그대로 쓰므로
