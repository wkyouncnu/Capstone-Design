%  위 표를 그림이 쓸 수 있게 숫자로 옮긴 것. W09_plot 이 궤적 위에 이 점들을
%  찍는다 — 회피가 돌 때 **무엇을 피하고 있었는가** 가 그림 한 장에서 읽힌다.
%  라이다가 실제로 본 것이 아니라 월드 SDF 에 적힌 자리다 (참값, 비교 기준).
obs_x_n = [  33  33  33  33  33  33  33  33  33  33  33  33  33 ...
