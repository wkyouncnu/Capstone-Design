%  3. 충돌회피 이음새 — 이 주차에만 있는 설정
%
%     파이썬 쪽(collision_avoidance_enu)이 두 토픽을 낸다
%       /vfh/command   geometry_msgs/Twist  — angular.z 가 회피 헤딩 [rad, ENU]
