%  1. 웨이포인트 — 출발점 기준 상대좌표 [m], NED
%     x = 북쪽(+), y = 동쪽(+)   (코드 이름 wp_north, wp_east, x_n, y_n)
%
%     **거의 정북 한 줄이다. 일부러 그렇게 두었다.** 다만 2·3번 웨이포인트를
%     서쪽으로 9 m 옮겨 두었다 — 옮긴 이유는 아래 "왜 서쪽 9 m 인가" 에 적었다.
%     1번은 **뜨는 자리 그대로 둔다**. 옮기면 배가 영영 출발하지 못한다 (아래).
%     LOS 는 장애물을 모른다. 알 필요도 없다 — 이 주차의 요점이 거기에 있다.
%     아래 월드 지도를 보면 이 한 줄이 어디서 막히는지 숫자로 읽힌다.
%
%     stationkeeping_task 의 장애물 배치 (월드 SDF 에서 읽은 값, 2026-10-27)
%     경로 원점(북 200, 동 -532) 기준 상대좌표로 환산했다. 아래 표의 x_n · y_n 은
%     링크 오프셋(북 3 · 동 5)을 **더하기 전** 의 include 자리다 — 더한 값이 참값이다
%
%       x_n(+3)  막는 것들의 y_n(+5)                 y_n = -9 선은?
%       -------  ---------------------------------   ------------------
%          36    -35..-23 벽 | +7..+19 벽            문 가운데 → 12.3 m 열렸다
%          48    -18, -3, +12                        -3 이 4.15 m → 간신히 열렸다
%          60    -28, -8, +12                        **-8 이 1.0 m → 막힌다**
%          72    -33, -8, +17                        **-8 이 1.0 m → 막힌다**
%          84    -18, -3, +12                        6 m 여유 → 열렸다
%          96    -23, -8, +7                         **-8 이 1.0 m → 막힌다**
%         133    부두(dock_2022) y_n=+7              마지막 웨이포인트 뒤
%
%     즉 경로선만 보면 **세 번 막힌다** (x_n = 60 · 72 · 96 의 가운데 부표).
%     그런데 2026-10-28 실측은 **다섯 번 켜지고 걸린 기둥은 네 곳**이었다 —
%     (48,-3) · (72,-8) 두 번 · (84,-3) · (96,-8). 거꾸로 (60,-8) 은 4.99 m
%     로 활짝 열린 채 지나갔다. 앞의 회피가 배를 서쪽으로 밀어 놓았기
%     때문이다. **경로선 기하는 예고일 뿐 판정이 아니다** — 판정은 그 순간의
%     선수각에서 뻗은 호 위에서 난다 (아래 3.93 m 설명).
%     막힌 자리만 파이썬이 조타를 잡고 나머지는 시뮬링크의 LOS 가 잡는다.
%     한 번 주행에 전환이 열 번 일어나므로 oa 신호를 그래프로 읽기에 좋다.
%
%     x_n = 36 의 벽은 가운데가 **넓게** 열려 있다 (y_n = -23..+7, 폭 30 m 짜리 문).
%     y_n = -9 선은 그 문의 가운데를 지난다 — 오른쪽 문설주까지 12.3 m 다.
%     **이 벽에서는 회피가 켜지지 않는 것이 맞다.** 늦게 본 것이 아니다.
%
%     왜 서쪽 9 m 인가 — 재 보고 두 번 옮겼다 (2026-10-27 → 2026-10-28)
%       (1) 처음에는 wp_east 를 0 으로 두었다. 그런데 150 초를 다 돌려 보니
%           **oa_flag 가 한 번도 서지 않았다.** 정북 선에서 가장 가까운 장애물이
%           (48,-3) · (84,-3) 으로 3 m 인데, 호를 지우는 중심거리는 3.93 m 다
%           (선체 반폭 1.23 + 안전여유 robot.safety_margin_m 1.20 + 장애물 1.5).
%           3 m 는 그보다 좁은데도 안 켜졌다 — 호가 **그 옆을 스쳐 지나가므로**
%           사각형이 걸리지 않았기 때문이다. 판정은 "지금 거리" 가 아니다.
%       (2) 그래서 동쪽 6 m 로 옮겼다. (96,+7) 이 1 m 로 들어와 **한 번** 막혔다.
%           한 번은 그래프로 읽기에 모자라다 — 전환이 두 번뿐이다.
%       (3) 서쪽 9 m 로 옮기면 (60,-8) · (72,-8) · (96,-8) 이 **셋 다 1.0 m** 로
%           들어온다. 그 다음으로 가까운 것이 (48,-3) 의 4.15 m 이므로
%           막히는 곳과 열린 곳이 깨끗하게 갈린다. 문도 12.3 m 로 활짝 열려
%           "벽에서는 왜 안 켜지는가" 를 설명하기에도 좋다.
%
%     **숫자가 3.93 m 보다 좁아야, 그리고 호 위에서 좁아야 막힌다.**
%     판정 기준은 지금 거리가 아니라 3 초(4.5 m) 뒤까지 끌고 간 선체 사각형이다
%     (회피기 arc_collides → footprint_clearance). 강의노트 H-3 절에 라이다
%     원시 스캔 실측으로 확인한 것을 적어 두었다.
%
%     옮길 때 한 번 더 걸렸다 — 1번 웨이포인트는 건드리면 안 된다 (2026-10-27)
%       세 점을 다 옆으로 옮겼더니 배가 북쪽 32 m 쯤에서 제자리를 맴돌았다.
%       전환 판정이 sw_mode = 1 (경로 방향, d - x_e < R_LOS) 이기 때문이다.
%       1번 구간은 "뜨는 자리 → 1번 웨이포인트" 인데, 둘이 떨어져 있고 그
%       구간이 **옆쪽**을 향한다. 배는 북쪽으로 가므로 이 구간의 진행거리가
%       줄지 않는다 → 1번에서 영원히 전환되지 않고, 파이썬에 넘어가는 목표점도
%       **배 뒤쪽**에 머문다. 회피기는 뒤로 가려 하고 LOS 는 앞으로 가려 하니
%       oa_flag 가 70 % 구간에서 서 버렸다 — 회피처럼 보이지만 회피가 아니다.
%       1번을 (0, 0) 으로 되돌리면 1번 구간의 길이가 0 이라 즉시 전환된다.
%
%     표를 만들 때 한 번 틀렸던 것 (2026-10-27)
%       월드 SDF 를 <include> 로 훑으면 51 개가 나온다. 그 가운데 다섯은
%       `<!-- <include> ... -->` 안에 든 **주석**이다 — 월드에 없는 물체다.
%       주석을 지우지 않고 세었더니 정북 2~4 m 앞에 부표가 둘 더 있는 것으로
%       읽혀 "두 번 막힌다" 는 결론이 흔들렸다. 주석을 먼저 지우면 46 개,
%       경로 주변 42 개다 (아래 obs_x_n · obs_y_n). x_n = 105 · 117 줄은
%       주석 안에 들어 있어 **월드에 없다** — 그래서 위 표에도 없다.
%
% > [주의] 장애물 배치는 월드마다 다르다. 월드를 바꾸면 위 표를 다시 만들어야 한다.
%   만드는 방법은 강의노트 9주차 2-3 절에 적어 두었다 (월드 SDF 의 <include> 를 읽는다).
% =====================================================================
wp_north = [   0   60  125 ];   % 웨이포인트 x (북쪽) [m]
