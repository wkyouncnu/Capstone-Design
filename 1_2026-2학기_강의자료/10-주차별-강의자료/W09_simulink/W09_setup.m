% W09_SETUP  9주차 실습 설정 — 이 파일만 고치면 된다.
%
%   실행하면 오프라인 모델이 곧바로 돌고 그림이 나온다.
%
%   >> W09_setup
%
%   임무: 웨이포인트를 따라가다가 → 지정한 점에서 로이터링 → 다시 웨이포인트
%   이 전환을 Stateflow 미션 상태기계가 관리한다.
%
%   구조 참고
%     UGV_WpFollowingAndLoitering/MILS/UGV_Control_StateFlow_260529.slx

clear; clc;

%% ====================================================================
%  1. 웨이포인트 경로 — 출발점 기준 상대좌표 [m], NED
%
%     지그재그 경로다. 가운데 WP3 가 수역 안쪽에 있어서
%     그 주위를 도는 로이터 원이 육지에 걸리지 않는다.
%
% > [주의] 안전 수역 N in [-28, 60],  E in [-18, 100]
%   로이터 원이 이 범위를 벗어나면 VRX 에서 배가 육지에 얹힌다.
%   중심 (20, 55) 에 반경 18 이면 N in [2, 38], E in [37, 73] 이라 안전하다.
% =====================================================================
wp_north = [ -20   50   20   50  -20 ];
wp_east  = [  20   20   55   90   90 ];

Delta = 10;     % LOS lookahead distance [m]
R_LOS = 5;      % 웨이포인트 수락반경 [m]

%% ====================================================================
%  2. 로이터링 — 어느 웨이포인트에서, 어떻게 돌 것인가
% =====================================================================
loiter_wp     = 3;       % 몇 번째 웨이포인트에 도착하면 돌기 시작할 것인가
loiter_radius = 18;      % 로이터 반경 [m]
loiter_turns  = 2;       % 몇 바퀴 돌고 다시 출발할 것인가
p_c           = 0.313;   % > 0 시계방향,  < 0 반시계방향
crab_comp     = 1;       % 1 = 크랩각 보상 (8주차 참조)

u_ref = 1.5;             % 목표 속도 [m/s] — 두 모드 공통

%% ====================================================================
%  3. 제어 게인 — 7·8주차와 완전히 같다
% =====================================================================
Kp_psi = 400;   Kd_psi = 200;
Kp_u   = 300;   Ki_u   = 100;

half_beam = 1.027135;
F_max     = 500;


%% ====================================================================
%  4. 운동모델 계수 — Gazebo 와 같은 값
% =====================================================================
m_usv = 211;    Izz = 653;
Xu = 100;  Xuu = 150;
Yv = 100;  Yvv = 100;
Nr = 800;  Nrr = 800;

%% ====================================================================
%  5. 추진기 모델
% =====================================================================
k_prop = 1000 * 0.004422 * 0.2^4;
n_max  = sqrt(F_max / k_prop);
tau_n  = 0.30;

%% ====================================================================
%  6. 실시간 그림
% =====================================================================
animate       = 1;
animate_every = 0.25;
boat_scale    = 2;

%% ====================================================================
%  7. VRX 스폰 위치
% =====================================================================
origin_north =  200;
origin_east  = -532;

%% ====================================================================
%  8. 자동 계산 — 손대지 않아도 된다
% =====================================================================
Ts_ctrl = 0.05;

n_wp = numel(wp_north);
if loiter_wp < 2 || loiter_wp > n_wp
    error('loiter_wp 는 2 이상 %d 이하여야 합니다.', n_wp);
end

% 로이터 중심은 지정한 웨이포인트에 고정한다.
% 이렇게 두면 웨이포인트 인덱스가 지나가도 중심이 흔들리지 않는다.
loiter_cn = wp_north(loiter_wp);
loiter_ce = wp_east(loiter_wp);

psi_init = atan2(wp_east(1) - 0, wp_north(1) - 0);
x0 = [0.1; 0; 0; 0; 0; psi_init];

if p_c > 0, dir_name = '시계방향'; else, dir_name = '반시계방향'; end

fprintf('W09 설정 완료\n');
fprintf('  웨이포인트 %d개\n', n_wp);
fprintf('  WP%d 도착 시 로이터링 — 반경 %g m, %g 바퀴, %s\n', ...
        loiter_wp, loiter_radius, loiter_turns, dir_name);
fprintf('  로이터 중심 (N,E) = (%g, %g)\n', loiter_cn, loiter_ce);
fprintf('  목표 속도 %g m/s, 크랩 보상 %d\n', u_ref, crab_comp);

%% ====================================================================
%  9. 바로 실행
% =====================================================================
auto_run = 1;

skip_run = getappdata(0, 'W09_skip_run');
if isempty(skip_run), skip_run = false; end
setappdata(0, 'W09_skip_run', false);

if auto_run && ~skip_run
    fprintf('\n오프라인 모델 실행 중  (auto_run = 0 으로 두면 실행하지 않는다)\n');
    load_system('W09_0_offline');
    out = sim('W09_0_offline');
    W09_plot(out, sprintf('WP -> 로이터(WP%d, %g바퀴) -> WP', loiter_wp, loiter_turns));
end
