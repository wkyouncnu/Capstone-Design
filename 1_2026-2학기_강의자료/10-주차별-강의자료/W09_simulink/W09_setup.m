F_bow_max = 250;        % 선수추진기 추력 포화 [N]

%  배분식이 받는 상수 넷을 묶음 하나로 넘긴다 — 6주차와 같은 이유다.
%  상수 블록의 글이 블록보다 길면 도면에 -C- 로 접혀 값이 안 보인다.
%  이름이 값보다 짧아야 강의 그림에서 읽힌다
alloc_prm = [half_beam; l_bow; F_max; F_bow_max];

%  옆걸음 이득 [N/rad] — **회피할 때만** 켜진다
%      Y_cmd = K_sway * ssa(psi_ref - psi) * oa_flag
%  oa_flag 가 0 이면 Y_cmd = 0 이고 선수추진기 추력도 0 이다. 그 구간의
%  배분식은 5주차와 글자까지 같아진다 (아래 build_w09_models.m 의 addBowThrust).
%
%  값을 고른 근거 — 회피가 걸리는 순간의 헤딩 오차가 보통 20~40도다.
%  30도(0.524 rad) 에서 선수추진기 한계의 절반쯤 나오게 두었다
%      250 * 0.524 = 131 N   (한계 250 N 의 52 %)
%  더 키우면 옆으로는 빨리 가지만 경로 이탈 y_e 가 그만큼 커진다
K_sway = 250;

%% ====================================================================
%  5. 플랜트 계수 — 5주차와 같다 (오프라인 쌍둥이는 없지만 운동모델 계수를 쓰는
