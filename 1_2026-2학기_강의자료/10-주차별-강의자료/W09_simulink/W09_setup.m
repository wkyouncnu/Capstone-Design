% W09_SETUP  9주차 토픽 조사 실습 설정 — 이 파일만 고치면 된다.
%
%   모델을 열기 전에 반드시 이 스크립트를 먼저 실행한다.
%
%   >> W09_setup
%   >> S = W09_offline_run                 % 0단계 — 운동모델 + 센서 모델로 같은 것을 먼저 (VRX 불필요)
%   >> open_system('W09_1_sensor_rates')   % 1단계 — 센서 수신 주기를 Simulink 로 잰다 (VRX 필요)
%   >> open_system('W09_2_qos_test')       % 2단계 — QoS 를 어긋나게 해 본다 (VRX 불필요)
%
%   이 주차의 요점
%     - `ros2 topic hz` 는 벽시계 기준이다. RTF 가 낮으면 설계값보다 느리게 보인다 (§2-3-7)
%     - Simulink 도 같은 것을 센다. 두 값이 비슷해야 연동이 제대로 된 것이다
%     - QoS 가 어긋나면 토픽이 보여도 데이터가 오지 않는다 (2주차 §2-9)

clear; clc;

%% ====================================================================
%  1. ROS 2 연결 — WSL 쪽 값과 같아야 한다
% =====================================================================
ros_domain_id = '7';
setenv('ROS_DOMAIN_ID', ros_domain_id);

%% ====================================================================
%  2. 조사할 토픽 — 설계값은 9주차 §2-3-7 의 표
%     모델 안의 Subscribe 블록에도 같은 이름이 들어 있다.
%     토픽 이름을 바꾸려면 모델에서 블록을 더블클릭해 고친다
% =====================================================================
topic_gps  = '/wamv/sensors/gps/gps/fix';        % 설계 20 Hz
topic_imu  = '/wamv/sensors/imu/imu/data';       % 설계 100 Hz
topic_wind = '/vrx/debug/wind/speed';            % 설계 20 Hz

hz_design_gps  = 20;
hz_design_imu  = 100;
hz_design_wind = 20;

%% ====================================================================
%  3. 샘플링 · 시뮬레이션
%     IMU 100 Hz 를 세려면 모델이 그보다 빨라야 한다 -> 200 Hz (Ts = 0.005)
% =====================================================================
Ts    = 0.005;     % [s]  200 Hz
T_end = 20;        % [s]  측정 시간. 짧으면 주기가 흔들린다

%% ====================================================================
%  4. 2단계(QoS) 설정
%     2주차 qos_test_pub 은 BEST_EFFORT 로 발행한다
%       ros2 run usv_basics qos_test_pub
% =====================================================================
topic_qos = '/qos_topic';

%% ====================================================================
%  5. 0단계(센서 모델) 설정 — VRX 없이 GPS · IMU 를 흉내 낸다 (9주차 1-5 절)
%     운동방정식 계수는 3주차 1-8 절과 같다 (4~8주차 오프라인 모델도 같은 값)
% =====================================================================
m_usv = 211;   Izz = 653;
Xu = 100;  Xuu = 150;   Yv = 100;  Yvv = 100;   Nr = 800;  Nrr = 800;
half_beam = 1.027135;
x0_w04 = zeros(6,1);                 % [u v r N E psi] — 원점에서 북쪽을 보고 정지

thrust_left  = -200;                 % 제자리 좌선회 (3주차 3-4 의 scenario 2 와 같음)
thrust_right =  200;

%  GPS — wamv_gazebo.urdf.xacro 가 부르는 위치와 wamv_gps.xacro 의 update_rate
gps_x = -0.85;   gps_y = 0.0;        % 안테나 위치 [m] (선체 축 FRD, 9주차 1-3 표)
lat0  = -33.72276870341191;          % 기준점 — 3주차 W03_setup 과 같음
lon0  = 150.67399057896623;

%  IMU — wamv_imu.xacro 의 angular_velocity 잡음 (z 축)
imu_gyro_std  = 0.009;               % 백색잡음 표준편차 [rad/s]
imu_gyro_bias = 0.00075;             % 바이어스 평균 [rad/s]
imu_seed      = 1;                   % 잡음 난수 씨앗 — 같은 값이면 같은 결과

%% ====================================================================
%  6. 실시간 화면 (W09_animate.m) — 4주차 W04_setup.m 과 같은 규약
%
%     모델을 돌리는 동안 창 하나가 열려 **센서가 제대로 오고 있는가**를 그린다.
%       왼쪽    참값 항적 + GPS 위치 점 + 선체와 선수 방향
%       오른쪽  ① 수신 주기 (설계값 점선)  ② 자이로 r 대 참값 r
%               ③ GPS 가 있어야 할 자리에서 벗어난 양
%                  (오프라인 = 안테나 레버암, VRX = 평균에서의 흩어짐)
%
%     붙어 있는 모델
%       오프라인  W09_0_offline
%       VRX       W09_1_sensor_rates
%
%     느린 노트북이면 animate = 0 으로 끄거나 animate_every 를 키운다.
%
%     >> 수신 주기를 재는 실행에서는 화면을 끈다 <<
%     그리는 일이 **벽시계**를 먹어 2-8-1 의 실측 Hz 가 내려간다.
%     W09_rates_run 은 이 값을 스스로 0 으로 두었다가 끝나고 되돌린다.
% =====================================================================
animate       = 1;       % 1 = 켬, 0 = 끔
animate_every = 0.25;    % 몇 초마다 다시 그릴 것인가 [시뮬레이션 초]

fprintf(['W09_setup 완료 — Ts = %.3f s (%.0f Hz), 측정 %g초, ' ...
         'ROS_DOMAIN_ID=%s, animate=%g (매 %g초)\n'], ...
         Ts, 1/Ts, T_end, ros_domain_id, animate, animate_every);
