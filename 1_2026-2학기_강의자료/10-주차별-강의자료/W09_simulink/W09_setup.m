% W09_SETUP  9주차 실습 설정 — 이 파일만 고치면 된다.
%
%   모델을 열기 전에 반드시 이 스크립트를 먼저 실행한다.
%   Simulink 의 Constant 블록들이 여기서 만든 변수 이름을 그대로 참조한다.
%
%   >> W09_setup
%   >> W09_vrx_run          % Gazebo 를 먼저 띄워 둔 뒤
%
%   5주차와 다른 것은 **딱 두 가지**다.
%     (1) 유도 출력과 내부루프 사이에 AvoidSeam 이 끼어 있다 (회피 헤딩 전환)
%     (2) 목표점을 ROS 2 로 내보낸다 (GoalPublisher) — 파이썬이 그것을 보고 판단한다
%   헤딩 PD·속도 PI·추력배분은 5주차 블록 **그대로**다. 게인도 같은 값이다.
%
%   오프라인 쌍둥이는 없다. 장애물은 Gazebo 월드에만 있으므로 이 주차는 Gazebo 전용이다.

clear;
if ~isequal(getappdata(0, 'W09_skip_run'), true), clc; end

%% ====================================================================
%  1. 웨이포인트 — 출발점 기준 상대좌표 [m], NED
%     x = 북쪽(+), y = 동쪽(+)   (코드 이름 wp_north, wp_east, x_n, y_n)
%
%     **정북 한 줄이다. 일부러 그렇게 두었다.**
%     LOS 는 장애물을 모른다. 알 필요도 없다 — 이 주차의 요점이 거기에 있다.
%     아래 월드 지도를 보면 이 한 줄이 어디서 막히는지 숫자로 읽힌다.
%
%     stationkeeping_task 의 장애물 배치 (월드 SDF 에서 읽은 값, 2026-10-27)
%     경로 원점(북 200, 동 -532) 기준 상대좌표로 환산했다
%
%       x_n     막는 것들의 y_n                      정북(y_n=0) 선은?
%       ----    ---------------------------------    -----------------
%        33     -40..-28 벽 | +2..+14 벽            +2 가 2 m 앞 → 막힌다
%        45     -23, -8, +7                          7 m 여유 → 열렸다
%        57     -33, -13, +7                         열렸다
%        69     -38, -13, +12                        열렸다
%        81     -23, -8, +7                          열렸다
%        93     -28, -13, +2                         +2 가 2 m 앞 → 막힌다
%       105     -33, -8, +17                          열렸다
%       117     -43, -13, +17                         열렸다
%       130     부두(dock_2022) y_n=+2               마지막 웨이포인트 뒤
%
%     즉 **정확히 두 번 막힌다** (x_n = 33 의 벽, x_n = 93 의 슬라럼 한 줄).
%     막힌 두 번만 파이썬이 조타를 잡고, 나머지는 시뮬링크의 LOS 가 잡는다.
%     한 번 주행에 전환이 네 번 일어나므로 oa 신호를 그래프로 읽기에 좋다.
%
%     x_n = 33 의 벽은 가운데가 열려 있다 (y_n = -27..+1, 폭 28 m 짜리 문).
%     배는 그 문의 **오른쪽 끝에서 2 m** 떨어진 자리에서 뜬다. 문 안에 있는데도
%     정북으로 가면 오른쪽 문설주를 스친다 — 회피가 할 일이 바로 그것이다.
%
% > [주의] 장애물 배치는 월드마다 다르다. 월드를 바꾸면 위 표를 다시 만들어야 한다.
%   만드는 방법은 강의노트 9주차 2-3 절에 적어 두었다 (월드 SDF 의 <include> 를 읽는다).
% =====================================================================
wp_north = [   0   60  125 ];   % 웨이포인트 x (북쪽) [m]
wp_east  = [   0    0    0 ];   % 웨이포인트 y (동쪽) [m]

%% ====================================================================
%  2. 유도 설정 — 5주차와 같은 값
% =====================================================================
guidance_mode = 2;      % 1 = atan2 유도,  2 = LOS 유도
Delta         = 10;     % lookahead distance [m]  (LOS 만 사용)
R_LOS         = 5;      % 웨이포인트 수락반경 [m]
sw_mode       = 1;      % 전환 판정.  1 = 경로 방향 (d - x_e < R),  2 = 수락 원
u_ref         = 1.5;    % 목표 속도 [m/s]

%% ====================================================================
%  3. 충돌회피 이음새 — 이 주차에만 있는 설정
%
%     파이썬 쪽(collision_avoidance_enu)이 두 토픽을 낸다
%       /vfh/command   geometry_msgs/Twist  — angular.z 가 회피 헤딩 [rad, ENU]
%       /vfh/oa_flag   std_msgs/Bool        — 회피 중인가
%     시뮬링크는 oa_flag 가 true 인 동안만 그 헤딩을 쓰고, 아니면 LOS 를 쓴다.
%
%     oa_timeout 은 **파이썬이 죽었을 때를 받치는 값**이다.
%     마지막 /vfh/command 가 들어온 뒤 이 시간이 지나면 flag 가 true 로 남아
%     있어도 무시하고 LOS 로 돌아간다. 안 두면 파이썬 노드가 죽은 순간의 헤딩을
%     영원히 붙잡고 그대로 직진한다.
%
%     값은 파이썬 쪽 sensor_timeout_sec 과 같게 0.5 s 로 둔다. 라이다가 lite 판에서
%     9.96 Hz 로 들어오므로 0.5 s 는 열 번 중 다섯 번을 놓친 상태다 — 죽었다고 볼 만하다.
% =====================================================================
oa_timeout = 0.5;       % /vfh/command 를 몇 초 못 받으면 LOS 로 되돌릴 것인가 [s]

%% ====================================================================
%  4. 제어 게인 — 5주차에서 만든 값 그대로다. 손대지 않는다.
% =====================================================================
% 헤딩 제어 — P-D 요각속도 되먹임 (MSS 방식)
%   tau_N = Kp_psi * ssa(psi_ref - psi) - Kd_psi * r
Kp_psi = 400;   Kd_psi = 200;

% 속도 제어 — u (surge velocity) 되먹임 PI
Kp_u = 300;     Ki_u = 100;
Kb   = Ki_u / Kp_u;     % anti-windup 되감기 이득 [1/s]

half_beam = 1.027135;   % 후방 2추진기 좌우 반폭 [m]
F_max     = 500;        % 추력 포화 [N]

%% ====================================================================
%  5. 플랜트 계수 — 5주차와 같다 (오프라인 쌍둥이는 없지만 운동모델 계수를 쓰는
%     블록이 추력배분에 남아 있다)
% =====================================================================
m_usv  = 211;    Izz = 653;
Xu = 100;  Xuu = 150;
Yv = 100;  Yvv = 100;
Nr = 800;  Nrr = 800;

k_prop = 1000 * 0.004422 * 0.2^4;   % 0.0070752 [N/(rad/s)^2]
n_max  = sqrt(F_max / k_prop);
F_plugin_max = 2353.53383667818;    % [N] 플러그인 한계 (URDF 값 그대로)

%  조류 — 이 주차에서는 쓰지 않는다 (VRX 에 해류 플러그인이 없다)
current_speed     = 0.0;
current_direction = 0.0;

%% ====================================================================
%  6. 실시간 그림
%     배 궤적·장애물·헤딩 명령 넷을 극좌표로 보는 그림은 **파이썬 쪽**에 있다
%     (W09_vrx_lite/ca_viz.py). 시뮬링크는 자기가 아는 것만 그린다.
% =====================================================================
animate       = 0;      % VRX 주행에서는 꺼 둔다 — 파이썬 그림이 이미 돌고 있다
animate_every = 0.25;
boat_scale    = 3;

%% ====================================================================
%  7. VRX 스폰 위치와 경로 원점
%     stationkeeping_task 에서는 배가 동 -532, 북 200 에서 뜬다 (실측 2026-10-27).
%     아래 값은 기본값일 뿐이고 W09_vrx_run 이 ground truth 첫 샘플로 덮어쓴다.
%
%     경로 원점을 스폰 자리와 **같게** 둔 까닭
%       장애물 표(1절)가 이 원점 기준으로 만들어져 있다. 원점을 옮기면 표도 틀린다.
% =====================================================================
origin_north =  200;
origin_east  = -532;

path_north0 =  200;   % 경로 원점의 월드 좌표 (ENU y = NED 북쪽) [m]
path_east0  = -532;   % 경로 원점의 월드 좌표 (ENU x = NED 동쪽) [m]

%% ====================================================================
%  8. 자동 계산 — 손대지 않아도 된다
% =====================================================================
psi_init = atan2(wp_east(2)-wp_east(1), wp_north(2)-wp_north(1));
x0 = [0.1; 0; 0; 0; 0; psi_init];

Ts_ctrl = 0.05;                          % 제어 주기 [s]
beta_c  = deg2rad(current_direction);

usv_p = [m_usv; Izz; Xu; Xuu; Yv; Yvv; Nr; Nrr; half_beam];

if guidance_mode == 1
    mode_name = 'atan2';
else
    mode_name = 'LOS';
end

%% ====================================================================
%  9. 실행 길이와 자동 정지
%     125 m 를 1.5 m/s 로 가면 83 초다. 회피로 돌아가는 길이 더해지고 초기
%     선회(스폰 헤딩이 동쪽이라 90도 돌아야 한다)까지 보아 넉넉히 둔다.
% =====================================================================
T_run     = 400;    % 최대 실행 시간 [s] — AutoStop 이 안 걸릴 때를 받친다
stop_hold = 10;     % 임무가 끝난 뒤 더 도는 시간 [s]

%% ====================================================================
%  10. ROS 2 도메인 — WSL 의 ~/.bashrc 와 같아야 토픽이 보인다
% =====================================================================
ros_domain_id = '7';
setenv('ROS_DOMAIN_ID', ros_domain_id);

fprintf('W09 설정 완료 — 충돌회피 (시뮬링크 제어 + 파이썬 회피 판단)\n');
fprintf('  웨이포인트 %d개 정북 한 줄, 유도 = %s\n', numel(wp_north), mode_name);
fprintf('  Delta = %g m, R = %g m, u_ref = %g m/s\n', Delta, R_LOS, u_ref);
fprintf('  회피 이음새: oa_timeout = %g s\n', oa_timeout);
fprintf('  ROS_DOMAIN_ID = %s  (WSL 의 echo $ROS_DOMAIN_ID 와 같아야 함)\n', ros_domain_id);
fprintf('\n다음 순서로 돌린다 (WSL 터미널 둘, MATLAB 하나)\n');
fprintf('  터미널 1 :  cd ~/Capstone-Design/1_2026-2학기_강의자료/10-주차별-강의자료/W09_vrx_lite\n');
fprintf('              bash run_vrx_ca.sh\n');
fprintf('  터미널 2 :  bash run_ca_nodes.sh\n');
fprintf('  MATLAB   :  W09_vrx_run\n');
