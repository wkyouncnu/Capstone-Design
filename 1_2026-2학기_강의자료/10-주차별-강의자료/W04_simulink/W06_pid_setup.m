% W06_PID_SETUP  6주차 PID 입문 실습의 파라미터를 base workspace 에 올린다.
%
%   사용법
%     >> W06_pid_setup            % 기본값으로 되돌리기
%     >> Kp = 30;                 % 한 개만 바꿔 보기
%     >> sim('W06_P1_pid_step');  % 다시 실행
%
%   이 파일의 값이 세 모델(W06_P1/P2/P3)의 블록 안에 그대로 쓰인다.
%   블록을 열면 숫자가 아니라 변수 이름이 보이는 이유다.

% ---------------------------------------------------------------------
% 1) 예제 플랜트 — 질량-스프링-댐퍼 (P1, P2 가 함께 쓴다)
%
%        m x'' + b x' + k x = f          m = 1, b = 2, k = 2
%        G(s) = 1 / (s^2 + 2s + 2)
%
%    배가 아니다. PID 를 처음 보기 위한 "아주 순한 2차 시스템"이다.
%    극이 -1 +- 1j 라서 그냥 두면 살짝 출렁이다 멈춘다.
% ---------------------------------------------------------------------
plant_num = 1;
plant_den = [1 2 2];

% ---------------------------------------------------------------------
% 2) PID 게인 (P1)
%    Kp : 오차에 비례.        키우면 빨라지고, 너무 키우면 출렁인다
%    Ki : 오차를 시간에 걸쳐 쌓음. 남는 오차를 없앤다
%    Kd : 오차가 줄어드는 속도. 미리 브레이크를 밟는다
%    Nf : 미분 필터 계수.      클수록 순수 미분에 가깝다(= 잡음에 약하다)
% ---------------------------------------------------------------------
Kp = 10;
Ki = 0;
Kd = 0;
Nf = 20;

% ---------------------------------------------------------------------
% 3) 잡음과 포화가 있는 현실 모델 (P2)
% ---------------------------------------------------------------------
Kp2 = 10;        % P2 의 게인은 P1 과 따로 둔다
Ki2 = 8;
Kd2 = 4;
Nf2 = 20;

r_step    = 1;        % 목표값
u_max     = 2.5;      % 제어입력 한계 (액추에이터가 낼 수 있는 최대). 정상상태에 2 가 필요하다
noise_var = 1e-5;     % 센서 잡음 분산 (표준편차 약 0.003). 0 이면 잡음 없음
noise_ts  = 0.01;     % 잡음 갱신 주기 [s]
Kb        = 2;        % 안티와인드업 되감기 이득. 0 으로 두면 안티와인드업이 사라진다

% ---------------------------------------------------------------------
% 4) 오프라인 배 — 종방향(surge) 속도 제어 (P3)
%    계수는 6주차 W06_5_offline 과 같은 값, 즉 Gazebo VRX 플러그인 값이다.
% ---------------------------------------------------------------------
m_boat  = 211;        % 질량 [kg]
Xu      = 100;        % 선형 항력
Xuu     = 150;        % 2차 항력
tau_m   = 0.30;       % 모터 1차 지연 시상수 [s]
X_max   = 500;        % 전체 추력 한계 [N] (추진기 1개 250 N x 2)

Kp_u = 300;
Ki_u = 300;
Kd_u = 0;
Nf_u = 20;
Kb_u = 2;             % 배 쪽 되감기 이득. 0 이면 안티와인드업 없음

fprintf(['W06_pid_setup 완료.\n' ...
         '  플랜트  G(s) = 1/(s^2 + 2s + 2)\n' ...
         '  P1 게인  Kp=%g  Ki=%g  Kd=%g  Nf=%g\n' ...
         '  P2 게인  Kp2=%g Ki2=%g Kd2=%g Nf2=%g  (r_step=%g, u_max=%g, noise_var=%g)\n' ...
         '  P3 게인  Kp_u=%g Ki_u=%g Kd_u=%g      (X_max=%g N)\n'], ...
         Kp, Ki, Kd, Nf, Kp2, Ki2, Kd2, Nf2, r_step, u_max, noise_var, ...
         Kp_u, Ki_u, Kd_u, X_max);
