% W04_SETUP  4주차 실습이 쓰는 모든 파라미터를 base workspace 에 올린다.
%
%   사용법
%     >> W04_setup                 % 기본값으로 되돌리기
%     >> Kp = 30;                  % 한 개만 바꿔 보기
%     >> sim('W04_P1_pid_step');   % 다시 실행
%
%   이 파일의 값이 모델 블록 안에 **변수 이름 그대로** 들어 있다.
%   블록을 열었을 때 숫자가 아니라 Kp, Kp_u, Kp_psi 가 보이는 이유다.
%
%   한 곳에 모아 두는 이유
%     실험하다 값이 엉키면 이 한 줄이 전부 되돌린다. 그리고 오프라인 모델과
%     VRX 쌍둥이가 **같은 변수**를 읽으므로 게인이 저절로 함께 옮겨간다.
%
%   옛 이름 W04_pid_setup 도 그대로 쓸 수 있다 (이 파일을 부르는 껍데기다).

% =====================================================================
% 1) 예제 플랜트 — 질량-스프링-댐퍼 (P0, P1, P2 가 함께 쓴다)
%
%        m y'' + b y' + k y = f          m = 1, b = 2, k = 2
%        G(s) = 1 / (s^2 + 2s + 2)
%
%    배가 아니다. PID 를 처음 보기 위한 "아주 순한 2차 시스템"이다.
%    극이 -1 +- 1j 라서 그냥 두면 살짝 출렁이다 멈춘다.
% =====================================================================
plant_num = 1;
plant_den = [1 2 2];

msd_m = 1;            % 질량 [kg]        — W04_P0_plant 가 적분기로 조립할 때 쓴다
msd_b = 2;            % 감쇠 [N s/m]
msd_k = 2;            % 스프링 [N/m]
f_step = 1;           % P0 에 넣는 계단 힘 [N] (정상상태 y = f_step/k = 0.5 m)

% 표준 2차계 (W04_P0_second_order) — 위 플랜트와 같은 값이 기본이다
%   wn = sqrt(k/m) = 1.4142,  zeta = b/(2 sqrt(mk)) = 0.7071
zeta = 0.7071;        % 감쇠비.     0.2 면 많이 출렁, 1 이면 안 출렁
wn   = 1.4142;        % 고유진동수 [rad/s]. 크면 빠르다

% =====================================================================
% 2) PID 게인 (P1)
%    Kp : 오차에 비례.        키우면 빨라지고, 너무 키우면 출렁인다
%    Ki : 오차를 시간에 걸쳐 쌓음. 남는 오차를 없앤다
%    Kd : 오차가 줄어드는 속도. 미리 브레이크를 밟는다
%    Nf : 미분 필터 계수.      클수록 순수 미분에 가깝다(= 잡음에 약하다)
% =====================================================================
Kp = 10;
Ki = 0;
Kd = 0;
Nf = 20;

% =====================================================================
% 3) 잡음과 포화가 있는 현실 모델 (P2)
% =====================================================================
Kp2 = 10;        % P2 의 게인은 P1 과 따로 둔다
Ki2 = 8;
Kd2 = 4;
Nf2 = 20;

r_step    = 1;        % 목표값
u_max     = 2.5;      % 제어입력 한계 (액추에이터가 낼 수 있는 최대). 정상상태에 2 가 필요하다
noise_var = 1e-5;     % 센서 잡음 분산 (표준편차 약 0.003). 0 이면 잡음 없음
noise_ts  = 0.01;     % 잡음 갱신 주기 [s]
Kb        = 2;        % 안티와인드업 되감기 이득. 0 으로 두면 안티와인드업이 사라진다

% 목표값 평활 (미분 킥) — 계단 모서리에서 제어입력이 튀는 것을 보이는 스위치
ref_smooth = 0;       % 0 = 계단 그대로, 1 = 1/(T_ref s + 1) 로 부드럽게
T_ref      = 0.5;     % 목표값 평활 시상수 [s]

% =====================================================================
% 4) 오프라인 배 — 종방향(surge) 속도 제어 (P3)
%    계수는 3주차 1-8 절 · W04_5_offline 과 같은 값, 즉 Gazebo VRX 플러그인 값이다.
% =====================================================================
m_boat  = 211;        % 질량 [kg]
Xu      = 100;        % 선형 항력
Xuu     = 150;        % 2차 항력
tau_m   = 0.30;       % 모터 1차 지연 시상수 [s]
T_m     = tau_m;      % 같은 값의 문서 표기 (본문은 T_m 으로 적는다)
X_max   = 500;        % 전체 추력 한계 [N] (추진기 1개 250 N x 2)

Kp_u = 300;
Ki_u = 300;
Kd_u = 0;             % 속도축에서 D 는 해롭다. 0 에서 올려 보면 나빠진다
Nf_u = 20;
Kb_u = 2;             % 배 쪽 되감기 이득. 0 이면 안티와인드업 없음

% 개루프 스위치 — 제어기를 빼고 추력을 직접 준다
boat_open = 0;        % 0 = 제어기(폐루프), 1 = 계단 추력(개루프)
X_open    = 400;      % 개루프로 줄 추력 [N]. 손계산 u_ss = 1.333 m/s, T_u = 0.42 s

% 속도 명령 평활 — 미분 킥을 보이기 위한 스위치
u_smooth = 0;         % 0 = 계단 그대로, 1 = 1/(T_ref_u s + 1)
T_ref_u  = 2.0;       % 속도 명령 평활 시상수 [s]

% =====================================================================
% 5) 오프라인 배 — 요(yaw) 축 · 헤딩 제어 (W04_3_heading_offline, W04_6_wrap)
%    계수는 3주차 1-8 절과 같다. 어긋나면 3주차가 옳다.
% =====================================================================
Iz      = 653;        % 요 관성 [kg m^2]
Nr      = 800;        % 선형 요 감쇠
Nrr     = 800;        % 2차 요 감쇠
b_half  = 1.027135;   % 추진기까지의 반폭 [m]
F_max   = 250;        % 추진기 1개의 추력 한계 [N]

psi_ref_deg = 45;     % 목표 선수각 [deg]. 모델 안은 rad, 이 경계가 deg2rad 블록이다
X_head      = 300;    % 헤딩 실험에서 같이 주는 전진 추력 [N]

Kp_psi = 800;         % 요 모멘트 = Kp_psi * ssa(psi_ref - psi) + Ki_psi*적분 + Kd_psi * r
Kd_psi = -400;        % **음수가 맞다.** D 는 브레이크라 회전과 반대로 낸다
Ki_psi = 0;           % 기본 0 (PD). port_eff 실험에서 켠다
N_max  = 500;         % 요 모멘트 포화 [N m]

% 개루프 스위치 — 제어기를 빼고 모멘트를 직접 준다
head_open = 0;        % 0 = 제어기(폐루프), 1 = 계단 모멘트(개루프)
N_open    = 300;      % 개루프로 줄 요 모멘트 [N m]

% 한쪽 추진기를 약하게 — PD 가 남기는 정상상태 오차를 만든다
port_eff = 1.0;       % 좌현(FL) 추진기 효율. 0.7 이면 30 % 약하다

% =====================================================================
% 6) 선수각 +-180 deg 이음매 (W04_6_wrap)
% =====================================================================
use_ssa          = 1;       % 1 = ssa 로 최단 방향, 0 = 그냥 빼기 (먼 길로 돈다)
psi0_deg         = 170;     % 초기 선수각 [deg]
psi_ref_wrap_deg = -170;    % 목표 선수각 [deg]. 최단 거리는 20 deg 다

% =====================================================================
% 7) 저역통과 필터 (부록 A1 · W04_P4_lowpass)
%    G(s) = wc / (s + wc)
% =====================================================================
lp_wc      = 20;      % 차단 각주파수 [rad/s]
lp_w_sig   = 0.5;     % 신호 각주파수 [rad/s]  — 통과해야 하는 쪽
lp_w_noise = 40;      % 잡음 각주파수 [rad/s]  — 걸러야 하는 쪽
lp_A_sig   = 1.0;     % 신호 진폭
lp_A_noise = 0.3;     % 잡음 진폭

% =====================================================================
% 8) 실시간 화면 (W04_animate.m) — 3주차 W03_setup.m 과 같은 규약
%
%    모델을 돌리는 동안 창 하나가 열려 궤적과 **지령 대비 응답**을 그린다.
%    오프라인 모델과 VRX 쌍둥이가 같은 함수를 쓰므로 이 두 값이 양쪽에 함께 듣는다.
%
%    붙어 있는 모델
%      오프라인  W04_3_heading_offline · W04_4_inner_loop_offline · W04_5_offline
%      VRX       W04_1_straight · W04_2_turn · W04_3_heading · W04_4_inner_loop
%
%    느린 노트북이면 animate = 0 으로 끄거나 animate_every 를 키운다.
%    끄면 눈에 띄게 빨라진다 — 그림 그리는 일은 제어와 아무 상관이 없다.
% =====================================================================
animate       = 1;       % 1 = 켬, 0 = 끔
animate_every = 0.25;    % 몇 초마다 다시 그릴 것인가 [시뮬레이션 초]

fprintf(['W04_setup 완료.\n' ...
         '  플랜트  G(s) = 1/(s^2 + 2s + 2)   (zeta=%.4f  wn=%.4f)\n' ...
         '  P1 게인  Kp=%g  Ki=%g  Kd=%g  Nf=%g\n' ...
         '  P2 게인  Kp2=%g Ki2=%g Kd2=%g Nf2=%g  (r_step=%g, u_max=%g, noise_var=%g, ref_smooth=%g)\n' ...
         '  P3 게인  Kp_u=%g Ki_u=%g Kd_u=%g      (X_max=%g N, boat_open=%g, X_open=%g N)\n' ...
         '  헤딩     Kp_psi=%g Kd_psi=%g Ki_psi=%g (N_max=%g N m, head_open=%g, port_eff=%g)\n' ...
         '  랩       use_ssa=%g  %g deg -> %g deg\n' ...
         '  화면     animate=%g  animate_every=%g s  (끄려면 animate = 0)\n'], ...
         zeta, wn, Kp, Ki, Kd, Nf, Kp2, Ki2, Kd2, Nf2, r_step, u_max, noise_var, ref_smooth, ...
         Kp_u, Ki_u, Kd_u, X_max, boat_open, X_open, ...
         Kp_psi, Kd_psi, Ki_psi, N_max, head_open, port_eff, ...
         use_ssa, psi0_deg, psi_ref_wrap_deg, animate, animate_every);
